import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import path from "node:path";

// base — подкаталог репозитория на GitHub Pages (sailorstale.github.io/<repo>/).
// Только для прод-сборки; в dev остаётся "/". На Railway (корень домена + свой
// сервер) задаём BASE_PATH=/ — тогда ассеты грузятся от корня.
export default defineConfig(({ command }) => ({
  base:
    process.env.BASE_PATH ??
    (command === "build" ? "/inclusive-employment-prototype/" : "/"),
  plugins: [react()],
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "./src"),
    },
  },
  /*
    dev: /api проксируется на локальный сервер правок (server/index.js).
    Если сервер не запущен — фронт сам уходит в localStorage-режим.

    ИСКЛЮЧЕНИЕ — КОММЕНТАРИИ КЛИЕНТА (/api/review). Они идут на БОЕВОЙ сервер,
    а не на локальный. Комментарии пишет клиент у себя, и смысл они имеют только
    все вместе, в одном месте: работать локально с пустым списком, пока замечания
    лежат на боевом сайте, невозможно.

    Правило одно для чтения и для записи. Значит, отметка «применён», правка и
    удаление из локальной копии меняют ЖИВЫЕ данные, которые видит клиент. Это
    и есть цель — один список на всех, — но удалять чужой комментарий с локалхоста
    так же необратимо, как с боевого сайта.

    Порядок ключей важен: Vite берёт первое подходящее правило, поэтому более
    точное «/api/review» стоит выше общего «/api».

    Адрес можно переопределить переменной REVIEW_API — например, направить на
    локальный сервер, когда боевой недоступен или трогать его не хочется.

    Так же переопределяется и сервер правок — переменной EDITS_API. Это нужно,
    чтобы открыть страницу НА ДАННЫХ ДРУГОГО СТЕНДА и увидеть её глазами клиента:
    разметка живёт в данных, у каждого стенда они свои, и разойтись они могут
    незаметно. Писать при этом будем тоже туда — открывать боевой адрес стоит
    только для просмотра.
  */
  server: {
    proxy: {
      "/api/review": {
        target:
          process.env.REVIEW_API ??
          "https://inclusion-editor-production.up.railway.app",
        changeOrigin: true,
      },
      "/api": {
        target: process.env.EDITS_API ?? "http://localhost:8787",
        changeOrigin: true,
      },
    },
  },
}));
