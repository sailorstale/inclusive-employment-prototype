/*
  ЗАГОТОВЛЕННЫЕ ВАРИАНТЫ ПРАВОК ГРУЗЯТСЯ ПО ТРЕБОВАНИЮ.

  Разборы текстов (наши варианты для блоков) весят 3,4 мегабайта: 2,3 у реестра
  источника и 1,1 у реестра сайта. Нужны они ТОЛЬКО в режиме редактора, когда
  человек открыл блок и смотрит предложенные формулировки. Читателю сайта они не
  нужны ни разу, а грузились всем и всегда — это две трети всего кода страницы.

  Поэтому данные вынесены в отдельные куски сборки и подтягиваются, когда
  редактор впервые их спрашивает. Пока кусок едет, вариантов просто нет; как
  только приехал, подписчики перерисовываются и варианты появляются.

  Общий механизм на оба реестра: они одинаковые по устройству и отличаются
  только источником данных.
*/

export type Loader<T> = () => Promise<T>;

export type LazyIndex<T> = {
  /** Готовый индекс или undefined, если ещё не загрузили. */
  peek: () => T | null;
  /** Запустить загрузку (повторные вызовы бесплатны). */
  load: () => Promise<T>;
};

/** Индекс, который строится при первом запросе. */
export function lazyIndex<T>(build: Loader<T>): LazyIndex<T> {
  let value: T | null = null;
  let started: Promise<T> | null = null;

  const load = () =>
    (started ??= build().then((v) => {
      value = v;
      notify();
      return v;
    }));

  return { peek: () => value, load };
}

/*
  Подписка на «данные приехали». Реестров два, и каждый может приехать в свой
  момент, поэтому оповещаем всех подписчиков разом: перерисовка дешёвая, а
  разбираться, чей именно кусок приехал, незачем.
*/
const listeners = new Set<() => void>();

function notify() {
  for (const fn of listeners) fn();
}

export function onVariantsLoaded(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
