/*
  АДРЕС КОММЕНТАРИЯ. id устроен как «slug::адреса::uid», где адреса — один или
  несколько путей компонентов через плюс: одно замечание нередко относится к
  нескольким блокам подряд («вот эти три карточки надо объединить»).

  Отдельный файл без React — эти две функции нужны и панели, и самому
  инструменту, а держать их рядом с компонентом мешает горячей перезагрузке.
*/

/** Адреса блоков внутри id. */
export function pathsOf(id: string): string[] {
  const middle = id.split("::")[1] ?? "";
  return middle ? middle.split("+") : [];
}

/** id нового комментария к набору блоков. */
export function commentId(slug: string, paths: string[], uid: string): string {
  return `${slug}::${paths.join("+")}::${uid}`;
}
