/*
  ЖУРНАЛ РАЗБОРА ЗАМЕЧАНИЙ — что мы сделали по каждому замечанию клиента.

  Замечание и ответ на него живут в разных местах. Само замечание лежит в данных
  на боевом сервере: там его оставил клиент, и мы эти данные не трогаем. А ответ
  на замечание — это правка в коде, и записывать её надо рядом с ней, тем же
  коммитом.

  Отсюда правило: ЗАПИСЬ ПОЯВЛЯЕТСЯ ВМЕСТЕ С ПРАВКОЙ. Метка «сделано» в панели
  зажигается ровно тогда, когда правка выходит на боевой стенд, — раньше она
  соврала бы клиенту, что страница уже изменилась. Если запись откатить, метка
  погаснет вместе с ней.

  Что показывает панель (см. PageComments): подпись «сделано», строку «что
  сделали» и пару «было — стало». Пустое «стало» значит, что блок со страницы
  убран совсем, и панель говорит об этом прямо, вместо тревожного «блок не
  найден».

  Тексты пишем ДЛЯ ЧЕЛОВЕКА, а не для отчёта машины: клиент читает их в панели
  рядом со своим замечанием и должен понять, что произошло, не заглядывая в код.
*/

export type AppliedComment = {
  /** id замечания в панели: «страница::адреса::метка». */
  id: string;
  /** Что сделали — одной фразой. */
  what: string;
  /** Как было на странице до правки. */
  before: string;
  /*
    Как стало. Пусто — блока на странице больше нет: замечание просило убрать,
    и убрали.
  */
  after?: string;
  /** Когда внесли. Дата в формате ГГГГ-ММ-ДД. */
  date: string;
  /*
    ВТОРОЙ РАУНД. Клиент прочитал наш ответ, не согласился и написал реплику в
    ветку под замечанием — значит, по этому замечанию мы правим ещё раз, и на
    правку заводится ВТОРАЯ запись здесь, рядом с первой. Обе показываются в
    панели по порядку: клиент видит всю историю, а не только последний шаг.

    Здесь пишем, сколько реплик клиента эта запись отвечает. Первая запись поле
    не заполняет: до неё реплик не было, и это ноль. Вторая ставит `answers: 1` —
    «сделано в ответ на первую реплику». Так панель понимает, ответили мы уже
    клиенту или он ждёт: реплик в ветке больше, чем отвечено, — замечание снова
    в работе и горит как «новый раунд».
  */
  answers?: number;
};

