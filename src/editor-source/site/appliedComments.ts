/*
  Записей на одно замечание может быть НЕСКОЛЬКО — по одной на раунд правок.
  Порядок сохраняем такой же, как в списке выше: сверху первый раунд, под ним
  второй. Панель показывает их в этом же порядке.
*/
const BY_ID = new Map<string, AppliedComment[]>();
for (const rec of LOG) {
  const list = BY_ID.get(rec.id);
  if (list) list.push(rec);
  else BY_ID.set(rec.id, [rec]);
}

/** Все раунды разбора замечания по порядку. Пусто — замечание ещё в работе. */
export function appliedAllFor(id: string): AppliedComment[] {
  return BY_ID.get(id) ?? [];
}

/*
  Последний раунд разбора. Нет записи — замечание ещё в работе.

  Именно последний, а не первый: если по замечанию правили дважды, показывать
  надо то, как страница выглядит сейчас.
*/
export function appliedFor(id: string): AppliedComment | undefined {
  const list = BY_ID.get(id);
  return list ? list[list.length - 1] : undefined;
}

/*
  Ждёт ли замечание нашего ответа. Клиент написал реплику в ветку, а записи о
  правке под неё ещё нет — значит, начался новый раунд и за замечание снова
  надо браться.

  Считаем по числу реплик, а не по датам: правку нередко вносят в тот же день,
  когда клиент написал, и день в день даты не различают порядок событий.
*/
export function awaitingRound(id: string, replies: number): boolean {
  const list = BY_ID.get(id);
  const answered = list?.length ? list[list.length - 1].answers ?? 0 : 0;
  return replies > answered;
}
