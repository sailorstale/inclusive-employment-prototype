/*
  ВЫНЕСЕНО ИЗ КАРТОЧКИ ПО ЗАМЕЧАНИЮ КЛИЕНТА — блок остаётся на странице, но
  перестаёт быть частью карточки и читается обычным текстом под ней.

  Это сосед dropScaffold: там блок вообще не доезжает до страницы, здесь он
  доезжает, просто уже не внутри разметки. Механика тоже похожа — правим не
  источник, а то, что до страницы доходит.

  Директивы раскладки лежат в данных на сервере, и у боевого стенда они свои.
  Поправить их там значит поправить ровно один стенд, а на соседнем всё
  останется как было. Поэтому решение живёт здесь, в коде: оно уезжает вместе с
  правкой и работает везде одинаково.

  Абзац «Поэтому при трудоустройстве важно учитывать не только размер
  заработной платы…» на «Льготах сотрудников» — замечание Юли от 7 августа 2026
  («оформляем пример как везде»). Директива затянула его в карточку «Пример»
  вместе с расчётами, хотя это вывод для всей страницы, а не часть примера. На
  «Квотах и господдержке» такие же карточки кончаются самим примером, а выводы
  стоят снаружи, — теперь и здесь так же.

  Четыре абзаца в конце «Что говорят компании» на «Как устроен наём» — замечание
  Юли от 7 августа 2026: «выше отсутствуют 4 абзаца текста из гугдока». Разметка
  «тут три цитаты» захватила диапазон до конца раздела, и авторский вывод после
  речи спикеров уехал в речь последнего из них — Дениса Розы: раскладка отдаёт
  хвост группы последнему автору, сама эту границу она не найдёт.

  На экране абзацев не было видно совсем: карточка цитаты режет длинный текст до
  пяти строк и прячет остальное под «Далее». Клиент справедливо прочитала это
  как пропажу. Снимаем их с разметки — и они возвращаются обычным текстом под
  тремя цитатами, как в гугл-доке. Цитатам это ничем не грозит: у директивы
  остаются ровно те девять блоков, из которых три цитаты и собирались.

  Три блока в «Дополнительных форматах занятости» на «Форматах занятости» —
  замечание Мити от 11 августа 2026: «Убрать карточки, оставить текст. Это
  просто два предложения». Разметка «Три карточки» держала цепочку из девяти
  блоков; шесть первых сняты со страницы прошлым замечанием Юли, и оставшийся
  хвост из трёх блоков превратился в три синие карточки подряд — подводку, сам
  список из двух пунктов и вывод. Снимаем этот хвост с разметки, и раздел
  читается обычным текстом: абзац, список с маркерами, абзац.

  Вывод в конце примера на «Психологической поддержке» — замечание Мити от
  15 августа 2026: «Вынести из примера». Синяя карточка «Пример» держала пять
  блоков: заголовок, три абзаца про женщину 52 лет и вывод «Этот случай
  показывает…». Вывод относится не к самой истории, а ко всему разделу, и
  внутри карточки читался частью случая. Он хвостовой, поэтому карточка просто
  укорачивается до трёх абзацев, а вывод выходит наружу и подводит к
  следующему разделу.

  Адресуем блок его собственным id, а не текстом: id у блока стабильный, и
  правка формулировки в источнике не расклеит эту привязку.
*/
const OUT_OF_CARD = new Set<string>([
  "/source/m2::sohranyatsya-li-posobiya-i-lgoty-pri-trudoustroy::paragraph::139d97q",
  "/source/m2::dopolnitelnye-formaty-zanyatosti::paragraph::1geoicn",
  "/source/m2::dopolnitelnye-formaty-zanyatosti::list::voz3e6",
  "/source/m2::dopolnitelnye-formaty-zanyatosti::paragraph::b7q6j3",
  "/source/m4::chto-govorit-biznes::paragraph::12nw0je",
  "/source/m4::chto-govorit-biznes::paragraph::1l7bjxr",
  "/source/m4::chto-govorit-biznes::paragraph::186ccr1",
  "/source/m4::chto-govorit-biznes::paragraph::1fp0ol3",
  "/source/m6-2::psihologicheskaya-podderzhka-soiskatelya-s-inval::paragraph::lfmbtk",
]);

/*
  Снимаем блоки ТОЛЬКО С КОНЦА директивы. Директива адресуется непрерывной
  цепочкой блоков (см. placeDirectives), и выдерни мы блок из середины —
  цепочка перестала бы совпадать с источником, а разметка молча слетела бы со
  всего куска. Хвост же просто укорачивается, и оставшиеся блоки совпадают там
  же, где совпадали раньше.

  Директиву, от которой не осталось ни одного блока, возвращаем нетронутой:
  «карточка из ничего» — это не то, о чём просил клиент, и такой случай значит,
  что список выше собран неверно.
*/
export function cutFromCards(directives: Directive[]): Directive[] {
  return directives.map((d) => {
    let end = d.blocks.length;
    while (end > 0 && OUT_OF_CARD.has(d.blocks[end - 1].id)) end -= 1;
    if (end === d.blocks.length || end === 0) return d;
    return { ...d, blocks: d.blocks.slice(0, end) };
  });
}
