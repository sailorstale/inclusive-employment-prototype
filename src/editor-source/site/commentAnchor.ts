/*
  ПРИВЯЗКА КОММЕНТАРИЯ К БЛОКУ — и её починка.

  Адрес компонента («10.6.0») — это его МЕСТО в дереве страницы: третий узел
  внутри седьмого внутри одиннадцатого. Стоит перестроить раскладку — завернуть
  абзацы в карточку, поднять секцию уровнем выше, — и все адреса ниже съезжают.
  Комментарии, оставленные раньше, начинают показывать в пустоту.

  Так и вышло: после перестройки структуры на «Реалиях и мифах» из тридцати трёх
  замечаний потеряли свой блок двадцать девять.

  ЧИНИМ ПО ТЕКСТУ, а не переписыванием данных. У каждого замечания сохранён
  снимок текста блока (поле original, первые шестьдесят знаков). Если адрес
  больше не находится, ищем на странице блок с таким же началом текста. Данные
  клиента не трогаем: починка происходит при каждом показе и переживёт
  следующую перестройку тоже.

  Ищем ПО ОТРИСОВАННОЙ СТРАНИЦЕ, а не по дереву узлов. Всё, ради чего нужна
  привязка, — рамка, прокрутка, подсветка — живёт в разметке, и узел, которого
  в ней нет, бесполезен: у секций, например, своего адреса в разметке вовсе нет.

  Одинаковых начал на странице бывает много («Почему это важно» встречается
  шесть раз), поэтому из нескольких подходящих берём тот, чей адрес ближе к
  прежнему: перестройка обычно сдвигает блоки недалеко.
*/

/* Метки замен (приватная зона Юникода) в сравнении только мешают. */
const MARKS = /[\u{E000}-\u{F8FF}]/gu;

/*
  Сравниваем «на слух»: без служебных символов, без лишних пробелов, в нижнем
  регистре. Текст блока мог с тех пор слегка поправиться, и точного совпадения
  здесь требовать нельзя.
*/
const norm = (s: string) =>
  s.replace(MARKS, "").replace(/\s+/g, " ").toLowerCase().trim();

/*
  Снимок короче этого — не улика: по «Важно» или «Пример» подойдёт полстраницы,
  и починка привязала бы комментарий к случайному блоку.
*/
const MIN_SNIPPET = 12;

/** Насколько два адреса далеки друг от друга: сравниваем по сегментам. */
function distance(a: string, b: string): number {
  const x = a.split(".").map(Number);
  const y = b.split(".").map(Number);
  let d = 0;
  for (let i = 0; i < Math.max(x.length, y.length); i++)
    d += Math.abs((x[i] ?? 0) - (y[i] ?? 0)) * Math.pow(0.5, i);
  return d;
}

/**
 * Текущие адреса блоков комментария на отрисованной странице.
 *
 * Сохранённые адреса возвращаются как есть, если они ещё находятся. Иначе ищем
 * блок по снимку текста. Пустой ответ значит, что блок не нашёлся вовсе — его
 * переписали или убрали.
 */
export function resolveAnchor(
  host: HTMLElement,
  paths: string[],
  snapshot: string | null | undefined,
): string[] {
  const has = (p: string) => Boolean(host.querySelector(`[data-json-path="${CSS.escape(p)}"]`));
  const alive = paths.filter(has);
  if (alive.length === paths.length) return paths;

  const snap = norm(snapshot || "");
  if (snap.length < MIN_SNIPPET) return alive;

  const nodes: { path: string; text: string }[] = [];
  host.querySelectorAll<HTMLElement>("[data-json-path]").forEach((el) => {
    const t = norm(el.textContent || "");
    if (t) nodes.push({ path: el.getAttribute("data-json-path") || "", text: t });
  });

  // Снимок обрезан по шестидесяти знакам, поэтому сначала ищем по НАЧАЛУ текста.
  let hits = nodes.filter(
    (n) => n.text.startsWith(snap) || (n.text.length >= MIN_SNIPPET && snap.startsWith(n.text)),
  );

  /*
    Начало могло уехать: у карточек первые слова забирает заголовок, и абзац
    «Медицинский подход фокусируется на диагнозе» превращается в заголовок
    «Медицинский подход» и текст «фокусируется на диагнозе». Тогда ищем кусок
    снимка ВНУТРИ текста блока. Порог длиннее, чем в первом проходе: короткий
    кусок встретится где угодно.
  */
  if (!hits.length) {
    const part = snap.slice(0, 40);
    if (part.length >= 20) hits = nodes.filter((n) => n.text.includes(part));
    if (!hits.length) {
      const tail = snap.slice(-40);
      if (tail.length >= 20) hits = nodes.filter((n) => n.text.includes(tail));
    }
  }
  if (!hits.length) return alive;

  /*
    Из подходящих берём ближайший к прежнему адресу, а из равных по расстоянию —
    самый КОРОТКИЙ по тексту: у вложенных блоков текст родителя начинается с
    текста ребёнка, и без этого рамка охватывала бы целый раздел вместо абзаца.
  */
  const from = paths[0];
  const best = hits.slice().sort((a, b) => {
    const d = distance(a.path, from) - distance(b.path, from);
    return d !== 0 ? d : a.text.length - b.text.length;
  })[0];
  return [best.path];
}
