import { stripMarks } from "@/editor-source/richText";

/*
  ПРИВЯЗКА КОММЕНТАРИЯ К БЛОКУ.

  Адрес компонента («10.6.0») — это его МЕСТО в дереве страницы: третий узел
  внутри седьмого внутри одиннадцатого. Стоит перестроить раскладку — завернуть
  абзацы в карточку, поднять секцию уровнем выше, — и все адреса ниже съезжают.

  ГЛАВНОЕ ПРАВИЛО: адресу самому по себе НЕ ВЕРИМ. После перестройки он почти
  всегда куда-нибудь да ведёт — просто не туда. Замечание про социальный подход
  показывало на список причин не раскрывать инвалидность, и со стороны это
  выглядит так, будто клиент написал ерунду. Молчаливая ошибка хуже пропажи.

  Поэтому опорой служит СНИМОК ТЕКСТА блока (поле original, первые шестьдесят
  знаков), который сохраняется вместе с замечанием. Ищем на странице блок с этим
  текстом; сохранённый адрес нужен только чтобы выбрать между одинаковыми.
  Не нашли — честно отвечаем «не нашли», а не показываем на случайный блок.

  Данные клиента при этом не трогаем: поиск идёт при каждом показе и переживёт
  следующую перестройку тоже.
*/

/*
  Сравниваем «на слух»: без разметки замен, без лишних пробелов, в нижнем
  регистре. Текст блока мог с тех пор слегка поправиться, и точного совпадения
  здесь требовать нельзя.

  МЕТКИ ЗАМЕН СНИМАЕМ ПРАВИЛЬНО — через stripMarks, а не просто выбрасывая
  служебные символы. Замена хранит ОБА варианта, нынешний и прежний; если
  выкинуть только сами метки, они склеятся: «Этот сайт подготовилиЭтот гид
  подготовили эксперты». Такой снимок не совпадал ни с одним блоком, и
  замечание объявлялось потерянным, хотя блок был на виду.
*/
const norm = (s: string) =>
  stripMarks(s)
    /*
      Маркеры списка выбрасываем. В снимке комментария их нет (он снят с текста
      узла), а на странице пункт рисуется с «•» впереди — из-за этого список
      «Зачем вам это нужно?» не совпадал сам с собой.
    */
    .replace(/[•·]/g, " ")
    .replace(/\s+/g, " ")
    .toLowerCase()
    .trim();

/*
  Снимок короче этого — не улика: по «Важно» или «Пример» подойдёт полстраницы,
  и привязка ушла бы к случайному блоку.
*/
const MIN_SNIPPET = 12;

/** Насколько два адреса далеки друг от друга: сравниваем по сегментам. */
function distance(a: string, b: string): number {
  const x = a.split(".").map(Number);
  const y = b.split(".").map(Number);
  let d = 0;
  for (let i = 0; i < Math.max(x.length, y.length); i++)
    d += Math.abs((x[i] ?? 0) - (y[i] ?? 0)) * Math.pow(0.5, i);
  return d;
}

/*
  Текст блока берём ВИДИМЫЙ (innerText), а не весь подряд: у заменённых слов
  рядом лежит скрытая подсказка «было: …», и в textContent она приклеивается
  к тексту, мешая сравнению.
*/
function collect(host: HTMLElement): { path: string; text: string }[] {
  const out: { path: string; text: string }[] = [];
  host.querySelectorAll<HTMLElement>("[data-json-path]").forEach((el) => {
    const t = norm(el.innerText || el.textContent || "");
    if (t) out.push({ path: el.getAttribute("data-json-path") || "", text: t });
  });
  return out;
}

/**
 * Адреса блоков комментария на отрисованной странице.
 *
 * Пустой ответ значит, что блок не нашёлся: текст переписали или блок убрали.
 * Такое замечание показываем в списке с пометкой, но рамку не рисуем — лучше
 * никакой, чем на чужом блоке.
 */
export function resolveAnchor(
  host: HTMLElement,
  paths: string[],
  snapshot: string | null | undefined,
): string[] {
  const snap = norm(snapshot || "");
  const nodes = collect(host);

  /*
    СОХРАНЁННЫЙ АДРЕС, ЕСЛИ ОН ПОДТВЕРЖДАЕТСЯ ТЕКСТОМ. После перепривязки
    (tools/comments-remap) адреса в записях верные, и искать заново незачем:
    поиск по тексту не различает одинаковые блоки, а адрес различает. Но верим
    ему только вместе с проверкой: блок на этом месте должен начинаться с того
    же текста, что записан в снимке.
  */
  const saved = paths.map((p) => nodes.find((n) => n.path === p));
  if (saved.every(Boolean)) {
    const first = saved[0]!.text;
    if (!snap || first.startsWith(snap.slice(0, 40)) || snap.startsWith(first.slice(0, 40)))
      return paths;
  }

  /*
    КОРОТКИЙ СНИМОК берём, только если он совпал РОВНО С ОДНИМ блоком. Длина
    сама по себе ничего не гарантирует: «Пример» встречается на странице
    десяток раз, а «1 степень» — один. Уникальность и есть доказательство.
  */
  if (snap.length < MIN_SNIPPET) {
    if (snap.length >= 4) {
      const only = nodes.filter((n) => n.text.startsWith(snap));
      if (only.length === 1) return [only[0].path];
    }
    // Опоры нет совсем — остаётся сохранённый адрес, если он ещё существует.
    return paths.filter((p) => nodes.some((n) => n.path === p));
  }

  // 1. Точное начало: снимок обрезан по шестидесяти знакам.
  let hits = nodes.filter(
    (n) => n.text.startsWith(snap) || (n.text.length >= MIN_SNIPPET && snap.startsWith(n.text)),
  );

  /*
    2. Начало могло уехать: у карточек первые слова забирает заголовок, и абзац
    «Медицинский подход фокусируется на диагнозе» превращается в заголовок
    «Медицинский подход» и текст «фокусируется на диагнозе». Тогда ищем кусок
    снимка ВНУТРИ текста блока. Порог длиннее, чем в первом проходе: короткий
    кусок встретится где угодно.
  */
  if (!hits.length) {
    const head = snap.slice(0, 40);
    if (head.length >= 20) hits = nodes.filter((n) => n.text.includes(head));
  }
  if (!hits.length) {
    const tail = snap.slice(-40);
    if (tail.length >= 20) hits = nodes.filter((n) => n.text.includes(tail));
  }
  if (!hits.length) return [];

  /*
    Из подходящих берём ближайший к прежнему адресу, а из равных по расстоянию —
    самый КОРОТКИЙ по тексту: у вложенных блоков текст родителя начинается с
    текста ребёнка, и без этого рамка охватывала бы целый раздел вместо абзаца.
  */
  const from = paths[0] ?? "0";
  const best = hits.slice().sort((a, b) => {
    const d = distance(a.path, from) - distance(b.path, from);
    return d !== 0 ? d : a.text.length - b.text.length;
  })[0];
  return [best.path];
}
