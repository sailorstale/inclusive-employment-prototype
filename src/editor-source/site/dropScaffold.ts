import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";

/*
  ЛЕСА КУРСА — блоки, которые на сайте лишние. Это не правка текста, а выбор
  того, что вообще попадает на страницу: то же самое делает pageMap, когда не
  берёт секции «Модуль N», «Введение» и «Заключение».

  Первый случай — приглашение оставить вопросы «в следующей редакции
  гида». В курсе оно закрывало каждый модуль, а на сайте под каждой страницей
  уже стоит настоящая форма мнения (узел Feedback), поэтому текст-приглашение
  дублирует её и обещает несуществующую редакцию.

  Формулировок в источнике много («Остались вопросы или пожелания?», «Есть
  идеи, как сделать гид лучше?»), и продолжение иногда лежит отдельным блоком
  («Оставьте их здесь. Мы учтём…»). Ловим и вопрос, и продолжение — по началу
  фразы, чтобы не зависеть от хвоста.

  Источник в левой колонке инструмента сверки этот фильтр не проходит: там
  страница остаётся дословной, и расхождение видно глазами.
*/
const SCAFFOLD = [
  /^\s*Остались\s+вопрос/iu,
  /^\s*Оставьте\s+их\s+здесь/iu,
  /^\s*Поделитесь\s+ими\s+с\s+нами/iu,
];

/*
  ЯРЛЫК «Обратная связь» — вторая разновидность лесов. В курсе он отделял разбор
  от задания, которое студент только что выполнил. На сайте задание не
  выполняют: разбор идёт сразу за списком критериев, и ярлык сообщает читателю
  ровно ничего.

  Снимаем ТОЛЬКО с неразмеченных блоков. В квизе эта же строка — служебный
  маркер: по ней раскладка понимает, где кончаются варианты ответа и начинается
  общий разбор (см. contentTree). Там блок всегда накрыт директивой, и трогать
  его нельзя — иначе квиз развалится.
*/
const FEEDBACK_LABEL = /^\s*обратная\s+связь\s*:?\s*$/iu;

/*
  СНЯТО ПО ЗАМЕЧАНИЮ КЛИЕНТА — блоки, которые убрали не потому, что они курсовые,
  а потому что клиент решил их не показывать. Механика та же (блок не доезжает до
  страницы), причина другая, поэтому список отдельный.

  Абзац про видео на странице «О проекте» — замечание Юли от 7 августа 2026.
  Ловим по началу фразы: дальше в нём стоит ссылка, а ссылки в источнике ещё
  правят, и привязываться к ним нельзя.

  Ярлык «Почему это важно» — замечание Юли от 7 августа 2026, повторённое у
  всех шести направлений в разделе «Как выстроить устойчивые процессы». Строка
  ничего не добавляет: абзац сразу под названием направления и так объясняет,
  зачем оно нужно. Соседние ярлыки («На что обратить внимание», «Как
  организовать процесс») остаются — они называют РАЗНЫЕ списки, а этот стоял
  над обычным абзацем.

  Совпадение точное, по всей строке: слова «почему это важно» встречаются и в
  обычных предложениях («Почему это важно и выгодно бизнесу?»), и такой абзац
  пропасть не должен.

  Заголовок «Важные нюансы» на «Договоре и оформлении» — замечание Юли от
  6 августа 2026, дважды подряд: сперва «убираем», потом уточнение «только
  заголовок». Вместе это значит одно: снимаем строку, а список из шести пунктов
  под ней остаётся на месте. Заголовок называл список тем же словом, каким он и
  так читается, — и заодно уводил в сторону подпись соседней таблицы, которая
  растёт из ближайшего заголовка сверху (см. captionFor в contentTree).

  Строка «О льготах для сотрудников с инвалидностью расскажем далее» — замечание
  Юли от 6 августа 2026. В курсе она вела читателя к следующему разделу модуля,
  а на сайте льготы живут отдельной страницей, и ссылка на неё уже стоит в меню
  слева и в «Читайте также».

  Подраздел «Когда может измениться заработная плата» на «Льготах сотрудников» —
  замечание Юли от 7 августа 2026, оставленное дважды: отдельно на заголовок и
  отдельно на единственный абзац под ним. Значит, снимаем оба блока, и подраздел
  уходит со страницы целиком. Абзац отвечал не на тот вопрос, который задаёт
  заголовок: он говорил, что зарплата меняется при изменении нормы рабочего
  времени, тогда как весь раздел выше объясняет обратное — при сокращённой
  неделе зарплата сохраняется. Заголовок в источнике уровня h3, поэтому его
  снятие ничего не разрезает: секции режутся по h2.

  Начало «Форматов занятости» — замечания Юли от 7 августа 2026. Она показала на
  строку «Причины могут быть разными» и на три карточки под ней («Экономический
  фактор», «Состояние здоровья», «Специфика профессии») и у каждой написала
  «убираем». Карточка — это заголовок вместе со своим абзацем, поэтому у каждой
  из трёх снимаем обе строки, а не одно название. Заголовки в источнике уровня
  h3, так что секции от их снятия не разрезаются.

  После этой правки раздел начинается так: «Официальное трудоустройство на
  полную ставку подходит не всем. Поэтому многие люди с инвалидностью выбирают
  другие форматы занятости:» — и дальше список форматов, ради которого страница
  и написана.

  Строка «О том, как рассчитывается совокупный доход, мы рассказывали ранее» —
  замечание оттуда же. Расчёт разобран на соседней странице «Льготы
  сотрудников», а слово «ранее» на сайте не значит ничего: свой порядок чтения
  читатель выбирает сам.

  Все эти формулировки встречаются в источнике по одному разу (проверено по всем
  модулям), поэтому совпадение по началу строки ничего лишнего не зацепит.
  Названия карточек короткие и могли бы попасться внутри обычного предложения,
  поэтому у них совпадение точное, по всей строке.
*/
const CUT_BY_CLIENT = [
  /^\s*О\s+том,\s+как\s+этот\s+подход\s+работает\s+на\s+практике/iu,
  /^\s*Почему\s+это\s+важно\s*:?\s*$/iu,
  /^\s*Важные\s+нюансы\s*:?\s*$/iu,
  /^\s*О\s+льготах\s+для\s+сотрудников\s+с\s+инвалидностью\s+расскажем\s+далее/iu,
  /^\s*Когда\s+может\s+измениться\s+заработная\s+плата\s*$/iu,
  /^\s*Заработная\s+плата\s+может\s+измениться\s+только\s+в\s+том\s+случае/iu,
  /^\s*Причины\s+могут\s+быть\s+разными/iu,
  /^\s*Экономический\s+фактор\s*$/iu,
  /^\s*При\s+невысокой\s+заработной\s+плате\s+совокупный\s+доход/iu,
  /^\s*Состояние\s+здоровья\s*$/iu,
  /^\s*Даже\s+сокращённая\s+35-часовая\s+рабочая\s+неделя/iu,
  /^\s*Специфика\s+профессии\s*$/iu,
  /^\s*В\s+некоторых\s+сферах\s+чаще\s+востребована\s+проектная\s+работа/iu,
  /^\s*О\s+том,\s+как\s+рассчитывается\s+совокупный\s+доход/iu,
];

/*
  Заголовок h2 не выбрасываем, даже если он «Остались вопросы?»: по нему режется
  секция, и без него её содержимое слилось бы с предыдущей секцией и вылезло на
  чужую страницу. Такие секции и так не взяты в pageMap — они на сайт не идут.
*/
const isScaffold = (b: SourceBlock, directive?: Directive): boolean => {
  if (b.kind === "heading" && b.level === 2) return false;
  const text = (b as { text?: string }).text;
  if (typeof text !== "string") return false;
  if (SCAFFOLD.some((re) => re.test(text))) return true;
  if (CUT_BY_CLIENT.some((re) => re.test(text))) return true;
  return !directive && FEEDBACK_LABEL.test(text);
};

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

/*
  Директивы адресуются последовательностью блоков, поэтому раскладку считаем
  ДО чистки, а потом переносим её адреса на укороченные секции. Иначе директива
  «Удалить», захватившая заодно и это приглашение (в М2 — вместе с пятью
  картинками), перестала бы совпадать, и удалённое вернулось бы на страницу.

  Секции не пропадают и не меняют порядок (h2 мы не трогаем), поэтому съезжает
  только номер блока внутри секции — его и пересчитываем.
*/
export function dropScaffold(
  sections: BlockSection[],
  at: DirectiveAt,
): { sections: BlockSection[]; directiveAt: DirectiveAt } {
  const kept = sections.map((sec, si) =>
    sec.blocks.flatMap((b, bi) => (isScaffold(b, at(si, bi)) ? [] : [bi])),
  );
  return {
    sections: sections.map((sec, si) => ({
      ...sec,
      blocks: kept[si].map((bi) => sec.blocks[bi]),
    })),
    directiveAt: (si, bi) => {
      const was = kept[si]?.[bi];
      return was === undefined ? undefined : at(si, was);
    },
  };
}
