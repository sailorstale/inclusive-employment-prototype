import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";

/*
  ЛЕСА КУРСА — блоки, которые на сайте лишние. Это не правка текста, а выбор
  того, что вообще попадает на страницу: то же самое делает pageMap, когда не
  берёт секции «Модуль N», «Введение» и «Заключение».

  Пока здесь один случай — приглашение оставить вопросы «в следующей редакции
  гида». В курсе оно закрывало каждый модуль, а на сайте под каждой страницей
  уже стоит настоящая форма мнения (узел Feedback), поэтому текст-приглашение
  дублирует её и обещает несуществующую редакцию.

  Формулировок в источнике много («Остались вопросы или пожелания?», «Есть
  идеи, как сделать гид лучше?»), и продолжение иногда лежит отдельным блоком
  («Оставьте их здесь. Мы учтём…»). Ловим и вопрос, и продолжение — по началу
  фразы, чтобы не зависеть от хвоста.

  Источник в левой колонке инструмента сверки этот фильтр не проходит: там
  страница остаётся дословной, и расхождение видно глазами.
*/
const SCAFFOLD = [
  /^\s*Остались\s+вопрос/iu,
  /^\s*Оставьте\s+их\s+здесь/iu,
  /^\s*Поделитесь\s+ими\s+с\s+нами/iu,
];

/*
  Заголовок h2 не выбрасываем, даже если он «Остались вопросы?»: по нему режется
  секция, и без него её содержимое слилось бы с предыдущей секцией и вылезло на
  чужую страницу. Такие секции и так не взяты в pageMap — они на сайт не идут.
*/
const isScaffold = (b: SourceBlock): boolean => {
  if (b.kind === "heading" && b.level === 2) return false;
  const text = (b as { text?: string }).text;
  return typeof text === "string" && SCAFFOLD.some((re) => re.test(text));
};

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

/*
  Директивы адресуются последовательностью блоков, поэтому раскладку считаем
  ДО чистки, а потом переносим её адреса на укороченные секции. Иначе директива
  «Удалить», захватившая заодно и это приглашение (в М2 — вместе с пятью
  картинками), перестала бы совпадать, и удалённое вернулось бы на страницу.

  Секции не пропадают и не меняют порядок (h2 мы не трогаем), поэтому съезжает
  только номер блока внутри секции — его и пересчитываем.
*/
export function dropScaffold(
  sections: BlockSection[],
  at: DirectiveAt,
): { sections: BlockSection[]; directiveAt: DirectiveAt } {
  const kept = sections.map((sec) =>
    sec.blocks.flatMap((b, bi) => (isScaffold(b) ? [] : [bi])),
  );
  return {
    sections: sections.map((sec, si) => ({
      ...sec,
      blocks: kept[si].map((bi) => sec.blocks[bi]),
    })),
    directiveAt: (si, bi) => {
      const was = kept[si]?.[bi];
      return was === undefined ? undefined : at(si, was);
    },
  };
}
