import type { Node, SectionNode } from "@/editor-source/source/contentTree";

/*
  СТРОКА-ВЕРДИКТ НАД РАЗБОРОМ КВИЗА — где её не показывать.

  После кнопки «Проверить» над разбором стоит слово: «Верно», «Частично верно»
  или «Неверно». Замечание Мити от 11 августа 2026 по четырём квизам «Этики и
  коммуникации»: «В этом квизе нет частично верных ответов… Убери заголовок у
  результата». Вариант там либо верный, либо нет, а «частично верно» загоралось,
  стоило отметить не все верные строки, и читалось как «ответ засчитан
  наполовину».

  ПОЧЕМУ ПО СТРАНИЦЕ, А НЕ ВЕЗДЕ. Убрать строку всюду значило бы решить за те
  страницы, про которые никто не писал. Поэтому список ведётся руками, и страница
  попадает в него только после просьбы. Ключ — адрес страницы, ровно как в
  раскладке квизов (quizzes.ts).

  ТРИ СТРАНИЦЫ ДОБАВЛЕНЫ 14 АВГУСТА 2026 по замечаниям клиента. На «Шаге 4»
  шесть замечаний, на «Шаге 5» восемь, на «Разговоре с работодателем» четыре, и
  все об одном: «убрать в результате слова „верно" и „неверно", тут в плашках
  квиза уже есть ответ». Плашка стоит у каждого выбранного варианта и говорит то
  же самое, поэтому строка над разбором повторяет её слово в слово.
*/
/*
  «ЛЬГОТЫ СОТРУДНИКОВ» ДОБАВЛЕНЫ 16 АВГУСТА 2026 — просьба Мити по снимку
  страницы: «в ответе уберём заголовок». Квиз на странице один, и разбор под ним
  начинался словами «Частично верно», хотя сразу над ним у каждого выбранного
  варианта уже стоит плашка с ответом. Читатель получал один и тот же вердикт
  дважды подряд.
*/
const NO_VERDICT = new Set<string>([
  "/general/team",
  "/general/benefits",
  "/companies/step-4",
  "/companies/step-5",
  "/ngo/talks",
]);

/** Нужно ли прятать строку-вердикт на этой странице. */
export const hidesQuizVerdict = (slug: string): boolean => NO_VERDICT.has(slug);

/*
  Копии, а не правка на месте: узлы принадлежат общему дереву модуля, и одна и
  та же секция приезжает на страницу и в выгрузку. Правка на месте задела бы
  соседние страницы того же модуля.
*/
function mark<T extends Node | SectionNode>(node: T): T {
  const kids = (node as { children?: (Node | SectionNode)[] }).children;
  const next =
    (node as Node).component === "Quiz" ? { ...node, noVerdict: true } : node;
  return kids ? { ...next, children: kids.map(mark) } : next;
}

/** Разделы страницы, где у квизов снята строка-вердикт. Не та страница — как были. */
export function hideQuizVerdict<T extends Node | SectionNode>(
  nodes: T[],
  slug: string,
): T[] {
  return hidesQuizVerdict(slug) ? nodes.map(mark) : nodes;
}
