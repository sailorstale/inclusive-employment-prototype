import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";
import { blockRefId } from "@/editor-source/source/blockId";

/*
  НАЗВАНИЕ, СНЯТОЕ С КАРТОЧКИ ПО ЗАМЕЧАНИЮ КЛИЕНТА — карточка остаётся, но
  шапки над текстом у неё больше нет.

  Это пятый сосед в ряду: dropScaffold (блок не доезжает до страницы),
  cutFromCard (доезжает, но вне карточки), clientEdits (доезжает изменённым),
  importantCards (собирается в карточку). Здесь карточка и её блоки остаются как
  были — уходит только название.

  ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. Название карточка получает не из поля, а из пометки
  дизайнера: «Пример в заголовок» уносит слово из начала абзаца в шапку, «Добавь
  заголовок Важно» ставит шапку прямо. Пометки лежат в данных на сервере, и у
  боевого стенда они свои — поправить их там значит поправить ровно один стенд.
  Поэтому решение живёт в коде, как и у соседей.

  КАК СНИМАЕМ. Комментарий пометки режется на куски по знакам препинания, и
  выбрасываются те, где встречается корень «заголов» — именно их читают правила
  разбора названия (explicitTitle и labelToTitle в contentTree). Остальные
  указания дизайнера («не капсом», «убрать ссылку») остаются работать.

  ЧЕГО ЭТОТ СЛОЙ НЕ ДЕЛАЕТ. Название может вернуться другим путём: если абзац
  начинается жирным словом («**Пример.** Компания…») или весь состоит из
  служебного ярлыка, раскладка возьмёт название оттуда. Такой текст правится
  отдельно, в clientEdits.

  ВМЕСТЕ С НАЗВАНИЕМ УХОДЯТ ЖЁЛТЫЙ ФОН И КАРТИНКА. Проверено 11 августа 2026 на
  карточке «Важно» на «Этике и коммуникации»: карточка осталась на месте, но
  стала обычной — и фон, и картинку раскладка выдаёт по названию, другого входа
  у них нет (bgFor и cardArt в contentTree). Значит просьбу «убрать слово
  „Важно“ из шапки, а жёлтую карточку оставить» одним этим слоем не выполнить:
  фон придётся ставить отдельно, модификатором в пометке. Прежде чем это делать,
  спросите дизайнера — возможно, обычной карточки достаточно.
*/

/** Блоки, у чьей карточки название снимается. Ключ — адрес блока. */
const NO_TITLE = new Set<string>([
  // ── «Шаг 2. Аудит рабочей среды» ────────────────────────────────────────
  // ── «Шаг 3. Создание инклюзивной среды» ─────────────────────────────────
]);

/** Куски комментария, где говорится про заголовок. */
const ABOUT_TITLE = /заголов|заглав|заглов|загов/i;

/*
  Комментарий без указаний про заголовок. Режем по тем же границам, по которым
  его читает раскладка: перенос строки, точка, точка с запятой. Кусок с корнем
  «заголов» выбрасывается целиком — вырезать из него отдельные слова опасно,
  правила разбора смотрят на соседние слова.
*/
function withoutTitle(comment: string): string {
  return comment
    .split(/([.;\n])/)
    .reduce<string[]>((acc, part, i) => {
      if (i % 2 === 1) {
        if (acc.length) acc[acc.length - 1] += part;
        return acc;
      }
      if (!ABOUT_TITLE.test(part)) acc.push(part);
      return acc;
    }, [])
    .join("")
    .trim();
}

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

/*
  Подменяем не саму пометку, а ответ на вопрос «какая пометка накрывает этот
  блок». Так цепочка блоков в пометке остаётся нетронутой: тронь мы её, адреса
  перестали бы совпадать с источником и разметка слетела бы со всего куска.

  Изменённая пометка кешируется по своему id и отдаётся всем блокам группы одним
  и тем же объектом: раскладка склеивает подряд идущие блоки в одну карточку,
  пока у них совпадает id пометки, и две разные копии разорвали бы карточку
  надвое.

  Место в цепочке — рядом с importantCards, после правок по замечаниям: адреса
  блоков к этому моменту окончательные.
*/
export function dropCardTitles(
  sections: BlockSection[],
  pathname: string,
  at: DirectiveAt,
): DirectiveAt {
  if (!NO_TITLE.size) return at;

  const changed = new Map<string, Directive>();
  const hit = new Set<string>();

  sections.forEach((sec, si) => {
    sec.blocks.forEach((b, bi) => {
      if (!NO_TITLE.has(blockRefId(b, pathname, sec.anchor))) return;
      const dir = at(si, bi);
      if (!dir) return;
      hit.add(dir.id);
      if (!changed.has(dir.id))
        changed.set(dir.id, { ...dir, comment: withoutTitle(dir.comment ?? "") });
    });
  });

  return (si, bi) => {
    const dir = at(si, bi);
    if (!dir || !hit.has(dir.id)) return dir;
    return changed.get(dir.id) ?? dir;
  };
}
