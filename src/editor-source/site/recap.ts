/*
  ИТОГИ СТРАНИЦ — «Подведём итоги» в конце каждой содержательной страницы.

  Зачем свой текст, а не текст источника. В курсе итог подводил черту под целым
  МОДУЛЕМ: три-восемь абзацев прозы, в конце обещание «в следующем модуле
  разберём…». На сайте модуля нет, страница — часть модуля, а обещание вести
  некуда: внизу и так стоит «Читайте также». Плюс сплошную прозу в конце
  тридцатитысячной страницы читатель пролистывает.

  Поэтому формат один на всех страницах (решение дизайнера): одна вводная фраза
  + три-пять пунктов, каждый — законченное предложение. Ничего нового: только
  то, что уже сказано на этой странице. Клиентский текст не выброшен, он был
  сырьём — его формулировки узнаваемы в пунктах.

  Где итога нет и почему:
  - /companies и /ngo — это входы в трек, навигация, а не материал;
  - /general/legal — страница сама целиком является сводкой правового раздела;
  - /general/legal/status — три тысячи знаков, подводить черту не под чем.

  Клиентская секция «Подведём итоги» со страницы при этом УХОДИТ (см.
  pageStructure): её место занимает этот текст. Практическое задание, которое
  в шести местах приклеено к итогу внутри секции, сохраняется отдельным
  разделом — оно к итогу отношения не имеет.
*/

export type Recap = {
  /** Вводная фраза: о чём была страница и главный вывод. */
  lead: string;
  /** Три-пять пунктов, каждый — законченное предложение. */
  points: string[];
  /*
    Название и якорь для раздела, который останется от хвоста курсовой секции
    итогов. Нужно, только когда своего заголовка H2 у хвоста нет: в «Шаге 1»
    название задания стоит обычной строкой, а пять правил общения в «Команде»
    вовсе не имеют общего заголовка. В остальных случаях H2 делается из первого
    подзаголовка хвоста, и поле не нужно.
  */
  tail?: {
    title: string;
    anchor: string;
    /** С какого компонента начинается хвост, если это не подзаголовок H3. */
    from?: "Block" | "Video" | "Stack" | "General Card" | "Accordion";
  };
};

