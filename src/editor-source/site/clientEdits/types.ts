import type { SourceBlock } from "@/editor-source/content/source.generated";

/*
  ЧТО МОЖНО СДЕЛАТЬ С БЛОКОМ ПО ЗАМЕЧАНИЮ КЛИЕНТА — набор для одной страницы.

  Записи лежат по файлу на страницу (соседние файлы этой папки), а механика,
  которая их применяет, — одна на всех в index.ts. Разделение появилось
  11 августа 2026: пять сессий разбирали замечания по своим страницам
  одновременно и дописывали в одни и те же списки, из-за чего каждое слияние
  приходилось разбирать руками.

  Ключом везде взят ТЕКСТ БЛОКА В ИСТОЧНИКЕ ЦЕЛИКОМ, а не начало фразы: он же
  служит адресом блока (blockRefId), поэтому совпадение по всей строке
  промахнуться не может.
*/

/*
  Новый блок, которого в источнике нет. Опора — соседний блок по началу текста.

  У СПИСКА, ТАБЛИЦЫ И КАРТИНКИ СВОЕГО ТЕКСТА НЕТ, и по началу фразы их не найти.
  Для таких опор есть afterId: адрес блока («страница::раздел::вид::отпечаток»),
  тот же, что у rewriteById, и взять его удобно из карты блоков (/blocks).

  Понадобилось, чтобы дописать заключение в конец «О проекте»: раздел кончается
  четырьмя пунктами списка, и последний из них — единственная возможная опора.
*/
export type Insert = {
  after?: RegExp;
  before?: RegExp;
  /** Адрес блока-опоры. Вставка идёт сразу за ним. */
  afterId?: string;
  blocks: SourceBlock[];
};

/** Заголовок, в который превращается абзац. */
export type Retyped = {
  /*
    ПЯТЫЙ УРОВЕНЬ — для подзаголовков ВНУТРИ карточки. Там заголовок не должен
    спорить ни с названием карточки, ни с заголовком раздела, а четвёртый уровень
    для этого крупноват (замечания Мити от 11 августа 2026 по «Шагу 1»). Снимок
    источника знает только 2–4: в гугл-доке глубже не пишут, — поэтому уровень 5
    заводится здесь, а не в generated-файле.
  */
  level: 2 | 3 | 4 | 5;
  md: string;
  text: string;
  anchor: string;
};

export type PageEdits = {
  /** Адрес страницы. Механика его не читает — он для человека и для сообщений об ошибке. */
  page: string;

  /*
    ТЕКСТ ВНУТРИ ЯЧЕЙКИ ТАБЛИЦЫ. Обычная правка текста живёт в правках редактора
    (см. store.ts), но до ячеек они не достают: раскладка берёт ячейку напрямую,
    мимо резолвера правок (tableToText в contentTree).

    Сверка точная, по всей ячейке целиком. Пустая замена значит, что ячейка со
    страницы уходит совсем.
  */
  cells?: Record<string, string>;

  /*
    СТРОКА ТАБЛИЦЫ ЦЕЛИКОМ — когда ячейку не взять её собственным текстом.

    Так бывает с ПУСТОЙ ячейкой: пустой ключ совпал бы со всеми пустыми ячейками
    сайта разом, а их девять. Ключом здесь служит вся строка: ячейки соединены
    « | » и взяты по ИСХОДНОМУ тексту, до всех прочих правок. Значение — новая
    строка целиком, ячейка за ячейкой.

    Ячеек в новой строке должно быть столько же, сколько в старой. Строка другой
    длины сдвинула бы колонки, поэтому такая запись не применяется, а попадает в
    список конфликтов и видна на странице «Проверки».

    Порядок правил: сначала строка, потом обычные замены по тексту ячейки. Так
    ключ строки всегда считается по источнику и одно правило не подменяет
    другому адрес.
  */
  cellRows?: Record<string, string[]>;

  /*
    ТАБЛИЦА ПЕРЕСОБРАНА ЦЕЛИКОМ — другая шапка, другие строки, другое число
    колонок. Ключ — АДРЕС блока: своего текста у таблицы нет, а ячейки правятся
    соседними полями и число колонок менять не умеют.

    Понадобилось, чтобы четырёхколоночную таблицу превратить в карточки:
    раскладка делает карточки только из таблицы в две колонки, где строка
    становится карточкой (см. split в importantCards/types.ts). Сузить таблицу
    было нечем.

    ОСТОРОЖНО С АДРЕСОМ В КАРТОЧКАХ. Отпечаток таблицы считается по её ячейкам,
    а карточки собираются ПОСЛЕ правок, — значит в importantCards стоит адрес
    уже НОВОЙ таблицы, а здесь ключом служит адрес старой. Перепутать легко, а
    поломка тихая: карточки не соберутся, и на странице останется таблица.
  */
  retable?: Record<string, { header: string[]; rows: string[][] }>;

  /** ТЕКСТ БЛОКА ПЕРЕПИСАН: разметка (md) и чистый текст. Вид блока прежний. */
  rewrite?: Record<string, { md: string; text: string }>;

  /*
    ТО ЖЕ САМОЕ, НО ПО АДРЕСУ БЛОКА — когда его текст в источнике не один.

    Обычный rewrite ищет блок по тексту, и это работает, пока текст встречается
    один раз. Заголовок «Практическое задание для представителей НКО» стоит на
    пяти страницах НКО сразу, а ссылка на документ у каждой своя. Правка по
    тексту приклеила бы всем пяти документ одной страницы — и четырём из них
    кнопку «Открыть задание», которой у них нет вовсе.

    Ключ — адрес блока («страница::раздел::вид::отпечаток»), он же считается по
    тексту, но вместе с модулем и разделом, поэтому один. Взять его удобно из
    карты блоков (/blocks).

    ОСТОРОЖНО С ОТПЕЧАТКОМ. Он считается по ЧИСТОМУ тексту, а не по разметке.
    Меняете только разметку (например, адрес ссылки) — адрес блока прежний, всё
    сходится. Меняете и текст — отпечаток станет другим, и правка перестанет
    находить свой блок. Проверка `npm run check:review` про это скажет.
  */
  rewriteById?: Record<string, { md: string; text: string }>;

  /*
    ССЫЛКИ ИЗ БЛОКА СНЯТЫ. Ключ — текст блока в источнике целиком; слова
    остаются, ссылками быть перестают.

    Зачем отдельно от rewrite. Правка текста ложится на блок ДО резолвера, а
    резолвер поверх неё кладёт правку редактора, если она на этот блок есть, —
    и наша разметка проигрывает. Правки редактора лежат в данных, у каждого
    стенда свои, и на боевом в них своя ссылка на своих словах. Поэтому ссылку
    снимаем ПОСЛЕ резолвера: тогда результат один и тот же на любом стенде и с
    любой правкой редактора.

    Текст блока при этом не меняется, а значит не меняется и его адрес: правка
    редактора остаётся на месте и не отцепляется.
  */
  unlink?: string[];

  /*
    АБЗАЦ СТАЛ ЗАГОЛОВКОМ. Это не то же самое, что rewrite: там меняется текст, а
    вид блока остаётся прежним. Здесь меняется именно вид, и вместе с ним
    появляются уровень и якорь, без которых заголовок не попал бы ни в
    оглавление, ни в структуру документа.
  */
  retype?: Record<string, Retyped>;

  /*
    ЗАГОЛОВОК СТАЛ ОБЫЧНЫМ ТЕКСТОМ — зеркало retype. Здесь перечисляются тексты
    заголовков источника, которые доезжают до страницы простыми абзацами.

    Вместе с видом блока пропадает и якорь, а с ним строка уходит из оглавления
    справа: туда идут только заголовки, у которых якорь есть. Поэтому просьба
    «сделать обычным текстом» и просьба «убрать из меню» закрываются одной
    записью, а не двумя.

    Осторожно с тем, что собиралось ОТ этого заголовка: разделы страницы ищут
    свои границы по заголовкам (см. pageStructure), и снятый заголовок может
    молча увести за собой кусок страницы.
  */
  untype?: string[];

  /*
    РАЗМЕТКА, СНЯТАЯ С БЛОКА. Директива дизайнера сильнее источника: она решает,
    каким компонентом блок выйдет на страницу, и заголовок из источника легко
    становится обычным абзацем. Правкой текста это не отменить, сменой вида —
    тоже: блок и так уже заголовок, просто разметка его прячет. Снимаем разметку,
    и блок выходит таким, какой он в источнике.
  */
  noMarkup?: string[];

  /*
    ЖИРНЫМ ВНУТРИ ПУНКТА СПИСКА. Ключ — текст пункта в источнике целиком,
    значение — его разметка на странице. Меняется только разметка: сам текст
    остаётся прежним, поэтому адрес списка (он считается по текстам пунктов) не
    сдвигается и разметка с него не слетает.
  */
  listItemMd?: Record<string, string>;

  /*
    КЛЮЧИ, КОТОРЫЕ ПОПАДАЮТ В НЕСКОЛЬКО БЛОКОВ НАМЕРЕННО.

    Правка адресуется текстом блока, а ищется этот текст по всему сайту: строка,
    которая встречается дважды, будет исправлена в обоих местах. Обычно это
    ошибка, и сверка `npm run check:review` о ней говорит. Иногда — нет: в
    источнике попадаются одинаковые заголовки, и правка верна для каждого.

    Такой ключ перечисляется здесь, и тогда сверка про него молчит. Молчит она
    ровно до тех пор, пока текст правда повторяется: как только вхождение
    останется одно, пометка сама станет ошибкой и о ней скажут — чтобы разрешение
    не пережило причину, по которой его дали.
  */
  sameTextOk?: string[];

  /*
    НОВЫЕ БЛОКИ НА СТРАНИЦЕ. Опора — соседний блок, найденный по началу текста, а
    не по номеру: номера съезжают от любой правки выше по модулю.

    Ставить блок ВНУТРЬ цепочки, которую занимает директива, нельзя — цепочка
    перестанет быть непрерывной и разметка слетит со всего куска. Вставка должна
    стоять на границе.
  */
  inserts?: Insert[];
};
