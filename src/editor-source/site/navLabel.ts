import { sidebars } from "@/data/nav";
import { pageBySlug } from "./pageMap";

/*
  ПОДПИСЬ СТРАНИЦЫ В БОКОВОМ МЕНЮ — поле navTitle в выгрузке.

  Подпись намеренно отличается от заголовка страницы: пункт меню читается под
  заголовком своей группы, и повторять её слова незачем («Поиск» под
  «Работодателями» вместо «Поиска работодателей»). Догадаться об этом по одному
  только h1 разработчик не может, поэтому подпись едет отдельным полем.

  Считается из того же места, где меню и живёт (nav.ts), чтобы подпись в меню
  сайта и подпись в выгрузке не могли разъехаться.

  ЦЕЛИКОМ МЕНЮ В ВЫГРУЗКЕ БОЛЬШЕ НЕТ. До 17 августа 2026 рядом со страницами
  ехал блок menu — шапка, боковые меню разделов и колонки подвала. Разработчик
  попросил его убрать: меню, шапку и подвал он собирает в конструкторе руками, и
  данные для них из файла не берёт. Вместе с блоком из выгрузки ушли заголовки
  групп («Соискатели», «Работодатели») — страницами они не являются, и своего
  места в списке страниц у них нет.
*/
const NAV_LABELS = new Map<string, string>(
  Object.values(sidebars).flatMap((spec) =>
    spec.groups.flatMap((g) =>
      g.items.flatMap((item) => [
        [item.path, item.label] as [string, string],
        ...(item.children ?? []).map(
          (c) => [c.path, c.label] as [string, string],
        ),
      ]),
    ),
  ),
);

/*
  Подпись страницы для меню. Страницы вне бокового меню (заглушка «Для
  соискателей») подписи там не имеют — берём название страницы, оно всегда есть.
  Поле в выгрузке стоит у КАЖДОЙ страницы: поле, которого то нет, то есть,
  заставляет каждый раз проверять, не забыли ли мы его.
*/
export function navLabelFor(slug: string): string {
  return NAV_LABELS.get(slug) ?? pageBySlug(slug)?.title ?? "";
}
