import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";

/*
  ПРАВКИ ПО ЗАМЕЧАНИЯМ КЛИЕНТА, КОТОРЫЕ НЕ УМЕЩАЮТСЯ В «УБРАТЬ БЛОК».

  ИСТОЧНИК НЕ ТРОГАЕМ НИКОГДА. Левая колонка инструмента сверки показывает
  модуль дословно, и весь смысл инструмента в том, что расхождение с гугл-доком
  видно глазами. Правка в `content/source/*.generated.ts` это расхождение
  прячет: клиент открывает сверку и видит, будто в доке уже так и написано.

  Есть и вторая причина, техническая. Адрес блока — это отпечаток его текста
  (blockRefId), а разметка привязана к отпечатку точным совпадением
  (placeDirectives). Правка одной буквы в источнике меняет отпечаток, разметка
  молча отваливается, и на странице вместо карточек появляется сырой блок.
  Проверено 10 августа 2026 на таблице со степенями: она развалилась обратно в
  таблицу, и чинить пришлось запись в данных — своими руками и на каждом стенде
  отдельно.

  Поэтому правим не источник, а то, что доходит до страницы. Это сосед
  dropScaffold (там блок вовсе не доезжает) и cutFromCard (там блок доезжает, но
  уже не внутри карточки). Здесь — три оставшихся случая: заменить текст внутри
  ячейки таблицы, вставить новый блок и поставить заголовок перед группой.

  Работает ТОЛЬКО на сайте и в выгрузке — там же, где dropScaffold. Инструмент
  «Редактура источника» этот слой не проходит.
*/

/*
  ТЕКСТ ВНУТРИ ЯЧЕЙКИ ТАБЛИЦЫ. Обычная правка текста живёт в правках редактора
  (см. store.ts), но до ячеек они не достают: раскладка берёт ячейку напрямую,
  мимо резолвера правок (tableToText в contentTree). Поэтому такие замены
  перечислены здесь поимённо.

  Сверка точная, по всей ячейке целиком: «1 степень» — короткая строка, и
  вхождением она нашлась бы где угодно.

  Заголовки степеней — замечание Юли от 6 августа 2026, по одному на каждую из
  трёх карточек: степень должна называться так же, как она названа в самой ИПРА.

  Пустая замена значит, что ячейка со страницы уходит совсем. Так снята фраза
  «Конкретные примеры зависят от рекомендаций…» у третьей степени — замечание
  оттуда же. Вместе с ячейкой уходит и подзаголовок «Пример» над ней: раскладка
  пропускает пустую ячейку целиком. Это верно по смыслу — примеров у третьей
  степени в карточке не осталось, они идут ниже отдельными карточками.
*/
const CELL_TEXT: Record<string, string> = {
  "**1 степень**": "**1 степень ограничения способности к трудовой деятельности**",
  "**2 степень**": "**2 степень ограничения способности к трудовой деятельности**",
  "**3 степень**": "**3 степень ограничения способности к трудовой деятельности**",
  "Конкретные примеры зависят от рекомендаций, указанных в ИПРА — разберём их ниже.":
    "",
};

type Insert = {
  /** Блок-опора: ищем его по началу текста. */
  after?: RegExp;
  before?: RegExp;
  /** Что поставить рядом с ним. */
  blocks: SourceBlock[];
};

/*
  НОВЫЕ БЛОКИ НА СТРАНИЦЕ. Опора — соседний блок, найденный по началу текста, а
  не по номеру: номера съезжают от любой правки выше по модулю.

  Абзац про электронные справки МСЭ — замечание Юли от 6 августа 2026 («Добавить
  ниже текст»), она показала на последний абзац раздела «Справка об
  инвалидности». Текст взят её словами, без правок.

  Заголовок «Примеры» — решение дизайнера от 10 августа 2026 по её же замечанию.
  У первой и второй степени пример один, у третьей их несколько, и они собраны в
  раскрывающиеся карточки ниже. Карточки начинались без всякого названия, и
  замечание просило это название дать.
*/
const INSERTS: Insert[] = [
  {
    after: /^\s*Группа\s+инвалидности\s+даёт\s+лишь\s+общее\s+представление/iu,
    blocks: [
      {
        kind: "paragraph",
        md: "С 1 марта 2026 года справки МСЭ оформляют преимущественно в электронном виде и направляют в личный кабинет на Госуслугах. Бумажную справку выдают по заявлению гражданина или при невозможности отправить электронный документ. Электронная и бумажная версии имеют одинаковую юридическую силу.",
        text: "С 1 марта 2026 года справки МСЭ оформляют преимущественно в электронном виде и направляют в личный кабинет на Госуслугах. Бумажную справку выдают по заявлению гражданина или при невозможности отправить электронный документ. Электронная и бумажная версии имеют одинаковую юридическую силу.",
      },
    ],
  },
  {
    before: /^\s*Пример\s+1\.\s+Трудоустройство\s+контент-менеджера/iu,
    /*
      Якорь у заголовка свой, а не общий с разделом: общий достаётся ПЕРВОМУ
      заголовку секции, и заняв его, «Примеры» увели бы к себе ссылку на весь
      раздел про ИПРА.
    */
    blocks: [
      {
        kind: "heading",
        level: 3,
        md: "Примеры",
        text: "Примеры",
        anchor: "primery-stepeni-ogranicheniya",
      },
    ],
  },
];

/** Ячейки таблицы, переписанные по замечаниям. Не таблица — блок как был. */
function fixCells(b: SourceBlock): SourceBlock {
  if (b.kind !== "table") return b;
  let touched = false;
  const rows = b.rows.map((row) =>
    row.map((cell) => {
      const next = CELL_TEXT[cell.trim()];
      if (next === undefined) return cell;
      touched = true;
      return next;
    }),
  );
  return touched ? { ...b, rows } : b;
}

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

const textOf = (b: SourceBlock): string =>
  typeof (b as { text?: string }).text === "string"
    ? (b as { text: string }).text
    : "";

/*
  Вставленный блок разметки не имеет и иметь не может: разметка адресуется
  блоками источника, а этого блока в источнике нет. Поэтому вместе с блоками
  пересобираем и адресацию: для нового блока директивы нет, для старого она та
  же, что была до вставки.

  Ставить блок ВНУТРЬ цепочки, которую занимает директива, нельзя — цепочка
  перестанет быть непрерывной и разметка слетит со всего куска. Обе наши вставки
  стоят на границе: абзац про справки МСЭ — последним в разделе, заголовок
  «Примеры» — перед первой из карточек-примеров.
*/
export function applyClientEdits(
  sections: BlockSection[],
  at: DirectiveAt,
): { sections: BlockSection[]; directiveAt: DirectiveAt } {
  /** Для каждого нового номера блока — его прежний номер (или null у вставленных). */
  const origin: (number | null)[][] = [];

  const next = sections.map((sec, si) => {
    const blocks: SourceBlock[] = [];
    const from: (number | null)[] = [];
    sec.blocks.forEach((b, bi) => {
      const text = textOf(b);
      for (const ins of INSERTS)
        if (ins.before?.test(text))
          for (const nb of ins.blocks) {
            blocks.push(nb);
            from.push(null);
          }
      blocks.push(fixCells(b));
      from.push(bi);
      for (const ins of INSERTS)
        if (ins.after?.test(text))
          for (const nb of ins.blocks) {
            blocks.push(nb);
            from.push(null);
          }
    });
    origin[si] = from;
    return { ...sec, blocks };
  });

  return {
    sections: next,
    directiveAt: (si, bi) => {
      const was = origin[si]?.[bi];
      return was === null || was === undefined ? undefined : at(si, was);
    },
  };
}
