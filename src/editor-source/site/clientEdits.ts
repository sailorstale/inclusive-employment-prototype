import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";

/*
  ПРАВКИ ПО ЗАМЕЧАНИЯМ КЛИЕНТА, КОТОРЫЕ НЕ УМЕЩАЮТСЯ В «УБРАТЬ БЛОК».

  ИСТОЧНИК НЕ ТРОГАЕМ НИКОГДА. Левая колонка инструмента сверки показывает
  модуль дословно, и весь смысл инструмента в том, что расхождение с гугл-доком
  видно глазами. Правка в `content/source/*.generated.ts` это расхождение
  прячет: клиент открывает сверку и видит, будто в доке уже так и написано.

  Есть и вторая причина, техническая. Адрес блока — это отпечаток его текста
  (blockRefId), а разметка привязана к отпечатку точным совпадением
  (placeDirectives). Правка одной буквы в источнике меняет отпечаток, разметка
  молча отваливается, и на странице вместо карточек появляется сырой блок.
  Проверено 10 августа 2026 на таблице со степенями: она развалилась обратно в
  таблицу, и чинить пришлось запись в данных — своими руками и на каждом стенде
  отдельно.

  Поэтому правим не источник, а то, что доходит до страницы. Это сосед
  dropScaffold (там блок вовсе не доезжает) и cutFromCard (там блок доезжает, но
  уже не внутри карточки). Здесь — оставшиеся случаи: заменить текст внутри
  ячейки таблицы, переписать текст блока, набрать жирным пункт списка,
  превратить абзац в заголовок, вставить новый блок и поставить заголовок перед
  группой.

  Работает ТОЛЬКО на сайте и в выгрузке — там же, где dropScaffold. Инструмент
  «Редактура источника» этот слой не проходит.
*/

/*
  ТЕКСТ ВНУТРИ ЯЧЕЙКИ ТАБЛИЦЫ. Обычная правка текста живёт в правках редактора
  (см. store.ts), но до ячеек они не достают: раскладка берёт ячейку напрямую,
  мимо резолвера правок (tableToText в contentTree). Поэтому такие замены
  перечислены здесь поимённо.

  Сверка точная, по всей ячейке целиком: «1 степень» — короткая строка, и
  вхождением она нашлась бы где угодно.

  Заголовки степеней — замечание Юли от 6 августа 2026, по одному на каждую из
  трёх карточек: степень должна называться так же, как она названа в самой ИПРА.

  Пустая замена значит, что ячейка со страницы уходит совсем. Так снята фраза
  «Конкретные примеры зависят от рекомендаций…» у третьей степени — замечание
  оттуда же. Вместе с ячейкой уходит и подзаголовок «Пример» над ней: раскладка
  пропускает пустую ячейку целиком. Это верно по смыслу — примеров у третьей
  степени в карточке не осталось, они идут ниже отдельными карточками.
*/
const CELL_TEXT: Record<string, string> = {
  "**1 степень**": "**1 степень ограничения способности к трудовой деятельности**",
  "**2 степень**": "**2 степень ограничения способности к трудовой деятельности**",
  "**3 степень**": "**3 степень ограничения способности к трудовой деятельности**",
  "Конкретные примеры зависят от рекомендаций, указанных в ИПРА — разберём их ниже.":
    "",
};

/*
  ТЕКСТ БЛОКА ПЕРЕПИСАН. Ключ — текст блока в источнике целиком, значение — то,
  что доезжает до страницы: разметка (md) и чистый текст.

  Ключом взят именно ТЕКСТ, а не начало фразы: он же служит адресом блока
  (blockRefId), поэтому совпадение по всей строке промахнуться не может. Все три
  строки в источнике встречаются по одному разу — проверено по всем модулям,
  5511 текстовых блоков.

  Ссылка на «Консультант Плюс» со слова «Квота» — замечание Юли от 7 августа
  2026, оставленное дважды: отдельно в первом абзаце страницы «Квоты и
  господдержка» и отдельно в разделе про альтернативное квотирование. У обоих
  блоков меняется только разметка, чистый текст остаётся прежним: слово «Квота»
  никуда не девается, оно перестаёт быть ссылкой. Две другие ссылки на этой
  странице («административная ответственность» и «штраф») клиент не трогал, и
  они остаются.

  «Давайте рассмотрим основные меры поддержки» — замечание оттуда же, клиент
  написала новую формулировку и «(жирным)». В источнике это заголовок третьего
  уровня, но на странице он давно не заголовок: разметка показывает его обычным
  абзацем (директива Text · L), а четыре меры поддержки под ним собраны в
  свёрнутые карточки. Так что правка чисто текстовая — строка становится жирным
  вводным абзацем с двоеточием, как «Условия:» и «Что можно компенсировать:»
  внутри самих карточек.
*/
const REWRITE: Record<string, { md: string; text: string }> = {
  "Квота — это минимальное количество рабочих мест, которое работодатель обязан выделить для трудоустройства людей с инвалидностью.":
    {
      md: "Квота — это минимальное количество рабочих мест, которое работодатель обязан выделить для трудоустройства людей с инвалидностью.",
      text: "Квота — это минимальное количество рабочих мест, которое работодатель обязан выделить для трудоустройства людей с инвалидностью.",
    },
  "Квота считается выполненной, если:": {
    md: "Квота считается выполненной, если:",
    text: "Квота считается выполненной, если:",
  },
  "Давайте рассмотрим основные меры поддержки": {
    md: "**Основные меры поддержки:**",
    text: "Основные меры поддержки:",
  },
};

/*
  АБЗАЦ СТАЛ ЗАГОЛОВКОМ. Ключ — текст блока в источнике целиком, значение — то,
  каким заголовком он выходит на страницу.

  Это не то же самое, что REWRITE: там меняется текст, а вид блока остаётся
  прежним. Здесь меняется именно вид, и вместе с ним появляются уровень и якорь,
  без которых заголовок не попал бы ни в оглавление, ни в структуру документа.

  Строка «Разберём реальные ситуации, которые могут возникнуть в работе» на
  «Этике и коммуникации» — замечание Юли от 7 августа 2026 («сделать
  заголовком»). Под ней идут пять разборов рабочих ситуаций, и до правки они
  начинались ничем: раздел «Как общаться с людьми с инвалидностью» переходил от
  жёлтой карточки «Главное правило» сразу к вопросам.

  Текст заголовка короче исходной фразы — решение дизайнера от 10 августа 2026,
  оно же записано в его пометке к разметке. Заголовок с глаголом и точкой
  («Разберём…») читается как оборванное предложение, а не как название раздела.

  Якорь задан руками и короткий: он попадает в адрес страницы, и длинную строку
  из семи слов туда класть незачем.
*/
const RETYPE: Record<string, { level: 2 | 3 | 4; md: string; text: string; anchor: string }> = {
  "Разберём реальные ситуации, которые могут возникнуть в работе.": {
    level: 3,
    md: "Реальные ситуации, которые могут возникнуть в работе",
    text: "Реальные ситуации, которые могут возникнуть в работе",
    anchor: "realnye-situacii-v-rabote",
  },
};

/*
  ЖИРНЫМ ВНУТРИ ПУНКТА СПИСКА. Ключ — текст пункта в источнике целиком,
  значение — его разметка на странице. Меняется только разметка: сам текст
  остаётся прежним, поэтому адрес списка (он считается по текстам пунктов, см.
  blockRefId) не сдвигается и разметка с него не слетает.

  Два списка на «Этике и коммуникации» — замечания Юли от 7 августа 2026:
  «можно их как-то визуально оформить?» у списка допустимых формулировок и
  «можно визуально показать, что так не надо?» у списка того, чего избегать.
  Решение дизайнера от 10 августа 2026 — жирный, и не более: списки стоят
  рядом, и цветные карточки сделали бы из простой пары «так можно — так не
  надо» два тяжёлых блока.

  Жирным набрана сама формулировка, а не весь пункт. В допустимых пункт и есть
  формулировка целиком, поэтому жирным становится он весь, кроме хвостовой
  точки с запятой. В том, чего избегать, у пункта есть ещё и объяснение
  («потребности есть у всех людей»), и оно остаётся обычным текстом: глаз
  цепляется за неудачное выражение, а причину читатель дочитывает спокойно.
*/
const LIST_ITEM_MD: Record<string, string> = {
  // Какие общие формулировки допустимы.
  "человек с инвалидностью;": "**человек с инвалидностью**;",
  "человек с особенностями здоровья;": "**человек с особенностями здоровья**;",
  "человек с особенностями развития.": "**человек с особенностями развития**.",
  // Чего избегать.
  "выражения «особые потребности» — потребности есть у всех людей, а не только у людей с инвалидностью;":
    "выражения **«особые потребности»** — потребности есть у всех людей, а не только у людей с инвалидностью;",
  "противопоставлений вроде «нормальные люди» и «люди с инвалидностью»;":
    "противопоставлений вроде **«нормальные люди»** и **«люди с инвалидностью»**;",
  "сравнений «здоровые люди» и «инвалиды».":
    "сравнений **«здоровые люди»** и **«инвалиды»**.",
};

type Insert = {
  /** Блок-опора: ищем его по началу текста. */
  after?: RegExp;
  before?: RegExp;
  /** Что поставить рядом с ним. */
  blocks: SourceBlock[];
};

/*
  НОВЫЕ БЛОКИ НА СТРАНИЦЕ. Опора — соседний блок, найденный по началу текста, а
  не по номеру: номера съезжают от любой правки выше по модулю.

  Абзац про электронные справки МСЭ — замечание Юли от 6 августа 2026 («Добавить
  ниже текст»), она показала на последний абзац раздела «Справка об
  инвалидности». Текст взят её словами, без правок.

  Заголовок «Примеры» — решение дизайнера от 10 августа 2026 по её же замечанию.
  У первой и второй степени пример один, у третьей их несколько, и они собраны в
  раскрывающиеся карточки ниже. Карточки начинались без всякого названия, и
  замечание просило это название дать.
*/
const INSERTS: Insert[] = [
  {
    after: /^\s*Группа\s+инвалидности\s+даёт\s+лишь\s+общее\s+представление/iu,
    blocks: [
      {
        kind: "paragraph",
        md: "С 1 марта 2026 года справки МСЭ оформляют преимущественно в электронном виде и направляют в личный кабинет на Госуслугах. Бумажную справку выдают по заявлению гражданина или при невозможности отправить электронный документ. Электронная и бумажная версии имеют одинаковую юридическую силу.",
        text: "С 1 марта 2026 года справки МСЭ оформляют преимущественно в электронном виде и направляют в личный кабинет на Госуслугах. Бумажную справку выдают по заявлению гражданина или при невозможности отправить электронный документ. Электронная и бумажная версии имеют одинаковую юридическую силу.",
      },
    ],
  },
  {
    before: /^\s*Пример\s+1\.\s+Трудоустройство\s+контент-менеджера/iu,
    /*
      Якорь у заголовка свой, а не общий с разделом: общий достаётся ПЕРВОМУ
      заголовку секции, и заняв его, «Примеры» увели бы к себе ссылку на весь
      раздел про ИПРА.
    */
    blocks: [
      {
        kind: "heading",
        level: 3,
        md: "Примеры",
        text: "Примеры",
        anchor: "primery-stepeni-ogranicheniya",
      },
    ],
  },
];

/** Ячейки таблицы, переписанные по замечаниям. Не таблица — блок как был. */
function fixCells(b: SourceBlock): SourceBlock {
  if (b.kind !== "table") return b;
  let touched = false;
  const rows = b.rows.map((row) =>
    row.map((cell) => {
      const next = CELL_TEXT[cell.trim()];
      if (next === undefined) return cell;
      touched = true;
      return next;
    }),
  );
  return touched ? { ...b, rows } : b;
}

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

const textOf = (b: SourceBlock): string =>
  typeof (b as { text?: string }).text === "string"
    ? (b as { text: string }).text
    : "";

/*
  Блоки с переписанным текстом. Списки, таблицы и картинки поля text не имеют,
  и до них правило не достаёт — там свои механизмы (CELL_TEXT для ячеек).

  Уровень заголовка, якорь и вид блока остаются прежними: меняется только то,
  что читатель видит. Адресацию директив это не сдвигает — разметку кладут на
  полный источник ДО этого слоя (см. useModuleDoc), и к моменту правки каждая
  директива уже нашла свои блоки.
*/
function rewriteText(b: SourceBlock): SourceBlock {
  if (b.kind !== "heading" && b.kind !== "paragraph" && b.kind !== "quote")
    return b;
  const next = REWRITE[b.text];
  return next ? { ...b, md: next.md, text: next.text } : b;
}

/*
  Абзац, ставший заголовком. Вид блока меняется целиком, поэтому собираем новый
  блок, а не дополняем прежний: у абзаца нет ни уровня, ни якоря, и оставь мы
  лишние поля — заголовок унёс бы их с собой в раскладку.
*/
function retype(b: SourceBlock): SourceBlock {
  if (b.kind !== "paragraph") return b;
  const next = RETYPE[b.text];
  if (!next) return b;
  return {
    kind: "heading",
    level: next.level,
    md: next.md,
    text: next.text,
    anchor: next.anchor,
  };
}

/** Пункты списка, набранные жирным по замечанию. Не список — блок как был. */
function boldListItems(b: SourceBlock): SourceBlock {
  if (b.kind !== "list") return b;
  let touched = false;
  const items = b.items.map((it) => {
    const md = LIST_ITEM_MD[it.text];
    if (md === undefined) return it;
    touched = true;
    return { ...it, md };
  });
  return touched ? { ...b, items } : b;
}

/*
  Вставленный блок разметки не имеет и иметь не может: разметка адресуется
  блоками источника, а этого блока в источнике нет. Поэтому вместе с блоками
  пересобираем и адресацию: для нового блока директивы нет, для старого она та
  же, что была до вставки.

  Ставить блок ВНУТРЬ цепочки, которую занимает директива, нельзя — цепочка
  перестанет быть непрерывной и разметка слетит со всего куска. Обе наши вставки
  стоят на границе: абзац про справки МСЭ — последним в разделе, заголовок
  «Примеры» — перед первой из карточек-примеров.
*/
export function applyClientEdits(
  sections: BlockSection[],
  at: DirectiveAt,
): { sections: BlockSection[]; directiveAt: DirectiveAt } {
  /** Для каждого нового номера блока — его прежний номер (или null у вставленных). */
  const origin: (number | null)[][] = [];

  const next = sections.map((sec, si) => {
    const blocks: SourceBlock[] = [];
    const from: (number | null)[] = [];
    sec.blocks.forEach((b, bi) => {
      const text = textOf(b);
      for (const ins of INSERTS)
        if (ins.before?.test(text))
          for (const nb of ins.blocks) {
            blocks.push(nb);
            from.push(null);
          }
      blocks.push(retype(rewriteText(boldListItems(fixCells(b)))));
      from.push(bi);
      for (const ins of INSERTS)
        if (ins.after?.test(text))
          for (const nb of ins.blocks) {
            blocks.push(nb);
            from.push(null);
          }
    });
    origin[si] = from;
    return { ...sec, blocks };
  });

  return {
    sections: next,
    directiveAt: (si, bi) => {
      const was = origin[si]?.[bi];
      return was === null || was === undefined ? undefined : at(si, was);
    },
  };
}
