import { MARK_A, MARK_B, MARK_C, markRe } from "@/editor-source/richText";

/*
  РАСКУРСОВКА (сорт D) — убираем «курсовой дух» текста: самоссылки на курс/модуль/
  гид → сайтовые формулировки. СТРОГО по белому списку: слова, которые могут быть
  ОБЫЧНЫМ контентом («курсы» как товар, «уроки» = выводы), НЕ трогаем.

  Каждая замена помечается прямо в тексте метками (см. richText): renderInline
  рисует заменённый кусок как <mark> с подсказкой «было: …». Так любое
  расхождение сайта с источником либо объяснено пометкой, либо это искажение.

  ССЫЛКАМИ, А НЕ СЛОВАМИ. «Подробнее об этом мы рассказывали в модуле 2» — на
  сайте модулей нет, а раздел есть, и до него один клик. Поэтому замена
  подставляет не только название, но и ссылку на страницу. Разметку внутри
  замены рисует renderInline, а в выгрузке разработчику остаётся обычная
  markdown-ссылка.
*/

/*
  Куда ведут разделы сайта. Собрано здесь, чтобы адрес был в одном месте.

  Адрес — путь от корня, без решётки: именно такой нужен разработчику на боевом
  сайте. Решётку своего адреса прототип приписывает при показе (previewHref в
  richText), в данные она не попадает.
*/
const AT = {
  start: "/general/start",
  how: "/general/how",
  legal: "/general/legal",
  benefits: "/general/legal/benefits",
  team: "/general/team",
  companies: "/companies",
  step: (n: string) => `/companies/hire/step-${n}`,
  ngoAudience: "/ngo/audience",
  ngoGuidance: "/ngo/candidates/guidance",
  ngoPsychology: "/ngo/candidates/psychology",
  ngoVacancies: "/ngo/candidates/vacancies",
  ngoEmployers: "/ngo/employers",
  ngoTalks: "/ngo/employers/talks",
  ngoSupport: "/ngo/support",
};

type Rule = { re: RegExp; to: string | ((m: RegExpMatchArray) => string) };

/*
  ССЫЛКИ ПО НАЗВАНИЮ, А НЕ ПО НОМЕРУ.

  Трек «Для компаний» ссылался на соседние части номерами («в модуле 2», «в шаге
  4»), и правила ниже ловят их по числу. Трек «Для НКО» ссылался НАЗВАНИЯМИ
  разделов («читайте в разделе «Профориентация»»), и под это подходящего правила
  не было: одиннадцать страниц трека стояли почти без внутренних ссылок.

  Названия в тексте вдобавок устарели. Раздел «Подбор работы и подготовка к
  собеседованию» на сайте называется «Подбор вакансий и собеседование», а
  «Документы, льготы и квоты: правовые основы трудоустройства» — «Правовые
  основы». Поэтому замена ставит не только ссылку, но и НЫНЕШНЕЕ имя страницы:
  читатель ищет в меню слева ровно то, что прочитал в тексте.

  Правила намеренно длинные и дословные. Обобщать («в разделе «X»» → ссылка на
  страницу X) нельзя: в тексте так же называют разделы трудового договора
  («в раздел «Условия труда»»), и обобщённое правило увело бы читателя со
  страницы туда, где ничего подобного нет.
*/
const LINK_RULES: Rule[] = [
  {
    re: /см\. раздел «Профориентация»/gi,
    to: `см. раздел [«Профориентация»](${AT.ngoGuidance})`,
  },
  {
    re: /читайте в разделе «Профориентация»/gi,
    to: `читайте в разделе [«Профориентация»](${AT.ngoGuidance})`,
  },
  {
    re: /в разделе «Профориентация и психологическая поддержка»/gi,
    to: `в разделах [«Профориентация»](${AT.ngoGuidance}) и [«Психологическая поддержка»](${AT.ngoPsychology})`,
  },
  {
    re: /в разделах «Подбор работы и подготовка к собеседованию» и «Сопровождение на этапе трудоустройства»/gi,
    to: `в разделах [«Подбор вакансий и собеседование»](${AT.ngoVacancies}) и [«Сопровождать сотрудника»](${AT.ngoSupport})`,
  },
  {
    re: /в разделах «Поиск работодателей» и «Взаимодействие с работодателями»/gi,
    to: `в разделах [«Поиск работодателей»](${AT.ngoEmployers}) и [«Разговор с работодателем»](${AT.ngoTalks})`,
  },
  {
    re: /в разделе «Документы, льготы и квоты: правовые основы трудоустройства»/gi,
    to: `в разделе [«Правовые основы»](${AT.legal})`,
  },
  {
    re: /в разделе «Анализ аудитории программ трудоустройства»/gi,
    to: `в разделе [«Аудитория программы»](${AT.ngoAudience})`,
  },
  /*
    «Следующий раздел» — слово из курса, который читали подряд. На сайте это
    соседняя СТРАНИЦА, и до неё надо доехать по меню. Обе фразы дословные:
    точно такая же формулировка на шаге 5 указывает на соседний раздел ТОЙ ЖЕ
    страницы, и трогать её нельзя.
  */
  {
    re: /Подробнее о подборе вакансий поговорим в следующем разделе\./gi,
    to: `подробнее о подборе вакансий — в разделе [«Подбор вакансий и собеседование»](${AT.ngoVacancies}).`,
  },
  {
    re: /которые мешают двигаться дальше \(подробнее об этом — в следующем разделе\)/gi,
    to: `которые мешают двигаться дальше (подробнее — в разделе [«Психологическая поддержка»](${AT.ngoPsychology}))`,
  },
  /*
    Осколки чтения подряд: «глава», «предыдущий шаг», «далее разберём». Первые
    две фразы указывают на место в той же странице, поэтому им хватает замены
    слова. Третья («далее разберём другие формы») обещает продолжение, которого
    на этой странице нет: формы занятости живут на соседней.
  */
  { re: /В этой главе/gi, to: "на этой странице" },
  {
    re: /В предыдущем шаге мы рассказали, как провести аудит/gi,
    to: `на [шаге 2](${AT.step("2")}) мы рассказали, как провести аудит`,
  },
  {
    re: /Далее разберём другие формы трудоустройства и особенности их оформления\./gi,
    to: `другие формы занятости разобраны в разделе [«Льготы и формы занятости»](${AT.benefits}).`,
  },
];

/*
  Белый список. Порядок: длинные/специфичные раньше общих — иначе правило
  «в модуле 5» съело бы «в модуле 5 «Создание инклюзивной среды»» и потеряло
  название, по которому и понятно, о какой странице речь.

  Хвостовое название модуля в кавычках забираем вместе с самой ссылкой: иначе
  на странице получалось два заголовка подряд — «в разделе «Правовые основы»
  «Документы, льготы и квоты: правовые основы трудоустройства»».
*/
const RULES: Rule[] = [
  { re: /в модуле об этике общения/gi, to: `в разделе [«Команда и коммуникация»](${AT.team})` },
  { re: /в модуле 1(\s*«[^»]+»)?/gi, to: `в разделе [«Реалии и мифы»](${AT.start})` },
  { re: /в модуле 2(\s*«[^»]+»)?/gi, to: `в разделе [«Правовые основы»](${AT.legal})` },
  { re: /в модуле 3(\s*«[^»]+»)?/gi, to: `в разделе [«Команда и коммуникация»](${AT.team})` },
  { re: /в модуле 4(\s*«[^»]+»)?/gi, to: `в разделе [«Как устроен наём»](${AT.how})` },
  // Модуль 5 — это весь трек найма по шагам. Кроме одной ссылки, где назван
  // конкретный шаг: «в модуле 5 «Создание инклюзивной среды»» — это шаг 3.
  { re: /в модуле 5\s*«Создание инклюзивной среды»/gi, to: `на [шаге 3 «Создание среды»](${AT.step("3")})` },
  { re: /в модуле 5(\s*«[^»]+»)?/gi, to: `в разделе [«Для компаний»](${AT.companies})` },
  { re: /в следующих модулях/gi, to: "далее" },
  { re: /в следующем модуле/gi, to: "далее" },
  { re: /в этом модуле/gi, to: "на этой странице" },
  { re: /в данном модуле/gi, to: "на этой странице" },
  /*
    «в отдельном разделе этого модуля» — раздел на сайте есть, а модуля нет.
    Правило стоит ПОСЛЕ ссылок на шаги (ниже по коду они применяются раньше),
    поэтому «в шаге 4 этого модуля» к этому месту уже не доходит.
  */
  { re: /\s+этого модуля/gi, to: "" },
  { re: /следующей редакции гида/gi, to: "следующей версии сайта" },
  { re: /следующей версии гида/gi, to: "следующей версии сайта" },
  { re: /в этом гиде/gi, to: "здесь" },
  { re: /этого гида/gi, to: "этого сайта" },
];

/*
  ССЫЛКИ НА ШАГИ — только внутри трека найма (модули 5.x).

  На сайте шаг — это страница («Шаг 3. Создание среды»), поэтому ссылку можно
  поставить прямо в текст. За пределами трека правило выключено намеренно: у НКО
  «Шаг 1»…«Шаг 8» — это разделы внутри страницы про подбор вакансий, и ссылка
  увела бы читателя в чужой трек.
*/
const STEP_RULES: Rule[] = [
  {
    re: /в шаге (\d) и шаге (\d)( этого модуля)?/gi,
    to: (m) => `на [шаге ${m[1]}](${AT.step(m[1])}) и [шаге ${m[2]}](${AT.step(m[2])})`,
  },
  { re: /в шаге (\d)( этого модуля)?/gi, to: (m) => `на [шаге ${m[1]}](${AT.step(m[1])})` },
  { re: /из шага (\d)( этого модуля)?/gi, to: (m) => `из [шага ${m[1]}](${AT.step(m[1])})` },
];

/*
  Замена наследует РЕГИСТР первой буквы оригинала. «В Модуле 5 мы подробно
  разберём…» открывает предложение, и без этого оно начиналось со строчной:
  «в разделе «Для компаний» мы подробно разберём…».
*/
const matchCase = (now: string, orig: string) =>
  /^\p{Lu}/u.test(orig) ? now.replace(/\p{Ll}/u, (c) => c.toUpperCase()) : now;

/*
  Правило применяется ТОЛЬКО к неразмеченным кускам строки.

  Метка хранит рядом и новый текст, и оригинал. Без этой оговорки следующее
  правило находило свою фразу внутри сохранённого оригинала и ставило метку
  внутрь метки: «в шаге 1 и шаге 3 этого модуля» превращалось в «на шаге 1 и
  шаге 3 и шаге 3» — хвост вылезал из разорванной вложенной метки.
*/
const replaceOne = (text: string, { re, to }: Rule) => {
  const sub = (s: string) =>
    s.replace(re, (...args) => {
      const m = args.slice(0, -2) as unknown as RegExpMatchArray;
      const now = matchCase(typeof to === "string" ? to : to(m), m[0]);
      return `${MARK_A}${now}${MARK_B}${m[0]}${MARK_C}`;
    });

  const marks = markRe();
  let out = "";
  let last = 0;
  let mk: RegExpExecArray | null;
  while ((mk = marks.exec(text))) {
    out += sub(text.slice(last, mk.index)) + mk[0];
    last = marks.lastIndex;
  }
  return out + sub(text.slice(last));
};

const apply = (text: string, rules: Rule[]) => rules.reduce(replaceOne, text);

/** Обернуть заменённые куски метками раскурсовки. */
export function decourse(text: string, moduleId?: string): string {
  const steps = moduleId?.startsWith("m5") ? STEP_RULES : [];
  // Дословные правила раньше общих: они длиннее и точнее.
  return apply(apply(apply(text, LINK_RULES), steps), RULES);
}

/** Убрать метки, оставив НОВЫЙ текст (заголовки, оглавление, «вы узнаете»). */
export function stripDecourse(text: string): string {
  return text.replace(markRe(), "$1");
}
