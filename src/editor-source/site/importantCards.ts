import type { SourceBlock } from "@/editor-source/content/source.generated";
import type { Directive } from "@/editor-source/directives";
import { blockRefId } from "@/editor-source/source/blockId";

/*
  КАРТОЧКА «ВАЖНО» ПО ЗАМЕЧАНИЮ КЛИЕНТА — блоки остаются на странице, но
  собираются в одну карточку вместо простого списка под заголовком.

  Это четвёртый сосед в ряду dropScaffold (блок не доезжает до страницы),
  cutFromCard (доезжает, но вне карточки) и clientEdits (доезжает изменённым).
  Здесь блоки не меняются вовсе — меняется только то, чем их считает раскладка.

  ПОЧЕМУ В КОДЕ, А НЕ В РАЗМЕТКЕ. Собрать блоки в карточку умеет обычная
  директива раскладки, но директивы лежат в данных на сервере, и у боевого
  стенда они свои. Поправить их там значит поправить ровно один стенд. Решение
  по замечанию клиента должно уезжать вместе с кодом и работать везде
  одинаково — то же рассуждение записано в cutFromCard.ts.

  ЗАЧЕМ ЭТО НУЖНО. Раздел «Особенности общения с людьми с разными формами
  инвалидности» — шесть рассказов от первого лица, и каждый кончается списком
  правил под заголовком «Краткое саммари». Замечания Юли от 7 августа 2026 и
  Мити от 10 августа 2026, по одному на каждый рассказ: список должен стать
  карточкой «Важно». Длинный монолог и сухая выжимка из него сейчас набраны
  одинаково, и выжимку не видно.

  Слово «Важно» — не украшение, а рабочее название: раскладка сама красит такую
  карточку жёлтым и ставит ей иллюстрацию «Важная информация» (см. bgFor и
  cardArt в contentTree). Поэтому строку «Краткое саммари» со страницы снимает
  dropScaffold: заголовком карточки становится «Важно», и второе название внутри
  читалось бы как ошибка.
*/

/** Что заворачиваем: подряд идущие блоки источника → одна карточка. */
type CardSpec = {
  /** Адреса блоков, ПОДРЯД и в порядке страницы. */
  blocks: string[];
  /** Название карточки. «Важно» само включает жёлтый фон и иллюстрацию. */
  title: string;
};

const SECTION = "/source/m3::osobennosti-obscheniya-s-lyudmi-s-raznymi-formam";

/*
  Шесть выжимок раздела, по одной на рассказ: незрячие, неслышащие, коляска,
  ментальная инвалидность, особенности речи, невидимая инвалидность.

  У второй карточки блока два. Абзац «Ещё больше правил общения с глухими и
  слабослышащими сотрудниками вы найдёте в памятке» стоит сразу под списком, и
  клиент отдельным замечанием просила забрать его в ту же карточку: памятка
  продолжает выжимку, а не начинает новую мысль.

  Адресуем блоки их собственными id, а не текстом: id держится за блок и
  переживает правку формулировки в источнике.
*/
const IMPORTANT: CardSpec[] = [
  { blocks: [`${SECTION}::list::24d6l5`], title: "Важно" },
  {
    blocks: [`${SECTION}::list::vf7g9y`, `${SECTION}::paragraph::16hcn8v`],
    title: "Важно",
  },
  { blocks: [`${SECTION}::list::1c9za60`], title: "Важно" },
  { blocks: [`${SECTION}::list::jcrsnc`], title: "Важно" },
  { blocks: [`${SECTION}::list::id1z3b`], title: "Важно" },
  { blocks: [`${SECTION}::list::1w77qhq`], title: "Важно" },
];

type BlockSection = { anchor?: string; blocks: SourceBlock[] };
type DirectiveAt = (si: number, bi: number) => Directive | undefined;

/*
  Директива, которой в данных нет. Раскладка не спрашивает, откуда директива
  пришла, — ей важны цель, модификаторы и комментарий, поэтому собираем ровно
  такую же запись, какую завёл бы дизайнер руками.

  Статус «applied» обязателен: раскладка молчит на директивах, которые ещё не
  перенесены (isActive в contentTree). Заголовок карточки раскладка вычитывает
  из комментария — отсюда фраза «Добавь заголовок Важно», а не поле.
*/
function directiveFor(spec: CardSpec, moduleId: string): Directive {
  return {
    id: `important:${spec.blocks[0]}`,
    module: moduleId,
    blocks: spec.blocks.map((id) => ({ id, kind: "list", snippet: "" })),
    target: "GeneralCard",
    targetLabel: "General Card",
    modifiers: { orient: "Vertical", icon: false, step: false },
    comment: `Добавь заголовок ${spec.title}`,
    status: "applied",
    createdAt: "2026-08-10T00:00:00.000Z",
  };
}

/*
  Та же адресация директив, но на названных местах — синтетическая карточка.

  Блоки не трогаем ВООБЩЕ: обычная директива адресуется непрерывной цепочкой
  блоков, и любая вставка или правка внутри цепочки рвёт совпадение, после чего
  разметка молча слетает со всего куска. Здесь меняется только ответ на вопрос
  «какая директива накрывает этот блок», а сами блоки остаются как были.

  Одна и та же директива на всю группу — это и есть склейка: раскладка собирает
  подряд идущие блоки в одну группу, пока у них совпадает id директивы.

  Место в цепочке ПОСЛЕДНЕЕ (см. useModuleDoc): к этому моменту леса курса сняты
  и номера блоков окончательны, а значит и адреса, которые мы отдаём.
*/
export function wrapImportantCards(
  sections: BlockSection[],
  pathname: string,
  moduleId: string,
  at: DirectiveAt,
): DirectiveAt {
  const mine = new Map<string, Directive>();

  sections.forEach((sec, si) => {
    const ids = sec.blocks.map((b) => blockRefId(b, pathname, sec.anchor));
    for (const spec of IMPORTANT) {
      const start = ids.indexOf(spec.blocks[0]);
      if (start < 0) continue;
      // Цепочка обязана совпасть целиком: неполная карточка — это не то, о чём
      // просил клиент, и значит источник разошёлся со списком выше.
      const whole = spec.blocks.every((id, k) => ids[start + k] === id);
      if (!whole) continue;
      const dir = directiveFor(spec, moduleId);
      spec.blocks.forEach((_, k) => mine.set(`${si}:${start + k}`, dir));
    }
  });

  return (si, bi) => mine.get(`${si}:${bi}`) ?? at(si, bi);
}
