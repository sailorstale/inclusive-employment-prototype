/*
  РАЗМЕТКА, ЖИВУЩАЯ В КОДЕ.

  ЗАЧЕМ. Разметка блоков — то, что превращает абзацы в карточки, квизы и цитаты, —
  хранится в данных сервера, а данные у каждого стенда свои. Публикация везёт
  только код, поэтому всё, что размечено на нашей машине, у клиента просто
  отсутствует, и никакой выкладкой там не появится.

  Замер 11 августа 2026: из 29 страниц сайта клиент видел не такими 14. У нас
  было 336 записей разметки, на боевом стенде 250, и 98 применённых записей
  существовали только у нас. Хуже всего выглядела «Первая встреча с
  соискателем»: вместо пяти карточек и трёх квизов там были заголовки, абзацы и
  пункты списка вразнобой.

  ЧТО ЗДЕСЬ ЛЕЖИТ. Ровно эти 98 записей, снятые с нашего стенда и разложенные по
  файлу на модуль. Они не переписаны и не улучшены — это тот же самый разбор,
  который дизайнер сделал руками, просто теперь он в репозитории и уезжает
  вместе с кодом.

  ПОЧЕМУ НЕ ПЕРЕНОС ДАННЫХ. Записи можно было бы скопировать в данные боевого
  стенда (tools/directives/push.mjs так и делает), и это быстрее. Но тогда
  решение продолжает жить только в данных, в двух копиях, и пропадает вместе с
  томом. В коде оно переживает и пересоздание тома, и переезд на другой стенд.

  ПРАВИЛО СЛИЯНИЯ: код ДОПОЛНЯЕТ данные, но не спорит с ними. Если запись с
  таким же опознавателем на сервере уже есть, берётся серверная — дизайнер
  правит разметку в своей панели, и его правка обязана быть сильнее. Поэтому на
  нашем стенде эта папка не меняет ничего: там все 98 записей и так есть. Меняет
  она ровно то, ради чего заведена, — страницу у клиента.
*/

const CODE_MARKUP: Directive[] = [
  ...markupM1,
  ...markupM2,
  ...markupM3,
  ...markupM5_1,
  ...markupM5_2,
  ...markupM5_3,
  ...markupM6_1,
  ...markupM6_2,
  ...markupM6_3,
  ...markupM6_4,
];

/** Сколько записей разметки лежит в коде. Для страницы «Проверки». */
export const codeMarkupCount = CODE_MARKUP.length;

/**
 * Разметка с сервера, дополненная той, что лежит в коде.
 *
 * Порядок сохраняем: сначала всё, что пришло с сервера, потом недостающее из
 * кода. Раскладка порядок не читает — она ищет директивы по блокам, — но
 * человеку, который смотрит список, привычнее видеть сначала своё.
 */
export function withCodeMarkup(fromServer: Directive[]): Directive[] {
  const known = new Set(fromServer.map((d) => d.id));
  const extra = CODE_MARKUP.filter((d) => !known.has(d.id));
  return extra.length ? [...fromServer, ...extra] : fromServer;
}
