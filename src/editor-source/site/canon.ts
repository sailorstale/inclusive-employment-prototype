import { MARK_A, MARK_B, MARK_C } from "@/editor-source/richText";

/*
  ЕДИНЫЕ НАЗВАНИЯ ПОВТОРЯЮЩИХСЯ БЛОКОВ.

  Одни и те же по смыслу блоки в источнике названы по-разному, потому что
  писались в разное время и разными людьми. Врезка с прямой речью встречается
  под семью названиями: «Что говорит бизнес», «Что говорят компании и НКО»,
  «Что говорят сотрудники с инвалидностью» и так далее. Практическое задание —
  под четырьмя, причём «для работодателей» и «для работодателя» соседствуют на
  сайте страница к странице.

  Читатель проходит трек подряд и каждый раз видит новое название одного и того
  же. Поэтому здесь один канон на весь сайт.

  Работает ТОЛЬКО на заголовках (см. вызов в useModuleDoc): в теле текста те же
  слова могут быть обычной фразой. Сверка точная, по всему заголовку целиком —
  ни одного «похоже, это оно».

  Замена помечается теми же метками, что и раскурсовка: на странице заголовок
  подсвечен, в подсказке видно исходное название.
*/

/** Кто говорит — три голоса и две смешанные врезки. Ключ приведён к нижнему регистру. */
const CANON: Record<string, string> = {
  // Голоса. «Бизнес» и «компании» — одно и то же, на сайте берём «компании»
  // (так называется и раздел в меню).
  "что говорит бизнес": "Что говорят компании",
  "что говорят компании": "Что говорят компании",
  "что говорит бизнес и нко": "Что говорят компании и НКО",
  "что говорят бизнес и нко": "Что говорят компании и НКО",
  "что говорят компании и нко": "Что говорят компании и НКО",
  "что говорят нко": "Что говорят НКО",
  // Сотрудник с инвалидностью — тоже человек с инвалидностью, разводить
  // эти две врезки незачем.
  "что говорят сотрудники с инвалидностью": "Что говорят люди с инвалидностью",
  "что говорят люди с инвалидностью": "Что говорят люди с инвалидностью",
  "что говорят люди с инвалидностью и нко": "Что говорят люди с инвалидностью и НКО",

  // Практические задания. Аудиторию оставляем — на «Шаге 4» их два подряд, и
  // без неё в оглавлении вышли бы две одинаковые строки. Приводим к одному
  // числу и убираем лишних «представителей».
  "практическое задание для работодателя": "Практическое задание для работодателей",
  "практическое задание для работодателей": "Практическое задание для работодателей",
  "практическое задание для представителей нко": "Практическое задание для НКО",
  "практическое задание для нко": "Практическое задание для НКО",
};

/*
  Правки ЧАСТИ заголовка. Нужны там, где целиком сверить нельзя: в источнике
  внутри заголовка бывает ссылка («Практическое [задание](адрес) для
  представителей НКО»), и подменять его целиком — значит потерять её.
*/
const PHRASES: { re: RegExp; to: string }[] = [
  { re: /\s+для представителей НКО\s*$/iu, to: " для НКО" },
];

/** Ключ для сверки: без разметки, хвостовой пунктуации и лишних пробелов. */
const key = (t: string) =>
  t
    .replace(/[*_]/g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*[:.]\s*$/, "")
    .trim()
    .toLowerCase();

const mark = (now: string, was: string) => `${MARK_A}${now}${MARK_B}${was}${MARK_C}`;

/** Каноническое название заголовка — или тот же текст, если он не из списка. */
export function canonize(text: string): string {
  const whole = CANON[key(text)];
  if (whole && whole !== text.trim()) return mark(whole, text);
  for (const { re, to } of PHRASES)
    if (re.test(text)) return mark(text.replace(re, to), text);
  return text;
}
