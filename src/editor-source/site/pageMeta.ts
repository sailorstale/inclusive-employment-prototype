/** Для браузера и поиска. */
export type PageMeta = {
  /** Заголовок вкладки браузера и строка в поисковой выдаче. */
  title: string;
  /** Описание страницы под ссылкой в поисковой выдаче. */
  description: string;
  /** Значок вкладки. */
  favicon: string;
};

/** Для карточки ссылки в соцсетях и мессенджерах (Open Graph). */
export type PageMetaOg = {
  title: string;
  description: string;
  /** Картинка карточки. */
  image: string;
};

export type PageSeo = { meta: PageMeta; og: PageMetaOg };

/*
  Мета страницы. Заголовок собираем из названия страницы и названия сайта:
  на самой странице человек уже видит заголовок, а во вкладке и в выдаче нужно
  понимать, что это за сайт.
*/
export function metaFor(slug: string, title: string): PageSeo {
  const head = `${title} — ${SITE}`;
  const description = DESCRIPTIONS[slug] ?? "";
  return {
    meta: { title: head, description, favicon: FAVICON },
    og: { title: head, description, image: OG_IMAGE },
  };
}

/** Адреса страниц без описания — для проверки, что мета заполнена целиком. */
export function slugsWithoutDescription(slugs: string[]): string[] {
  return slugs.filter((s) => !DESCRIPTIONS[s]);
}
