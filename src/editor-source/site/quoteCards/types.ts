/*
  ЦИТАТЫ ПО ЗАМЕЧАНИЯМ КЛИЕНТА — набор для одной страницы.

  Записи лежат по файлу на страницу (соседние файлы этой папки), а механика,
  которая собирает из них цитаты, — одна на всех в index.ts. Устройство
  повторяет importantCards: там та же задача, только карточка вместо цитаты.
*/

/** Что заворачиваем: подряд идущие блоки источника → одна цитата. */
export type QuoteSpec = {
  /*
    Адреса блоков, ПОДРЯД и в порядке страницы. Первым идёт блок со строкой
    авторства («Имя, должность „Организация“», весь курсивом), дальше речь.
    Разбор строки авторства — ветка Quote в contentTree.
  */
  blocks: string[];
  /** Крупная цитата или мелкая. По умолчанию крупная. */
  size?: "L" | "S";
  /*
    Клиент отказался от фото у этой цитаты. Тогда у неё не будет ни снимка, ни
    серого кружка-заглушки на его месте, и «дополнить авторство» о фото не
    напомнит.
  */
  noPhoto?: boolean;
};

export type PageQuotes = {
  /** Адрес страницы. Механика его не читает — он для человека и для сообщений об ошибке. */
  page: string;
  quotes: QuoteSpec[];
};
