import type { Directive } from "@/editor-source/directives";

/*
  ВАРИАНТ ОТВЕТА ВМЕСТЕ С РАЗБОРОМ — решение по замечанию клиента, живущее в
  коде.

  Замечание Мити от 11 августа 2026 по четырём квизам на «Как устроен наём»:
  «В вариантах ответа у нас сейчас короткие слова типа работодателя НКО. Их надо
  изменить следующим образом: после Работодателя ставим точку и ставим первый
  абзац из результата». То есть описание действия должно стоять прямо в
  варианте, а не открываться после ответа.

  ПОЧЕМУ В КОДЕ, А НЕ В ДАННЫХ. Разметка дизайнера лежит на сервере, и у
  каждого стенда она своя: правка, внесённая в панели, доедет до одного стенда и
  не доедет до клиента. Поэтому просьба дописывается к комментарию разметки
  здесь — она уезжает вместе с кодом и работает везде одинаково. Тот же приём
  использует importantCards, когда просит раскладку сделать N карточек.

  ОПОЗНАЁМ ДИРЕКТИВУ ПО ПЕРВОМУ БЛОКУ, а не по её id из данных: id у стендов
  разные, а цепочка блоков — общая. Если дизайнер перевесит разметку на другой
  блок, склейка перестанет находить свою директиву, и квизы вернутся к прежнему
  виду. Молча — поэтому список короткий и лежит на виду.
*/
const MERGE_FEEDBACK = new Set<string>([
  // Четыре квиза «Взаимодействие работодателей и НКО» на /general/how.
  "/source/m4::vzaimodeystvie-rabotodateley-i-nko-kto-za-chto-o::h3::mg5v7s",
]);

/** Фраза, по которой раскладка узнаёт просьбу (см. optionWithFeedback). */
const MARK = "Вариант ответа вместе с разбором";

/** Разметка квизов с дописанной просьбой. Остальные директивы — как были. */
export function mergeQuizFeedback(directives: Directive[]): Directive[] {
  return directives.map((d) =>
    d.target === "Quiz" && MERGE_FEEDBACK.has(d.blocks[0]?.id ?? "")
      ? { ...d, comment: `${d.comment ?? ""}\n${MARK}` }
      : d,
  );
}
