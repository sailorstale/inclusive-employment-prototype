/*
  КАРТОЧКИ ПО ЗАМЕЧАНИЯМ КЛИЕНТА — набор для одной страницы.

  Записи лежат по файлу на страницу (соседние файлы этой папки), а механика,
  которая собирает из них карточки, — одна на всех в index.ts. Разделение
  появилось 11 августа 2026: четыре сессии из пяти просили карточки на своих
  страницах и дописывали в один список, из-за чего слияние приходилось
  разбирать руками.
*/

/** Что заворачиваем: подряд идущие блоки источника → одна карточка. */
export type CardSpec = {
  /** Адреса блоков, ПОДРЯД и в порядке страницы. */
  blocks: string[];
  /*
    Название карточки. Оно решает и вид: «Важно» даёт жёлтый фон и картинку
    «Важная информация», «Пример» — картинку «Пример» на обычном синем фоне
    (см. bgFor и cardArt). Название длиннее четырёх слов или начинающееся с
    предлога раскладка отбросит.
  */
  title: string;
};

export type PageCards = {
  /** Адрес страницы. Механика его не читает — он для человека и для сообщений об ошибке. */
  page: string;
  cards: CardSpec[];
};
