/*
  КАРТОЧКИ ПО ЗАМЕЧАНИЯМ КЛИЕНТА — набор для одной страницы.

  Записи лежат по файлу на страницу (соседние файлы этой папки), а механика,
  которая собирает из них карточки, — одна на всех в index.ts. Разделение
  появилось 11 августа 2026: четыре сессии из пяти просили карточки на своих
  страницах и дописывали в один список, из-за чего слияние приходилось
  разбирать руками.
*/

/** Что заворачиваем: подряд идущие блоки источника → одна карточка. */
export type CardSpec = {
  /** Адреса блоков, ПОДРЯД и в порядке страницы. */
  blocks: string[];
  /*
    Название карточки. Оно решает и вид: «Важно» даёт жёлтый фон и картинку
    «Важная информация», «Пример» — картинку «Пример» на обычном синем фоне
    (см. bgFor и cardArt). Название длиннее четырёх слов или начинающееся с
    предлога раскладка отбросит.

    У карточки цитаты названия нет: подписью там работают имя и должность.
  */
  title?: string;
  /*
    ЧЕМ БЛОКИ СТАНУТ. По умолчанию — обычная карточка с названием.

    «Quote» — карточка цитаты: первая строка группы читается как авторство
    («Имя, должность в Компании»), остальные абзацы становятся речью, а имя и
    организация дают портрет и логотип (см. case «Quote» в contentTree). Так
    собраны все голоса на сайте, и в данных сервера у таких пометок стоит ровно
    эта цель.

    «Video» — место под ролик: блок «ВИДЕО» из источника заменяется плеером, а
    адрес ролика берётся из поля href. Названия такой записи не нужно.

    «List» — обычный список, но со значком вместо точек. Значок называет поле
    listIcon; названия и здесь не нужно. Нужно там, где точка не отвечает на
    вопрос, что это за перечень: шесть телеграм-каналов в конце «О проекте» —
    это ссылки, и значок ссылки говорит об этом раньше, чем прочитано название
    канала.
  */
  target?: "GeneralCard" | "Quote" | "Video" | "List";
  /*
    АДРЕС РОЛИКА — только у цели «Video». В источнике на его месте стоит пометка
    «ВИДЕО», а сама ссылка живёт в соседнем абзаце текстом, и забрать этот абзац
    в запись нельзя: он пропал бы целиком, ведь плеер отдаётся вместо блоков.
  */
  href?: string;
  /*
    ФОТО АВТОРА НЕ НУЖНО — только у цитаты. Клиент отказался от снимка, и тогда
    на его месте не должно остаться и серого кружка-заглушки, который у обычных
    цитат держит место под будущее фото.
  */
  noPhoto?: boolean;
  /*
    РАЗДЕЛИТЬ НА N КАРТОЧЕК — только у обычной карточки. По умолчанию группа
    блоков даёт одну карточку; здесь она делится на несколько.

    Единица деления однозначная, без догадок (см. ветку GeneralCard в
    contentTree): блоков ровно N, или один список из N пунктов, или одна таблица
    из двух колонок и N строк — тогда каждая строка становится карточкой, первая
    ячейка названием, вторая текстом.

    Число обязано сойтись с источником. Не сошлось — раскладка оставит прежний
    вид и скажет об этом заметкой прямо на странице, а не сделает вид, что всё
    хорошо.
  */
  split?: number;
  /*
    ЗНАЧОК ПУНКТОВ. Слово пишем по-русски, как в обычной разметке дизайнера
    («галочка», «ссылка», «крестик»): по нему раскладка и подбирает иконку
    (ICON_BY_WORD в contentTree). Не задан — у пунктов обычные точки.

    Работает у списков внутри карточки и у цели «List» — обычного списка на
    странице. Чек-листу нужна галочка: по его пунктам отмечаются, а не читают их
    подряд. Перечню ссылок — значок ссылки.
  */
  listIcon?: string;
};

export type PageCards = {
  /** Адрес страницы. Механика его не читает — он для человека и для сообщений об ошибке. */
  page: string;
  cards: CardSpec[];
};
