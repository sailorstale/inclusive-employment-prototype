const MERGE_FIRST_COLUMN = new Set<string>([
  // «Как нейросети помогают в работе», /companies/step-3.
  "/source/m5-2::chto-govoryat-lyudi-s-invalidnostyu-2::table-header::1qp66vb",
]);

/** Объединять ли первую колонку у таблицы с этим адресом шапки. */
