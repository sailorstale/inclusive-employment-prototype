/** Уже ссылка — второй раз не оборачиваем. */
const inLink = (text: string, at: number) => {
  const before = text.slice(0, at);
  const open = before.lastIndexOf("[");
  return open >= 0 && before.indexOf("]", open) < 0;
};

/*
  Название фонда в строке → markdown-ссылка. Оборачиваем ровно то, что написано
  в тексте, а не подменяем формулировку: «центра адаптации людей с инвалидностью
  Мастер ОК» так и останется, ссылкой станут слова «Мастер ОК».
*/
export function linkOrgSites(text?: string): string | undefined {
  if (!text) return text;
  let out = text;
  for (const site of ORG_SITES) {
    for (const name of site.match) {
      const at = out.indexOf(name);
      if (at < 0 || inLink(out, at)) continue;
      out =
        out.slice(0, at) + `[${name}](${site.href})` + out.slice(at + name.length);
      break; // фонд уже назван ссылкой — короткие варианты не пробуем
    }
  }
  return out;
}
