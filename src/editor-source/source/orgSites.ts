/*
  САЙТЫ НКО — чтобы название организации в подписи к цитате было ссылкой.

  В подписи под цитатой стоит должность автора, и в ней почти всегда назван его
  фонд: «руководитель проекта „РИТМ“, Благотворительный фонд «Действуй!»».
  Читателю естественно захотеть посмотреть, что это за фонд, а ссылки не было —
  хотя в тексте страниц эти же фонды упоминаются ссылками.

  Адреса взяты из самого источника: каждый из них уже стоит ссылкой в тексте
  какой-нибудь страницы. Ничего не выдумано, и если фонд сменит адрес, править
  надо здесь и в источнике.

  Только НКО. Работодатели («Пятёрочка», «Лаборатория Касперского», «Бургер
  Кинг») сюда не идут: цитата от сотрудника компании — это его рабочее место, а
  не организация, о которой читателю предлагают почитать отдельно.

  match — по чему узнаём фонд в строке должности. Названия в источнике написаны
  вразнобой («Мастер ОК», «центра адаптации людей с инвалидностью Мастер ОК»),
  поэтому ищем короткое устойчивое ядро имени, а не полное название.
*/
export type OrgSite = {
  /*
    Варианты написания, по которым узнаём фонд. Длинные — раньше коротких: имя
    целиком читается ссылкой лучше, чем его хвост («Фонд борьбы с лейкемией», а
    не одно слово «лейкемией»). Короткий вариант остаётся запасным на случай,
    когда в источнике фонд назван сокращённо.
  */
  match: string[];
  href: string;
};

