/*
  «Заголовки Прямое трудоустройство и Альтернативное квотирование превратить в
  жирный текст» — источник ставит подзаголовок там, где по смыслу просто акцент
  внутри ответа. В аккордеоне такой заголовок открывал бы СВОЙ аккордеон, и их
  выходило больше, чем просил дизайнер. Названные заголовки уходят в тело
  жирной строкой.
*/
const headingsToBold = (d?: Directive): string[] => {
  const m =
    /(?:загол\p{L}*|подзагол\p{L}*|заг)\s+(.+?)\s+(?:можно\s+)?(?:превра|сдела|переве)\p{L}*\s+(?:в\s+)?жирн/isu.exec(
      d?.comment || "",
    );
  if (!m) return [];
  return m[1]
    .split(/\s+и\s+|[,;]\s*/iu)
    .map((s) => s.replace(/[«»"'*_]/g, "").trim())
    .filter((s) => s.length >= 3);
};

/*
  «Все в одну карточку», «В одну карточку» — обратное делению: автоматика
  разложила бы набор по жирным лидам и заголовкам, а дизайнер хочет один блок.
*/
/** «Это одна фраза» — слить выделенные блоки в одну врезку. */
const wantsOnePhrase = (d?: Directive) => /одна\s+фраз/iu.test(d?.comment || "");

const wantsMerge = (d?: Directive) =>
  // «Одна карточка» — та же просьба, сказанная короче.
  /в\s+одну\s+карточ|одной\s+карточк|все\s+в\s+одну|одна\s+карточк/iu.test(
    d?.comment || "",
  );

/*
  «Предложение начинается с Нейросети…» — дизайнер называет слово, с которого
  должно начинаться тело. Всё, что было до него (служебный зачин вроде «Важно
  помнить, что»), уходит: ярлык уже стал заголовком карточки, и повторять его
  в первой строке незачем.
*/
const bodyStartsFrom = (d?: Directive): string | undefined =>
  /предложени\p{L}*\s+начина\p{L}*\s+с\p{L}*\s+([^\n.…]{3,40})/iu
    .exec(d?.comment || "")?.[1]
    ?.trim();

/*
  «Эту таблицу сложно читать, сделай из неё текст с заголовками, перечисления —
  списками». Таблица на четыре колонки в узкой вёрстке действительно не читается.

  Разбор идёт по смыслу таблицы, а не механически: строка — это один предмет
  рассказа (её первая ячейка — заголовок), а колонки — аспекты этого предмета
  (имя колонки становится подзаголовком, содержимое ячейки — текстом). Ячейки с
  маркерами «•» распадаются на список.
*/
const wantsTableToText = (d?: Directive) => {
  const c = d?.comment || "";
  return (
    /таблиц/iu.test(c) &&
    /(текст|заголовк|загов|списк|перечислен|разбер|разобра|переработ)/iu.test(c)
  );
};

/*
  Узнало ли ХОТЬ ОДНО правило что-нибудь в комментарии.

  Нужно, чтобы комментарий не мог пропасть молча. Просьба вроде «сделай из
  таблицы текст со списками» — это переструктурирование КОНТЕНТА, раскладка так
  не умеет; раньше она просто рендерила блок как есть и ничего не говорила.
  Теперь неразобранный комментарий виден заметкой в превью.

  Список намеренно перечисляет все правила поимённо: добавили новое — допишите
  сюда, иначе оно будет считаться «непонятым» и давать ложную заметку.
*/
/*
  КОММЕНТАРИЙ = ИНСТРУКЦИЯ + необязательное ОБЪЯСНЕНИЕ.

  Объяснение отделяется строкой, которая начинается со слова «Почему», и
  правилами НЕ читается. Без этой границы рассказ про раскладку сам становился
  раскладкой: в предложении «…в карточке ей место в заголовке» правило «добавь
  заголовок X» находило слово «заголовке» и делало заголовком карточки слово
  «место».

  Граница нужна именно потому, что предложение Claude и комментарий — теперь
  один текст: дизайнер правит его целиком, и объяснение живёт рядом с
  инструкцией, а не отдельным полем.
*/
// Без \b: в JS это ASCII-граница, и после кириллического «у» её не бывает —
// «Почему:» не совпадало. Те же грабли, что в проходе 17.
const WHY_LINE = /^[ \t]*почему/iu;
export function instructionOf(comment: string): string {
  const lines = (comment || "").split("\n");
  const i = lines.findIndex((l) => WHY_LINE.test(l));
  return (i < 0 ? lines : lines.slice(0, i)).join("\n").trim();
}

const commentRecognized = (d?: Directive): boolean =>
  wantsDelete(d) ||
  wantsUnlink(d) ||
  linkPhrase(d) !== undefined ||
  wantsDecaps(d) ||
  wantsMergeParagraph(d) ||
  wantsOnePhrase(d) ||
  bodyStartsFrom(d) !== undefined ||
  wantsImageToList(d) ||
  labelToTitle(d) !== undefined ||
  addedLinkUrl(d) !== undefined ||
  countHint(d) !== undefined ||
  wantsUnbold(d) ||
  wantsNumber(d) ||
  wantsUnitalic(d) ||
  wantsUnnumber(d) ||
  wantsMerge(d) ||
  wantsCapitalize(d) ||
  wantsNoColon(d) ||
  wantsTableToText(d) ||
  headingsToBold(d).length > 0 ||
  wantsLinePairs(d) ||
  listItemIcon(d) !== undefined ||
  listCount(d) !== undefined ||
  quizCount(d) !== undefined ||
  splitCount(d) !== undefined ||
  explicitTitle(d) !== undefined ||
  leadWordToDrop(d) !== undefined ||
  labelsToDrop(d).length > 0;

/*
  «далее предложение с большой буквы» — поднять регистр первой буквы тела.

  Запас на опечатку в корне обязателен: живой комментарий пришёл как «с болшой
  буквы» (без мягкого знака), и жёсткое «больш» молча не сработало. Поэтому
  между «бол» и «ш» допускаем любые буквы.
*/
const wantsCapitalize = (d?: Directive) =>
  /с\s+бол\p{L}*ш\p{L}*\s+букв/iu.test(d?.comment || "");

/*
  «без двоеточия» — источник пишет ярлык как «Важно:», и двоеточие тянется в
  заголовок карточки. Снимаем хвостовой знак у заголовка по просьбе.
*/
const wantsNoColon = (d?: Directive) =>
  /без\s+двоеточ|убра\p{L}*\s+двоеточ|убер\p{L}*\s+двоеточ/iu.test(d?.comment || "");

/*
  Блок-ЯРЛЫК: весь текст блока — одно служебное слово («Пример», «Важно»,
  «Важно:»). В источнике это подпись к следующему абзацу, а в карточке — её
  ЗАГОЛОВОК. Оставлять его текстом нельзя: он либо дублирует заданный заголовок
  («Важно» сверху и «Важно:» первой строкой), либо болтается как сирота.
*/
const LABEL_WORD =
  /^[*_\s]*(пример|важно|суть|итог|вывод|совет|правило|запомнить)\p{L}*\s*[:.]?[*_\s]*$/iu;
const isLabelBlock = (t: string) => LABEL_WORD.test(t.trim());
/** Ярлык как заголовок: без хвостового двоеточия и разметки. */
const labelAsTitle = (t: string) =>
  t.replace(/[*_]/g, "").replace(/\s*[:.]\s*$/, "").trim();

const capitalizeFirst = (t: string) =>
  t.replace(/^\s*(\p{Ll})/u, (m, c: string) => m.replace(c, c.toUpperCase()));

/*
  «Слово Важно убрать в начале предложения», «Слово Суть убрать» — источник
  начинает абзац служебным словом-ярлыком («Важно: …», «Суть — …»), которое в
  карточке дублирует заголовок. Убираем это слово ТОЛЬКО из начала текста:
  внутри предложения оно может быть по делу.
*/
const leadWordToDrop = (d?: Directive): string | undefined => {
  const c = d?.comment || "";
  /*
    Порядок слов любой: и «слово Суть убрать», и «убираем слово «Ситуация»».
    Живой комментарий пришёл вторым видом и молча не срабатывал — как обычно,
    правило знало ровно ту формулировку, на которой его писали.
  */
  const m =
    /слов\p{L}*\s+[«"']?([^\s,.;:!?»"']+)[»"']?\s+убра/iu.exec(c) ??
    /(?:убра|убир|убер|снят|снима|снима)\p{L}*\s+слов\p{L}*\s+[«"']?([^\s,.;:!?»"']+)/iu.exec(c);
  const w = m?.[1]?.trim();
  return w && w.length >= 2 ? w : undefined;
};

const stripLeadWord = (t: string, w: string): string => {
  const esc = w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  /*
    Слово может быть обёрнуто в жирный и отделено двоеточием или тире, причём
    двоеточие бывает и ВНУТРИ жирного: «**Суть:** государство…». Без второго
    разделителя такой ярлык не снимался — звёздочки шли после двоеточия.
  */
  const out = t.replace(
    new RegExp(`^\\s*[*_]*\\s*${esc}\\s*[:—–-]?\\s*[*_]*\\s*[:—–-]?\\s*`, "iu"),
    "",
  );
  return out.trim() ? out : t;
};

/*
  Карточка из строки вида «**1-я группа** — наиболее выраженные особенности…»:
  жирное начало (а если его нет — часть до тире) становится ЗАГОЛОВКОМ, остальное
  телом. Тире-разделитель при этом уходит — это и есть «убрать тире».

  Если жирная часть — это весь текст, заголовка нет: строка целиком жирная это
  не заголовок с телом, а просто акцент.
*/
const splitTitleBody = (text: string): { title?: string; body: string } => {
  const bold = text.match(/^\s*\*\*(.+?)\*\*\s*/);
  if (bold) {
    const rest = text
      .slice(bold[0].length)
      .replace(/^\s*[—–-]\s*/, "")
      .replace(/^\s*:\s*/, "");
    if (rest.trim())
      return { title: bold[1].trim().replace(/[.:;]+$/, ""), body: rest.trim() };
    return { body: text.trim() };
  }
  /*
    «Первое — **расширение географии работы**. НКО может…»: жирная фраза стоит не
    в начале строки, а за коротким зачином-перечислителем («Первое», «Второе
    направление»). Заголовок берём из жирного, зачин выбрасываем — на карточке
    он лишний, порядок и так виден по её месту в ряду.

    Зачин допускаем короткий (до сорока знаков) и только через тире. Без этих
    двух условий под правило попал бы обычный абзац, где жирным выделено слово
    в середине фразы, и половина текста уехала бы в заголовок.

    Первую букву заголовка поднимаем: фраза вырезана из середины предложения и
    начинается со строчной, а заголовок со строчной буквы — это опечатка.
  */
  const lead = text.match(/^\s*.{2,40}?\s+[—–]\s+\*\*(.+?)\*\*[.:]?\s*/su);
  if (lead) {
    const rest = text.slice(lead[0].length).trim();
    if (rest)
      return {
        title: capitalizeFirst(lead[1].trim().replace(/[.:;]+$/, "")),
        body: rest,
      };
  }
  const dash = text.match(/^(.{2,60}?)\s+[—–]\s+(.+)$/s);
  if (dash) return { title: dash[1].trim(), body: dash[2].trim() };
  return { body: text.trim() };
};

/*
  Явный заголовок карточки из комментария: «Добавь заголовок Важно»,
  «карточка с загловоком Пример». Опечатки дизайнера частые, поэтому корень
  берём с запасом (загол/заглов/загов/заглав).
*/
const explicitTitle = (d?: Directive): string | undefined => {
  if (!d?.target || wantsSplit(d)) return undefined;
  /*
    «Важно В ЗАГОЛОВОК» — это не «добавь заголовок X», а перенос ярлыка из
    начала абзаца. Без этой проверки правило хватало весь хвост комментария и
    заголовком становилась инструкция целиком.
  */
  if (labelToTitle(d) !== undefined) return undefined;
  // «заг» принимаем только целым словом: иначе «загрузить» дало бы заголовок.
  const m = /(?:заг(?=\s)|загол\p{L}*|заглов\p{L}*|загов\p{L}*|заглав\p{L}*)\s+([«"'])?([^«»"'.,;:!?\n]+)/iu.exec(
    withoutRemovals(d.comment || ""),
  );
  // Заголовок в КАВЫЧКАХ — явная граница, поставленная человеком.
  const quoted = Boolean(m?.[1]);
  const t = m?.[2]?.replace(/[*_]/g, "").trim();
  if (!t || t.length < 2 || t.length > 60) return undefined;
  /*
    Заголовок — короткая подпись («Важно», «Пример»), а не кусок фразы. Без этой
    проверки описательное предложение «сделай текст с заголовками и там ещё есть
    перечисления…» давало заголовком весь хвост фразы.

    Отсекаем по двум признакам: слишком много слов и начало со служебного слова
    (в осмысленной подписи его не бывает).

    КАВЫЧКИ ОТМЕНЯЮТ обе проверки: границу назвал человек, догадываться не о чем.
    Без этого «Добавь заголовок На этом этапе важно» молча не срабатывало —
    подпись начинается с предлога «на», а он в списке служебных слов.
  */
  const words = t.split(/\s+/);
  const FILLER = /^(и|а|но|или|там|тут|где|что|как|это|эти|все|всё|ещё|еще|же|в|на|с|со|для|по|из)$/iu;
  if (!quoted && (words.length > 4 || FILLER.test(words[0]))) return undefined;
  return t;
};

/*
  «Пояснение» — строительные леса исходника: внутри аккордеона ответ и ЕСТЬ
  пояснение, ярлык только шумит. «Миф» и «Правда» оставляем — они несут вердикт.
  На уровне модуля, потому что нужен и сборке аккордеона, и стражу потерь.
*/
const isExplainLabel = (t: string) =>
  /^[*_\s]*пояснени\p{L}*\s*:?[*_\s]*$/iu.test(t);

/*
  «Обратная связь к варианту 2» — служебная подпись в квизе: она говорит, к
  какому варианту относится разбор, и в результат не идёт. Страж потерь должен
  знать об этом, иначе ругается на каждую такую строку.
*/
const isOptionFeedbackLabel = (t: string) =>
  /^[*_\s]*обратн\p{L}*\s+связ\p{L}*\s+к\s+вариант\p{L}*\s*\d+[*_\s.:]*$/iu.test(t.trim());

/*
  «Вопрос 1» — такой же служебный ярлык квиза, как «Ситуация». Сам вопрос идёт
  абзацем под ним, а ярлык вставал в карточке отдельной строкой сверху и ничего
  не добавлял: читатель и так видит, что перед ним вопрос. Убираем — решение
  дизайнера 5 августа 2026.

  Ловим ТОЛЬКО голый ярлык («Вопрос 1», «Вопрос»). Заголовок со своим текстом
  («Вопрос о справке») остаётся как есть. На уровне модуля, потому что нужен и
  сборке квиза, и стражу потерь.
*/
const isQuestionLabel = (t: string) =>
  /^[*_\s]*вопрос\s*\d*[*_\s:.]*$/iu.test(t.trim());

/*
  «Если вы выбрали низкий диапазон» — подпись куска ОБЩЕГО разбора: она говорит,
  кому этот кусок адресован. Разбор уезжает к своему варианту ответа, и подпись
  вместе с ним не нужна: читатель уже выбрал, объяснять ему это незачем. Страж
  потерь должен знать, иначе ругается на каждую такую строку.
*/
const isSharedVariantLabel = (t: string) =>
  /^[*_\s]*если\s+вы\s+выбрали\s+[^.!?]{3,40}[*_\s:]*$/iu.test(t.trim());

const isDroppedLabel = (raw: string, labels: string[]) => {
  const bare = raw.replace(/[*_]/g, "").replace(/:$/, "").trim().toLowerCase();
  return bare.length > 0 && labels.includes(bare);
};

const stripBold = (md: string) => md.replace(/\*\*(.+?)\*\*/g, "$1");

/*
  Курсив — ОДИНОЧНАЯ звёздочка (или подчёркивание). Двойную не трогаем: это
  жирный, у него своя чистка. Поэтому по краям требуем «не звёздочку», иначе
  «**текст**» распался бы на «*текст*».
*/
const stripItalic = (md: string) =>
  md
    .replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, "$1$2")
    .replace(/(^|[^_])_([^_\n]+)_(?!_)/g, "$1$2");

/*
  Ведущая нумерация заголовка: «1. », «2) », «Пример 1. », «Ситуация 3 — ».
  Снимаем только ПРЕФИКС и только если после него что-то осталось: заголовок
  вида «1» (сам по себе номер) не должен превратиться в пустой.
*/
const stripNumber = (t: string) => {
  const out = t.replace(
    /^\s*(?:[«"']?\p{Lu}\p{L}*\s+)?\d+\s*(?:[.)»"']|—|–|-|:)?\s+/u,
    "",
  );
  return out.trim() ? out.trim() : t.trim();
};

/*
  «Убрать ссылку» — снять разметку ссылки, ТЕКСТ оставить. Просят, когда адрес
  в заголовке мешает: заголовок должен быть заголовком, а не кликом.
*/
const wantsUnlink = (d?: Directive) =>
  !!d &&
  /(убра|убир|убер|сня|без)\p{L}*\s+(ссылк|линк)|(ссылк|линк)\p{L}*\s+(убра|убир|убер|сня)/iu.test(
    d.comment || "",
  );

/** «…и написать её обычным текстом под заголовком» — адрес отдельной строкой. */
const wantsUrlAsText = (d?: Directive) => !!d && /текстом/iu.test(d.comment || "");

/*
  «Присвоить ссылку словам X» — адрес переезжает с заголовка на фразу в тексте.
  Голый адрес строкой читателю не нужен: ссылка должна жить в словах, которые
  он и так читает.
*/
const linkPhrase = (d?: Directive): string | undefined => {
  const c = d?.comment || "";
  if (!/(присво|назнач|повес)/iu.test(c)) return undefined;
  // Фраза в кавычках — самый надёжный вид; иначе берём хвост инструкции.
  const quoted = /[«"]([^»"]{3,80})[»"]/u.exec(c)?.[1];
  if (quoted) return quoted.trim();
  const tail =
    /(?:присво|назнач|повес)\p{L}*\s+(?:её|ее|ей|ссылку|ссылки|на)?\s*([^\n]{3,80})$/iu.exec(
      c,
    )?.[1];
  return tail?.trim();
};

/*
  «Написать не капсом, аббревиатуру капом оставить». Слово из заглавных длиннее
  четырёх букв — это не аббревиатура, а крик: приводим к обычному виду. СЗН,
  НКО, ИПРА (четыре буквы и короче) остаются как есть.
*/
const wantsDecaps = (d?: Directive) =>
  !!d && /(не|без)\s*капс|не\s+заглавн|строчн/iu.test(d.comment || "");

const ABBR_MAX = 4;
const decaps = (t: string) =>
  t.replace(/\p{Lu}[\p{Lu}\d-]+/gu, (w) =>
    w.replace(/-/g, "").length <= ABBR_MAX
      ? w
      : w[0] + w.slice(1).toLowerCase(),
  );

/** Снять разметку ссылки, оставив её текст. */
const stripLink = (t: string) => t.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");

/** Экранирование для поиска подстроки регэкспом. */
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Адрес из ссылки блока — нужен, когда его просят вынести обычным текстом. */
const linkUrl = (t: string) => /\[[^\]]+\]\(([^)]+)\)/.exec(t)?.[1];

/** «Добавить ссылку в первое слово» + адрес в том же комментарии. */
const addedLinkUrl = (d?: Directive): string | undefined =>
  /добав\p{L}*\s+ссылк/iu.test(d?.comment || "")
    ? /(https?:\/\/[^\s)]+)/.exec(d?.comment || "")?.[1]
    : undefined;

/*
  «Тут 4 аккордеона», «тут три цитаты» — дизайнер называет число, чтобы сверить
  результат. Само правило раскладки от этого не зависит: цитаты и аккордеоны
  собираются по структуре источника. Но если собралось другое число — об этом
  надо сказать, иначе расхождение заметит только клиент.
*/
const COUNT_WORD: Record<string, number> = { ...RU_NUM };
const countHint = (d?: Directive): { n: number; component: string } | undefined => {
  const m = /(\d+|дв[еа]|три|четыре|пять|шесть|семь|восемь)\s+(цитат|аккорд|аккард|аккод)\p{L}*/iu.exec(
    d?.comment || "",
  );
  if (!m) return undefined;
  const raw = m[1].toLowerCase();
  const n = /^\d+$/.test(raw) ? Number(raw) : COUNT_WORD[raw];
  if (!n) return undefined;
  return { n, component: /цитат/iu.test(m[2]) ? "Quote" : "Accordion" };
};

/*
  «Превратить картинку в список». Картинка — это схема из плашек, и прочитать
  её может только человек (или я в проходе). Поэтому пункты пишутся в
  комментарий после пустой строки, по одному на строку, а правило собирает из
  них обычный список. Так решение видно дизайнеру и правится им же.
*/
const wantsImageToList = (d?: Directive) =>
  !!d && /(картинк|изображен|схем)\p{L}*[^\n]*список/iu.test(d.comment || "");

/*
  «Пример в заголовок» — ярлык из начала абзаца («**Пример.** Во время
  аудита…») становится заголовком карточки, а из тела уходит. Это тот же
  случай, что ярлык отдельным блоком, только здесь он приклеен к первой строке.
*/
const labelToTitle = (d?: Directive): string | undefined =>
  /([\p{Lu}][\p{L}]{2,20})\s+в\s+заголов/iu.exec(d?.comment || "")?.[1];

/**
 * Тот ли это ярлык: «Пример» из комментария и «Пример.» из жирного лида —
 * одно и то же слово. Сверяем без разметки, хвостовой пунктуации и регистра.
 */
const sameLabel = (a?: string, b?: string): boolean => {
  const norm = (s?: string) =>
    (s || "").replace(/[*_]/g, "").replace(/[.:;!?\s]+$/u, "").trim().toLowerCase();
  return Boolean(a) && norm(a) === norm(b);
};

/** «Собрать эти три в один абзац» — склейка группы в один блок текста. */
/*
  \b здесь не годится: в JS граница слова считается по [A-Za-z0-9_], и перед
  кириллическим «один» её просто нет — правило молча не срабатывало.
*/
const wantsMergeParagraph = (d?: Directive) =>
  !!d && /(собер|собра|объедин)\p{L}*[^.\n]*один\s+(абзац|блок)?/iu.test(d.comment || "");

/*
  Готовый текст в комментарии. Дизайнер иногда пишет не «что сделать», а прямо
  «как должно получиться» — вторым абзацем после пустой строки. Тогда он и
  становится результатом, а не наша склейка.
*/
const commentTail = (d?: Directive) => {
  const parts = (d?.comment || "").split(/\n\s*\n/);
  return parts.length > 1 ? parts.slice(1).join("\n\n").trim() : "";
};

/** Текстовые чистки из комментария — общие для всей группы блоков. */
type TextFix = {
  unbold: boolean;
  unitalic: boolean;
  unnumber: boolean;
  unlink: boolean;
  decaps: boolean;
};
/** Те же чистки, но к готовой строке: у пунктов списка своего md() нет. */
const applyFix = (t: string, fix: TextFix): string => {
  let out = t;
  if (fix.unbold) out = stripBold(out);
  if (fix.unitalic) out = stripItalic(out);
  if (fix.unlink) out = stripLink(out);
  if (fix.decaps) out = decaps(out);
  return out;
};
const NO_FIX: TextFix = {
  unbold: false,
  unitalic: false,
  unnumber: false,
  unlink: false,
  decaps: false,
};
const textFix = (d?: Directive): TextFix => ({
  unbold: wantsUnbold(d),
  unitalic: wantsUnitalic(d),
  unnumber: wantsUnnumber(d),
  unlink: wantsUnlink(d),
  decaps: wantsDecaps(d),
});

/*
  Заголовок несёт свой вес сам (Heading, вопрос аккордеона, заголовок карточки).
  В источнике такие строки часто обёрнуты в «**…**» — если оставить, жирность
  ляжет поверх жирности. Поэтому в заголовках разметку веса снимаем.
*/
const headingText = (t: string, fix: TextFix = NO_FIX) => {
  const s = stripBold(t).trim();
  return fix.unnumber ? stripNumber(s) : s;
};
const stripEmph = (t: string) => t.replace(/^[*_]+|[*_]+$/g, "").trim();

/*
  Звёздочки ВНУТРИ строки. Разметка в источнике часто рваная: «**Ольга
  Алексеевна Поварова****, специалист…**», «…вакансии.* * **Доверие…*». Краевые
  маркеры снимает stripEmph, а внутренние остаются и читатель видит их как
  мусор посреди фразы. В цитате разметка веса не нужна вовсе — карточка и так
  набрана курсивом, — поэтому маркеры выделения снимаем целиком.
*/
const stripMarks = (t: string) =>
  t
    .replace(/\*+/g, "")
    .replace(/^_+|_+$/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();

/** Буквы и цифры в нижнем регистре — для сверки «упомянуто ли уже». */
const flatten = (t: string) =>
  t
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();

/*
  Группы по ВСЕМУ модулю: подряд идущие блоки одной директивы — вместе.

  Почему сквозным проходом, а не внутри каждой секции. Директива — единое целое,
  но секции режутся по h2. Директива, охватывающая несколько h2 (четыре меры
  господдержки — каждая заголовком h2), разрывалась на части: каждый аккордеон
  уезжал в собственную секцию, между ними появлялись отбивки, и общий конверт
  собрать было нельзя.

  Поэтому группа продолжается через границу секции, а принадлежит той секции,
  где НАЧАЛАСЬ. Секции, чей заголовок ушёл внутрь такой директивы, своего
  содержимого не получают и не рисуются вовсе.
*/
type PlacedGroup = Group & { si: number };

function groupsOfDoc(
  sections: Section[],
  directiveAt?: (si: number, bi: number) => Directive | undefined,
): PlacedGroup[] {
  const groups: PlacedGroup[] = [];
  let cur: PlacedGroup | null = null;
  sections.forEach((sec, si) => {
    sec.blocks.forEach((b, bi) => {
      const d = directiveAt?.(si, bi);
      const active = isActive(d) ? d : undefined;
      const item = { b, anchor: sec.anchor, at: `${si}:${bi}` };
      if (active && cur?.dir?.id === active.id) {
        cur.items.push(item);
      } else {
        cur = { dir: active, items: [item], si };
        groups.push(cur);
      }
    });
  });
  return groups;
}

/*
  Не-проза: в секцию напрямую не кладётся, только через Block.

  Stack сюда НЕ входит, хотя соблазн есть. В КОМПОНЕНТЫ.md про него
  сказано прямо: «кладётся куда угодно: в секцию, в карточку, в Compare Card,
  в аккордеон», и в перечне того, что требует конверта, списка нет. Лишний
  конверт давал +32 к собственным 16 контейнера — отбивка от абзаца выходила
  48 вместо 16.
*/
const NON_PROSE = new Set([
  "GeneralCard",
  "Accordion",
  "Quote",
  "Table",
  "Prompt",
  "Quiz",
  "Compare",
  "Image",
  "Video",
]);

const isPageSummary = (g: Group) => g.dir?.target === "PageSummary";

function needsCard(g: Group): boolean {
  if (isPageSummary(g)) return false;
  if (g.dir?.target) return NON_PROSE.has(g.dir.target);
  const k = g.items[0]?.b.kind;
  // Блок-цитата без автора становится Phrase — это проза, конверт не нужен.
  return k === "table" || k === "image";
}

/*
  «Поставить в один card container» — просьба склеить конверт с соседним ВОПРЕКИ
  правилу ролей. Обычно разные фоны означают разные по сущности блоки, и общий
  конверт им вреден. Но пара «Физическая инвалидность» и «Ментальная
  инвалидность» — это одно противопоставление, разбитое на две карточки: цвет
  тут различает стороны сравнения, а не роль. Исключение включается словами, а
  не догадкой.
*/
const wantsSameContainer = (d?: Directive) =>
  /(?:один|одном|одного)\s+(?:card\s*container|конверт\p{L}*|контейнер\p{L}*)/iu.test(
    d?.comment || "",
  );

const cardOrientation = (g: Group): "Vertical" | "Horizontal" =>
  g.dir?.target === "GeneralCard" && g.dir.modifiers?.orient === "Horizontal"
    ? "Horizontal"
    : "Vertical";

/** [текст](адрес): группа 1 — текст, группа 2 — сам адрес (нужен логотипу цитаты). */
const LINK_RE = /\[([^\]]+)\]\(((?:https?:)?\/\/[^)]+)\)/;

/*
  СКЛЕЙКА СОСЕДНИХ СПИСКОВ.

  Парсер источника отдаёт каждый пункт списка ОТДЕЛЬНЫМ блоком (в директивах это
  видно как «1 пунктов»). Без склейки каждый пункт получал свой Stack,
  а тот — свой Block: 32 пикселя от конверта плюс 16 от контейнера на
  КАЖДЫЙ пункт. Списки разъезжались на пол-экрана.

  По системе Stack — это вертикальный стек с равным шагом, и шаг задаёт
  он сам. Поэтому соседние списки одного типа сливаем в один контейнер: пункты
  идут подряд, промежуток — штатный gap.
*/
function listInside(n?: Node): Extract<Node, { component: "Stack" }> | undefined {
  if (!n) return undefined;
  if (n.component === "Stack") return n;
  if (
    n.component === "Block" &&
    n.children.length === 1 &&
    n.children[0].component === "Stack"
  )
    return n.children[0];
  return undefined;
}

/*
  Однородный конверт: какой ОДИН тип компонента лежит внутри Block.
  Служебные пометки инструмента не в счёт — они не контент.
*/
function soleKind(n?: Node): string | undefined {
  if (!n || n.component !== "Block") return undefined;
  const kinds = new Set(
    n.children.filter((c) => c.component !== "note").map((c) => c.component),
  );
  return kinds.size === 1 ? [...kinds][0] : undefined;
}

/*
  РОЛЬ содержимого конверта — по фону карточек. Фон здесь не украшение, а смысл:
  синий — обычная, жёлтый — важное, розовый — опасное, зелёный — позитив.

  Нужно для склейки: «Пример» (бежевый) и «Важно» (жёлтый) стоят рядом, оба —
  General Card, и по одному лишь типу склеивались в ОДИН конверт. Но это разные
  по сущности блоки, им нужны разные конверты. Одинаковые по роли (три карточки
  групп инвалидности, пара «медицинский/социальный подход») по-прежнему живут
  в одном.

  undefined — ролей несколько: такой конверт не склеиваем ни с чем.
*/
function soleRole(n?: Node): string | undefined {
  if (!n || n.component !== "Block") return undefined;
  const roles = new Set(
    n.children
      .filter((c) => c.component !== "note")
      .map((c) => (c.component === "General Card" ? c.bgColor : "—")),
  );
  return roles.size === 1 ? [...roles][0] : undefined;
}

/*
  СКЛЕЙКА СОСЕДЕЙ. Два правила, оба про «не плодить обёртки»:

  1. Соседние списки одного типа — в один Stack (он и есть стек с
     равным шагом, шаг задаёт сам).
  2. Соседние Block с ОДНИМ И ТЕМ ЖЕ типом внутри — в один конверт.
     Восемь мифов подряд это восемь аккордеонов в ОДНОМ Block, а не
     восемь конвертов по одному: каждый конверт добавлял свои 32 сверху, и
     ряд однотипных блоков разъезжался.

  Ориентация конвертов должна совпадать: вертикальный столбик и горизонтальный
  ряд карточек — разные раскладки, их сливать нельзя.
*/
function mergeSiblings(nodes: Node[]): Node[] {
  const out: Node[] = [];
  for (const raw of nodes) {
    // Сначала внутрь: аккордеоны и карточки тоже держат списки и конверты.
    const n: Node =
      "children" in raw && Array.isArray(raw.children)
        ? ({ ...raw, children: mergeSiblings(raw.children) } as Node)
        : raw;

    const prev = out[out.length - 1];

    // 1. Списки
    const a = listInside(prev);
    const b = listInside(n);
    if (a && b && a.ordered === b.ordered) {
      const merged = { ...a, children: [...a.children, ...b.children] };
      out[out.length - 1] =
        prev!.component === "Block"
          ? { ...prev!, children: [merged] }
          : merged;
      continue;
    }

    // 2. Однотипные конверты
    const ka = soleKind(prev);
    const kb = soleKind(n);
    // Роль (фон карточек) — часть условия: разные по сущности блоки не сливаем.
    const ra = soleRole(prev);
    const rb = soleRole(n);
    /*
      Исключение по просьбе: «поставить в один card container». Роли тогда не
      сверяем — дизайнер уже сказал, что эти карточки об одном. Тип и ориентация
      остаются обязательными: склеить карточку с аккордеоном не просили.
    */
    const joined =
      (prev?.component === "Block" && prev.join) ||
      (n.component === "Block" && n.join);
    if (
      ka &&
      ka === kb &&
      (joined || (ra !== undefined && ra === rb)) &&
      prev!.component === "Block" &&
      n.component === "Block" &&
      prev!.orientation === n.orientation
    ) {
      out[out.length - 1] = {
        ...prev!,
        // Пометку несёт и склейка: иначе третья карточка ряда не приклеилась бы.
        join: joined || undefined,
        children: [...prev!.children, ...n.children],
      };
      continue;
    }

    out.push(n);
  }
  return out;
}

/*
  ЯЧЕЙКА ТАБЛИЦЫ С ПЕРЕЧИСЛЕНИЕМ. В клиентском документе переносы строк внутри
  ячейки потерялись, и пункты слиплись в одну строку: «…дублировать письменно.•
  Если обратная связь даётся устно…». Ставим перенос перед каждым пунктом —
  дальше по этим переносам ячейка и разбирается на узлы (см. cellValue).
*/
/*
  Подзаголовок внутри ячейки («**Санузел:**», «**1. Работа допускается…**») в том
  же документе прилип к концу предыдущего пункта: «…на удобную высоту**Санузел:**».
  Ставим перенос и перед ним — иначе подзаголовок читается как хвост чужой строки.

  Узко по форме: только жирный кусок, который кончается двоеточием или начинается
  с номера. Обычное выделение внутри фразы не трогаем — оно не открывает новую
  группу, а просто подчёркивает слово.
*/
const CELL_LABEL = /([^\n])[ \t]*(\*\*(?:\d+[.)]\s[^*]*|[^*]*:)\*\*)/g;

export function cellWithLines(cell: string): string {
  const withBullets = cell.includes("•")
    ? cell.replace(/\s*•\s*/g, "\n• ").replace(/^\s*\n/, "").trim()
    : cell;
  return withBullets.replace(CELL_LABEL, "$1\n$2");
}

/*
  ЗНАЧЕНИЕ ЯЧЕЙКИ. Ячейка без перечисления остаётся строкой. Если внутри есть
  пункты, ячейка разбирается на узлы: строки с маркером собираются в список
  (Stack из List Item), остальные становятся вступительным текстом (Text).
  Групп может быть несколько — «фраза, список, фраза, список»; каждая новая
  фраза закрывает предыдущий список.

  Размер M, а не L: текст внутри ячейки на ступень мельче прозы страницы —
  так же, как внутри карточки (сама ячейка нарисована стилем Body M).
*/
export function cellValue(cell: string): TableCellValue {
  const text = cellWithLines(cell);
  if (!text.includes("•")) return text;

  const children: Node[] = [];
  let items: Node[] = [];
  const flushItems = () => {
    if (!items.length) return;
    // Нумерованных перечислений в ячейках нет — маркер всегда точка.
    children.push({ component: "Stack", ordered: false, children: items });
    items = [];
  };

  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith("•")) {
      items.push({
        component: "List Item",
        size: "M",
        type: "Dot",
        text: line.replace(/^•\s*/, ""),
      });
      continue;
    }
    flushItems();
    children.push({ component: "Text", size: "M", text: line });
  }
  flushItems();

  return { component: "Table cell", children };
}

export function buildDoc(
  moduleId: string,
  sections: Section[],
  resolve: ResolveMd,
  logoIndex: LogoEntry[],
  directiveAtRaw?: (si: number, bi: number) => Directive | undefined,
  avatarIndex: AvatarEntry[] = [],
): Doc {
  /*
    Единственная точка, где комментарий попадает в раскладку, — здесь. Срезаем
    объяснение («Почему: …») один раз на входе, чтобы каждое из трёх десятков
    правил не думало об этом само.
  */
  const trimmed = new WeakMap<Directive, Directive>();
  const directiveAt = (si: number, bi: number): Directive | undefined => {
    const d = directiveAtRaw?.(si, bi);
    if (!d) return undefined;
    const seen = trimmed.get(d);
    if (seen) return seen;
    const cut: Directive = { ...d, comment: instructionOf(d.comment) };
    trimmed.set(d, cut);
    return cut;
  };

  /** Актуальная разметка блока (с учётом правок) + чистки из комментария. */
  const md = (it: Item, fix: TextFix = NO_FIX): string => {
    const b = it.b;
    const type = b.kind === "heading" ? `h${b.level}` : "paragraph";
    // У таблицы, картинки и СПИСКА своего поля text нет: у списка текст живёт
    // в items. Без этой проверки адрес правки считался бы от undefined и падал.
    const raw =
      b.kind === "table" || b.kind === "image" || b.kind === "list"
        ? ""
        : resolve(type, (b as { text: string }).text, (b as { md: string }).md, it.anchor);
    return applyFix(raw, fix);
  };

  const liText = (it: Item, li: { text: string; md: string }) =>
    resolve("li", li.text, li.md, it.anchor);

  /** Блок без директивы — обычная раскладка по правилам системы. */
  const plainNodes = (it: Item, fix: TextFix, inCard = false): Node[] => {
    const b = it.b;
    switch (b.kind) {
      case "heading":
        return [
          {
            component: "Heading",
            level: `H${b.level}` as HeadingLevel,
            text: headingText(md(it, fix), fix),
            // Якорь из источника: он же стоит у секции и в оглавлении.
            anchor: b.anchor,
          },
        ];
      case "paragraph":
        // Body L — только проза страницы, вне карточек и прочих компонентов.
        // Внутри General Card, аккордеона и подобных текст на ступень мельче.
        return [{ component: "Text", size: inCard ? "M" : "L", text: md(it, fix) }];
      case "quote":
        // Quote — только речь человека с именем. Блок «>» автора не несёт,
        // поэтому по правилу это Phrase: фраза-врезка курсивом.
        return [{ component: "Phrase", size: "L", text: md(it, fix) }];
      case "list":
        return [
          {
            component: "Stack",
            ordered: b.ordered,
            children: b.items.map((li) => ({
              component: "List Item" as const,
              size: "L" as const,
              type: (b.ordered ? "Number" : "Dot") as "Number" | "Dot",
              text: liText(it, li),
            })),
          },
        ];
      case "table":
        return [
          {
            component: "Table",
            header: b.header,
            rows: b.rows.map((r) => r.map(cellValue)),
          },
        ];
      case "image":
        return b.src
          ? [{ component: "Image", src: b.src, alt: b.alt }]
          : [{ component: "Video" }];
    }
  };

  /*
    СТРАЖ ПОТЕРЬ.

    Контент не должен исчезать молча — только по явной команде «удалить».
    Правило раскладки сложное (лиды, ярлыки, деление на карточки), и один
    недосмотр уже стоил нам целого блока: список, попавший в карточку первым,
    пропадал бесследно.

    Поэтому сверяем: текст каждого исходного блока обязан оставить след в
    собранных узлах. Не оставил — рисуем заметку прямо в превью. Заметка
    служебная, в выгрузку не идёт: её задача — чтобы пропажу заметил человек.
  */
  const nodeText = (n: Node | SectionNode): string => {
    const parts: string[] = [];
    const o = n as Record<string, unknown>;
    for (const k of [
      "text",
      "question",
      "title",
      "alt",
      "author",
      "role",
      "org",
      // Квиз держит текст ещё и здесь — без этого страж считал его потерянным.
      "description",
      "explanation",
    ])
      if (typeof o[k] === "string") parts.push(o[k] as string);
    if (Array.isArray(o.items)) {
      /*
        Сначала ВСЕ варианты подряд, и только потом их разборы. Страж сверяет
        блок источника непрерывным куском, а список вариантов в источнике идёт
        сплошь: если вставить разбор между вариантами, список перестанет
        узнаваться и страж объявит его потерянным (проверено на самопроверке
        М6.1, где разбор появился у каждого варианта).
      */
      const opts = o.items as { text?: string; feedback?: string }[];
      parts.push(opts.map((i) => i?.text ?? "").join(" "));
      parts.push(opts.map((i) => i?.feedback ?? "").join(" "));
    }
    if (Array.isArray(o.paragraphs)) parts.push((o.paragraphs as string[]).join(" "));
    if (Array.isArray(o.header)) parts.push((o.header as string[]).join(" "));
    if (Array.isArray(o.rows))
      // Ячейка — либо строка, либо узел с содержимым (перечисление внутри).
      parts.push(
        (o.rows as TableCellValue[][])
          .flat()
          .map((c) => (typeof c === "string" ? c : nodeText(c)))
          .join(" "),
      );
    if (Array.isArray(o.children))
      parts.push((o.children as Node[]).map(nodeText).join(" "));
    return parts.join(" ");
  };

  /** Текст исходного блока — включая те виды, у которых своего поля text нет. */
  const itemText = (it: Item): string => {
    const b = it.b;
    if (b.kind === "list") return b.items.map((li) => liText(it, li)).join(" ");
    if (b.kind === "table") return [...b.header, ...b.rows.flat()].join(" ");
    if (b.kind === "image") return b.alt || "";
    return md(it);
  };

  /** Сравниваем по сути: без разметки, регистра и пунктуации. */
  const signature = (s: string) =>
    s
      /*
        Адрес ссылки в сверке не участвует: в исходнике он есть
        («[Фонд…](https://…)»), а в собранном узле остаётся только название —
        URL живёт отдельным полем. Иначе каждая цитата со ссылкой давала
        ложную тревогу.
      */
      .replace(/\]\([^)]*\)/g, " ")
      .replace(/https?:\/\/\S+/gi, " ")
      // Маркер списка — разметка, а не текст: в разборе квиза мы ставим его
      // сами, и без этого страж считал бы пункты «потерянными». Кружок «◯» из
      // вариантов ответа — такой же маркер: без него короткий вариант
      // («◯ Повторить вопрос громче.») давал ложную тревогу.
      .replace(/[*_`#>[\]()«»"'—–\-.,;:!?•·◯○●]/g, " ")
      .replace(/\s+/g, " ")
      .trim()
      .toLowerCase();

  /*
    Адреса блоков группы вешаем на её узлы: по ним сайт понимает, на какие
    блоки источника ложится директива, заведённая кликом по компоненту.
    Группа без директивы — это ровно один блок, поэтому адрес получается
    точным, а не «куда-то в этот абзац».
  */
  const stamp = (nodes: Node[], g: Group): Node[] => {
    const at = g.items.map((it) => it.at).filter((x): x is string => Boolean(x));
    return at.length ? nodes.map((n) => ({ ...n, at })) : nodes;
  };

  const guarded = (g: Group): Node[] => {
    const base = stamp(groupNodes(g), g);
    /*
      Комментарий, в котором ни одно правило ничего не узнало, — не «пожелание
      в воздух»: дизайнер его написал и ждёт результата. Показываем прямо в
      превью, иначе просьба исчезает бесследно (так и случилось с таблицей).

      Исключение — комментарий ПРЕДЛОЖЕНИЯ (его написал Claude). Там текст
      объясняет, что директива уже делает, и ждать от него исполнения нечего.
      Как только дизайнер правит комментарий, авторство переходит к нему
      (origin: "designer") и страховка включается обратно.
    */
    const comment = (g.dir?.comment || "").trim();
    const out: Node[] =
      comment && g.dir?.origin !== "claude" && !commentRecognized(g.dir)
        ? [
            ...base,
            {
              component: "note",
              text: `комментарий не разобран${
                g.dir?.target ? "" : " (компонент не выбран)"
              }: «${comment.replace(/\s+/g, " ").slice(0, 120)}»`,
            },
          ]
        : base;
    // Дизайнер назвал число («тут три цитаты») — сверяем и говорим, если не сошлось.
    const hint = countHint(g.dir);
    if (hint) {
      const got = out.filter(
        (n) => (n as Node).component === hint.component,
      ).length;
      if (got !== hint.n)
        out.push({
          component: "note",
          text: `просили ${hint.n}, собралось ${got} (${hint.component}) — проверьте`,
        });
    }

    /*
      Удаление и снятие ярлыков — намеренные потери, о них не предупреждаем.
      Готовый текст из комментария — тоже: дизайнер сам переписал абзац, и
      расхождение с источником здесь не пропажа, а его решение.
    */
    if (wantsDelete(g.dir)) return out;
    if (wantsMergeParagraph(g.dir) && commentTail(g.dir)) return out;
    const drop = labelsToDrop(g.dir);
    const produced = signature(out.map(nodeText).join(" "));
    /*
      Слово-ярлык, который просили снять («убираем слово „Ситуация"»), раскладка
      срезает — значит и сверять надо БЕЗ него, иначе страж ругается на каждый
      заголовок, где ярлык стоял.
    */
    const dropLead = leadWordToDrop(g.dir);
    const lost = g.items.filter((it) => {
      const raw0 = itemText(it);
      const raw = dropLead ? stripLeadWord(raw0, dropLead) : raw0;
      if (drop.length && isDroppedLabel(raw, drop)) return false;
      if (
        isExplainLabel(raw) ||
        isOptionFeedbackLabel(raw) ||
        isSharedVariantLabel(raw) ||
        isQuestionLabel(raw)
      )
        return false;
      const sig = signature(raw);
      // Короткие служебные подписи («Миф», «Правда») проверять бессмысленно:
      // они и так растворяются в тексте соседей и дают ложные тревоги.
      if (sig.length < 25) return false;
      /*
        Сверяем по ХВОСТУ, а не по началу: наши же правила срезают именно
        префикс («Пример 1. Трудоустройство…» → «Трудоустройство…»), и проба
        с начала давала ложную тревогу на каждом таком заголовке. Конец текста
        правила не трогают.
      */
      return !produced.includes(sig.slice(-40));
    });
    if (!lost.length) return out;
    return [
      ...out,
      {
        component: "note",
        text: `не попало в раскладку — ${lost.length} блок(ов): ${lost
          .map((it) => signature(itemText(it)).slice(0, 45))
          .join(" · ")}`,
      },
    ];
  };

  /*
    Ячейка таблицы — не всегда «просто текст» или «просто список». В одной могут
    лежать: вводная фраза, пронумерованные случаи жирным («**1. Работа
    допускается…**») и перечисление примеров через «•».

    Раскладывать это плоским списком нельзя: вводная фраза становилась пунктом,
    а текст ПОСЛЕ перечисления прилипал к последнему пункту. Поэтому читаем
    структуру: нумерованный жирный — подзаголовок и граница, «•» — пункты
    списка, всё остальное — текст.
  */
  const cellNodes = (cell: string): Node[] => {
    const out: Node[] = [];
    let bullets: string[] = [];
    const flushList = () => {
      if (!bullets.length) return;
      out.push({
        component: "Stack",
        ordered: false,
        children: bullets.map((t) => ({
          component: "List Item" as const,
          size: "L" as const,
          type: "Dot" as const,
          text: t,
        })),
      });
      bullets = [];
    };
    const pushText = (t: string) => {
      const s = t.trim();
      if (s) out.push({ component: "Text", size: "L", text: s });
    };

    for (const part of cell.split(/(\*\*\s*\d+\.\s*[^*]+?\*\*)/g)) {
      const head = part.match(/^\*\*\s*(\d+\.\s*[^*]+?)\s*\*\*$/);
      if (head) {
        flushList();
        // Хвостовая точка в подзаголовке не нужна, номер случая — нужен.
        out.push({
          component: "Heading",
          level: "H5",
          text: head[1].replace(/\s*[.:]\s*$/, "").trim(),
        });
        continue;
      }
      const chunks = part.split(/\s*•\s*/);
      const lead = chunks.shift() ?? "";
      if (lead.trim()) {
        flushList();
        pushText(lead);
      }
      for (const c of chunks) if (c.trim()) bullets.push(c.trim());
    }
    flushList();
    return out;
  };

  /** Таблица → проза: строка даёт заголовок, колонки — подзаголовки с текстом. */
  const tableToText = (
    b: Extract<SourceBlock, { kind: "table" }>,
    fix: TextFix,
  ): Node[] => {
    const out: Node[] = [];
    for (const row of b.rows) {
      const [first, ...rest] = row;
      if (first?.trim())
        out.push({
          component: "Heading",
          level: "H4",
          text: headingText(first, fix),
        });
      rest.forEach((cell, i) => {
        if (!cell?.trim()) return;
        const col = b.header[i + 1];
        // Имя колонки — подзаголовок. Без него читатель не поймёт, что за текст.
        if (col?.trim())
          out.push({ component: "Heading", level: "H5", text: headingText(col, fix) });
        out.push(...cellNodes(cell));
      });
    }
    return out;
  };

  const groupNodes = (g: Group): Node[] => {
    const { dir } = g;

    if (wantsDelete(dir))
      return [
        { component: "note", text: `убрано по директиве: ${g.items.length} блок(ов)` },
      ];

    const fix = textFix(dir);
    const drop = labelsToDrop(dir);
    const items = drop.length
      ? g.items.filter((it) => !isDroppedLabel(md(it), drop))
      : g.items;

    /*
      Разбор таблицы в текст работает и БЕЗ выбранного компонента: дизайнер
      описал результат словами, и цель тут не нужна — таблица превращается в
      обычную прозу с заголовками.
    */
    if (wantsTableToText(dir))
      return items.flatMap((it) =>
        it.b.kind === "table" ? tableToText(it.b, fix) : plainNodes(it, fix),
      );

    if (!dir?.target) {
      /*
        Картинка-схема разворачивается в список: пункты дизайнер (или я в
        проходе) выписывает в комментарий после пустой строки.
      */
      if (wantsImageToList(dir)) {
        const lines = commentTail(dir)
          .split("\n")
          .map((s) => s.replace(/^\s*[-—•*\d.)\s]+/, "").trim())
          .filter(Boolean);
        if (lines.length)
          return [
            {
              component: "Stack",
              ordered: false,
              children: lines.map((text) => ({
                component: "List Item" as const,
                size: "L" as const,
                type: "Dot" as const,
                text,
              })),
            },
          ];
        return [
          {
            component: "note",
            text: "картинку в список: выпишите пункты в комментарий после пустой строки",
          },
        ];
      }

      /*
        Ссылка переезжает на названные слова: с заголовка её сняли, а адрес
        вешаем на первую же подходящую фразу в ТЕКСТЕ группы. Заголовки
        пропускаем намеренно — из них ссылку как раз и убирали.
      */
      const phrase = linkPhrase(dir);
      if (fix.unlink && phrase) {
        const url = items.map((it) => linkUrl(md(it))).find(Boolean);
        let done = false;
        return items.flatMap((it) =>
          plainNodes(it, fix).map((n) => {
            if (done || !url || n.component !== "Text") return n;
            const t = n.text;
            const at = t.toLowerCase().indexOf(phrase.toLowerCase());
            if (at < 0) return n;
            done = true;
            const found = t.slice(at, at + phrase.length);
            return {
              ...n,
              text: `${t.slice(0, at)}[${found}](${url})${t.slice(at + phrase.length)}`,
            };
          }),
        );
      }

      /*
        Ссылка в заголовке: разметку снимаем всегда (fix.unlink), а если просили
        «написать её обычным текстом» — адрес идёт отдельной строкой под
        заголовком. Сноска (Text S): это служебная строка, а не абзац.
      */
      if (fix.unlink && wantsUrlAsText(dir))
        return items.flatMap((it) => {
          const url = linkUrl(md(it));
          const nodes = plainNodes(it, fix);
          return url ? [...nodes, { component: "Text", size: "S", text: url } as Node] : nodes;
        });

      // «Добавить ссылку в первое слово» — ссылкой становится ровно одно слово.
      const addUrl = addedLinkUrl(dir);
      if (addUrl)
        return items.flatMap((it, i) => {
          if (i > 0 || it.b.kind === "table" || it.b.kind === "image")
            return plainNodes(it, fix);
          const t = md(it, fix);
          return [
            {
              component: "Text",
              size: "L",
              text: t.replace(/^([\p{L}\p{N}«»-]+)/u, `[$1](${addUrl})`),
            } as Node,
          ];
        });

      /*
        Склейка группы в один абзац. Текст берём из комментария, если дизайнер
        его там написал; ссылки из исходных блоков возвращаем на их названия —
        «назначить ссылки хедхантеру и авито» это и значит.
      */
      if (wantsMergeParagraph(dir)) {
        const links = items.flatMap((it) =>
          [...md(it).matchAll(/\[([^\]]+)\]\(([^)\s]+)\)/g)].map((m) => ({
            text: m[1],
            url: m[2],
          })),
        );
        let text =
          commentTail(dir) ||
          items
            .map((it) => stripBold(stripLink(md(it, fix))).trim())
            .filter(Boolean)
            .join(" ");
        for (const l of links)
          if (!new RegExp(`\\[${escapeRe(l.text)}\\]`).test(text))
            text = text.replace(l.text, `[${l.text}](${l.url})`);
        return [{ component: "Text", size: "L", text }];
      }

      return items.flatMap((it) => plainNodes(it, fix));
    }

    const mods = dir.modifiers || {};

    /*
      Чистки ТЕЛА: снять служебное слово-ярлык в начале и поднять регистр.
      Общие для карточки и аккордеона: источник помечает ярлыком («**Суть:**
      государство компенсирует…») и абзац карточки, и абзац аккордеона —
      просьба «слово Суть убрать» не должна зависеть от выбранного компонента.
    */
    const dropWord = leadWordToDrop(dir);
    const capBody = wantsCapitalize(dir);
    /*
      «Предложение начинается с Нейросети…» — обрезаем зачин до названного
      слова и поднимаем регистр: слово стало первым в предложении. Режем только
      ПЕРВЫЙ блок и только если слово в нём действительно есть.
    */
    const startFrom = bodyStartsFrom(dir);
    /*
      Функция ИДЕМПОТЕНТНА намеренно: bodyText вызывают по два раза на один и
      тот же текст (сначала «есть ли что показывать», потом сам текст). С
      флагом «уже отрезали» второй вызов возвращал текст целиком — и обрезка
      пропадала. После первой обрезки слово стоит в начале, и повторный вызов
      уже ничего не делает.
    */
    const cutToStart = (t: string) => {
      if (!startFrom) return t;
      const at = t.toLowerCase().indexOf(startFrom.toLowerCase());
      return at > 0 ? capitalizeFirst(t.slice(at).trim()) : t;
    };
    const bodyText = (t: string) => {
      let out = dropWord ? stripLeadWord(t, dropWord) : t;
      out = cutToStart(out);
      if (capBody) out = capitalizeFirst(out);
      return out.trim();
    };
    /** Те же чистки для готовых узлов — текст лежит внутри Text/Phrase. */
    const fixBodyNodes = (nodes: Node[]): Node[] =>
      dropWord || capBody
        ? nodes.map((n) =>
            n.component === "Text" || n.component === "Phrase"
              ? { ...n, text: bodyText(n.text) }
              : n,
          )
        : nodes;

    switch (dir.target) {
      case "PageSummary":
        return [
          {
            component: "Page Summary",
            children: items.flatMap((it): Node[] =>
              it.b.kind === "list"
                ? it.b.items.map((li) => ({
                    component: "List Item" as const,
                    size: "L" as const,
                    type: "Dot" as const,
                    text: liText(it, li),
                  }))
                : [{ component: "Text", size: "M", text: md(it, fix) }],
            ),
          },
        ];

      case "GeneralCard": {
        /*
          КАЖДЫЙ блок с ведущим **жирным** начинает СВОЮ карточку: «**Медицинский
          подход** …» и «**Социальный подход** …» — это две равнозначные карточки
          в ряд, а не одна с двумя абзацами. Блоки без такого лида продолжают
          текущую карточку («**Пример.** …» плюс продолжение абзацами).

          Сами карточки всегда Vertical (иконка сверху, под ней заголовок и
          текст). «Горизонтально» из директивы — про РЯД: это ориентация
          конверта Block, две карточки по половине колонки бок о бок.

          Иконка у каждой карточки своя — подобрана по тексту её блока.
        */
        const cards: Node[] = [];
        const bg = typeof mods.bg === "string" ? mods.bg : "blue";
        // «X в заголовок» — ярлык из начала абзаца работает так же, как явный заголовок.
    const forcedTitle = explicitTitle(dir) ?? labelToTitle(dir);
        const noColon = wantsNoColon(dir);
        /** Хвостовое двоеточие заголовка — по просьбе «без двоеточия». */
        const titleFix = (t?: string) =>
          t && noColon ? t.replace(/\s*[:：]\s*$/, "").trim() || t : t;
        /*
          Нумерация заголовков — по месту карточки в ряду. Ставим в самом конце,
          одним проходом по готовому ряду: так номера идут подряд независимо от
          того, каким путём ряд собрался (по жирным лидам или явным делением).
        */
        const withNumbers = (list: Node[]): Node[] =>
          wantsNumber(dir)
            ? list.map((n, i) =>
                n.component === "General Card" && n.title
                  ? { ...n, title: `${i + 1}. ${n.title}` }
                  : n,
              )
            : list;
        /*
          Заголовок назвали комментарием, а первая строка тела — та же фраза:
          «Добавь заголовок На этом этапе важно» при абзаце «На этом этапе
          важно:». В источнике это была подпись к списку, в карточке подпись —
          уже заголовок, и повторять её незачем. Сверяем по сути: без разметки,
          хвостового двоеточия и регистра.
        */
        const sameAsTitle = (t: string | undefined, body: string) => {
          if (!t) return false;
          const norm = (s: string) =>
            s
              .replace(/[*_]/g, "")
              .replace(/\s+/g, " ")
              .replace(/\s*[:.：]\s*$/, "")
              .trim()
              .toLowerCase();
          return norm(t) === norm(body);
        };
        // Иконки лежат в директиве в том же порядке, что и блоки.
        const iconOf = (it: Item) =>
          dir.blocks.find((x) => x.snippet && md(it).startsWith(x.snippet.slice(0, 20)))
            ?.icon;

        /*
          ЯВНОЕ ДЕЛЕНИЕ «сделать N карточек».

          Автоматика делит по жирному лиду, и когда это расходится с замыслом,
          возразить ей было нечем. Теперь количество можно назвать в комментарии.

          Единицу деления берём однозначную, без догадок: либо блоков ровно N
          (каждый блок — карточка), либо это один список из N пунктов (каждый
          пункт — карточка). Не сошлось — не выдумываем: оставляем автоматику и
          говорим об этом заметкой, иначе дизайнер будет думать, что просьба
          исполнена.
        */
        /*
          «Все в одну карточку» — обратное делению. Автоматика разложила бы набор
          по жирным лидам, а дизайнер хочет один блок: первый блок даёт заголовок
          (или он задан явно), остальное идёт телом подряд.
        */
        if (wantsMerge(dir)) {
          const [head, ...tail] = items;
          const t0 = md(head, fix);
          /*
            Блок-ярлык («Пример», «Важно:») даёт заголовок и в тело не идёт:
            иначе слово стоит и заголовком, и первой строкой текста.
          */
          const headIsLabel = isLabelBlock(t0);
          const auto = headIsLabel ? { title: labelAsTitle(t0), body: "" } : splitTitleBody(t0);
          const title = titleFix(
            forcedTitle ?? (auto.title ? headingText(auto.title, fix) : undefined),
          );
          const firstBody = headIsLabel ? "" : forcedTitle ? t0 : auto.body;
          const icon = iconOf(head);
          const kids: Node[] = [];
          if (bodyText(firstBody) && !sameAsTitle(title, firstBody))
            kids.push({ component: "Text", size: "M", text: bodyText(firstBody) });
          for (const it of tail) kids.push(...plainNodes(it, fix, true));
          return [
            {
              component: "General Card",
              orientation: "Vertical",
              bgColor: bg,
              icon: mods.icon && icon ? icon : undefined,
              title,
              children: kids,
            },
          ];
        }

        const want = splitCount(dir);
        const unitText = (it: Item) =>
          it.b.kind === "list"
            ? it.b.items.map((li) => applyFix(liText(it, li), fix)).join(" ")
            : md(it, fix);

        let units: { it: Item; text: string }[] | null = null;
        if (want) {
          if (items.length === want) {
            units = items.map((it) => ({ it, text: unitText(it) }));
          } else if (
            items.length === 1 &&
            items[0].b.kind === "list" &&
            items[0].b.items.length === want
          ) {
            const it = items[0];
            units = (it.b as { items: { text: string; md: string }[] }).items.map((li) => ({
              it,
              text: applyFix(liText(it, li), fix),
            }));
          }
        }

        if (units) {
          return withNumbers(units.map(({ it, text }) => {
            const { title, body } = splitTitleBody(text);
            const icon = iconOf(it);
            return {
              component: "General Card",
              orientation: "Vertical",
              bgColor: bg,
              icon: mods.icon && icon ? icon : undefined,
              title: titleFix(title ? headingText(title, fix) : undefined),
              children: bodyText(body)
                ? [{ component: "Text", size: "M", text: bodyText(body) }]
                : [],
            };
          }));
        }

        for (const it of items) {
          const t = md(it, fix);
          const lead = t.match(/^\s*\*\*(.+?)\*\*:?\s*/);
          /*
            Тире после жирного лида — граница заголовка и тела («**Первый
            вариант** — сотрудничество с более опытной НКО…»), а не начало
            фразы. В карточке заголовок уже отделён, и тире осталось бы висеть
            перед первым словом. Правило то же, что при делении на N карточек.
          */
          const after = (lead ? t.slice(lead[0].length) : t).replace(
            /^\s*[—–-]\s+/,
            "",
          );
          /*
            Карточку начинает ЛИД — жирное начало, за которым идёт текст, либо
            заголовок. Блок целиком жирный («**Миф**», «**Пояснение**») — это
            служебный ярлык, а не заголовок карточки: он остаётся внутри
            текущей, иначе каждый ярлык плодил бы пустую карточку.
          */
          const startsCard =
            (lead && after.trim().length > 0) ||
            it.b.kind === "heading" ||
            isLabelBlock(t);
          if (startsCard || !cards.length) {
            // Хвостовая пунктуация в заголовке не нужна: «**Пример.**» → «Пример».
            const derived = lead
              ? headingText(lead[1].replace(/[.:;]+$/, ""), fix)
              : it.b.kind === "heading"
                ? headingText(t, fix)
                : undefined;
            /*
              Заголовок из комментария перебивает выведенный из жирного лида, и
              только у ПЕРВОЙ карточки: он задан один, размножать его по всем
              нельзя. Сам лид тогда уходит в тело — иначе текст, который был
              «заголовком», просто пропал бы.
            */
            const forced = cards.length === 0 ? forcedTitle : undefined;
            /*
              «Пример в заголовок» — это НЕ новый заголовок, а перенос ярлыка,
              который уже стоит жирным в начале абзаца («**Пример.** Во время
              аудита…»). Раз он уехал в заголовок, в теле его быть не должно:
              иначе слово читается дважды подряд. Отличаем от «добавь заголовок
              X», где X приходит со стороны, а жирный лид — настоящий текст,
              терять который нельзя.
            */
            const movedLead =
              cards.length === 0 &&
              explicitTitle(dir) === undefined &&
              Boolean(lead) &&
              sameLabel(labelToTitle(dir), lead![1]);
            /*
              Блок-ярлык («Важно:») — это заголовок, а не текст. Если заголовок
              уже задан комментарием, ярлык просто выбрасываем: иначе слово
              стоит дважды — заголовком и первой строкой тела.
            */
            const labelOnly = isLabelBlock(t);
            const title = titleFix(
              forced ?? (labelOnly ? labelAsTitle(t) : derived),
            );
            /*
              Блок, обёрнутый в жирный ЦЕЛИКОМ, — это метка «важное утверждение»,
              которой источник помечал заголовок. С явным заголовком метка лишняя:
              акцент несут карточка и заголовок, а жирное тело целиком читается как
              ошибка вёрстки. Поэтому у такого лида снимаем жирность.

              Жирные вставки ВНУТРИ обычного текста не трогаем: там это смысловое
              выделение, а не метка.
            */
            const rest = labelOnly
              ? ""
              : movedLead
                ? after
                : forced
                  ? lead && !after.trim()
                    ? lead[1]
                    : t
                  : lead
                  ? after
                  : it.b.kind === "heading"
                    ? ""
                    : t;
            const icon = iconOf(it);
            /*
              У списка, таблицы и картинки СВОЕГО текста нет — md() для них
              пустой, он читает поля text/md, которых у этих видов не бывает.
              Раньше такой блок, попав в карточку ПЕРВЫМ, исчезал молча: rest
              пустой → тело пустое → контент терялся. Рендерим его как есть.

              Пустое тело законно только у заголовка (он ушёл в title) и у
              блока, чей текст целиком стал заголовком.
            */
            const ownText =
              it.b.kind !== "list" && it.b.kind !== "table" && it.b.kind !== "image";
            cards.push({
              component: "General Card",
              orientation: "Vertical",
              bgColor: bg,
              icon: mods.icon && icon ? icon : undefined,
              title,
              children:
                bodyText(rest) && !sameAsTitle(title, rest)
                  ? [{ component: "Text", size: "M", text: bodyText(rest) }]
                  : ownText
                    ? []
                    : plainNodes(it, fix, true),
            });
          } else {
            const last = cards[cards.length - 1] as Extract<
              Node,
              { component: "General Card" }
            >;
            last.children.push(...plainNodes(it, fix, true));
          }
        }
        /*
          Автоматика делит по заголовкам и жирным лидам и часто САМА даёт
          нужное число — тогда просьба исполнена, и заметка была бы ложной
          тревогой. Сообщаем, только если число реально разошлось.
        */
        return want && cards.length !== want
          ? [
              ...withNumbers(cards),
              {
                component: "note" as const,
                text: `просили ${want} карточек, получилось ${cards.length} — проверьте деление`,
              },
            ]
          : withNumbers(cards);
      }

      case "Accordion": {
        /*
          Новый аккордеон начинает заголовок ВЕРХНЕГО в группе уровня (обычно h3
          с формулировкой мифа). Заголовки помельче («Кейс из практики», h4) —
          часть ответа и уходят внутрь тела, а не отрываются в отдельный вопрос.
        */
        /*
          «Пояснение» из аккордеона убираем всегда. Это строительные леса
          исходного текста: внутри аккордеона ответ и ЕСТЬ пояснение, ярлык
          только шумит. «Миф» и «Правда» оставляем — они несут вердикт, без них
          читатель не поймёт, подтверждают утверждение или опровергают.
        */
        const items2 = items.filter((it) => !isExplainLabel(md(it)));

        /*
          Заголовки, названные в комментарии, вопросом аккордеона не становятся:
          дизайнер попросил превратить их в жирный текст внутри ответа.
        */
        const boldNames = headingsToBold(dir);
        const isBoldHeading = (it: Item) =>
          it.b.kind === "heading" &&
          boldNames.some((n) => roughlySame(n, headingText(md(it, fix), fix)));

        const levels = items2
          .filter((it) => it.b.kind === "heading" && !isBoldHeading(it))
          .map((it) => (it.b as { level: number }).level);
        const topLevel = levels.length ? Math.min(...levels) : 0;
        const out: Node[] = [];
        let q: string | null = null;
        let body: Node[] = [];
        const flush = () => {
          if (q === null) return;
          out.push({
            component: "Accordion",
            state: mods.state === "Expanded" ? "Expanded" : "Collapsed",
            question: q,
            children: body,
          });
          q = null;
          body = [];
        };
        for (const it of items2) {
          const isTop =
            it.b.kind === "heading" &&
            (it.b as { level: number }).level === topLevel &&
            !isBoldHeading(it);
          if (isTop) {
            flush();
            q = headingText(md(it, fix), fix);
          } else if (q !== null && it.b.kind === "heading") {
            /*
              ВНУТРИ АККОРДЕОНА ЗАГОЛОВКОВ НЕТ (решение дизайнера). Подписи
              вроде «Как действовать» и «Результат» — жирная строка тела, а не
              Heading: настоящий заголовок здесь один, это сам вопрос
              аккордеона, и второй уровень с ним только спорит.
            */
            body.push({
              component: "Text",
              size: "M",
              text: `**${headingText(md(it, fix), fix)}**`,
            });
          } else if (q !== null) {
            // Тело аккордеона — внутри компонента: Body L там не используется.
            body.push(...fixBodyNodes(plainNodes(it, fix, true)));
          } else {
            out.push(...plainNodes(it, fix));
          }
        }
        flush();
        /*
          Число аккордеонов задаётся заголовками источника, а не комментарием:
          деление по количеству тут не автоматизировано. Но молчать нельзя —
          если получилось не столько, сколько просили, дизайнер должен узнать
          об этом сразу, а не искать глазами.
        */
        const wantAcc = splitCount(dir);
        return wantAcc && out.length !== wantAcc
          ? [
              ...out,
              {
                component: "note" as const,
                text: `просили ${wantAcc} аккордеонов, получилось ${out.length} — деление идёт по заголовкам источника, проверьте`,
              },
            ]
          : out;
      }

      case "Quote": {
        /*
          В группе может быть НЕСКОЛЬКО цитат (несколько строк авторства подряд:
          «Имя, должность в Компании» → речь → следующее «Имя, …»). Каждая строка
          авторства открывает новую цитату. Строку разбираем на имя (до первой
          запятой) и должность+компанию (после). Компания-Яндекс даёт круглый
          логотип; организация из ссылки — прямоугольный.

          «Убери кавычки» в комментарии — снимаем « » вокруг речи.
        */
        const dropQuotes = /кавыч/i.test(dir.comment || "");
        const stripQuotes = (t: string) =>
          dropQuotes ? t.replace(/^\s*[«"„“]+|[»"“”]+\s*$/g, "").trim() : t;

        const parsed = items.map((it) => {
          const t = md(it).trim();
          /*
            Хвостовая ссылка может быть обёрнута в жирный («…, **[Мастер
            ОК](ссылка)**»). Без запаса на звёздочки строка «не заканчивалась
            ссылкой», и автор с организацией уезжали в тело цитаты.

            После ссылки часто остаётся ХВОСТИК ПУНКТУАЦИИ: закрывающая кавычка,
            если название в кавычках разорвано ссылкой пополам («…, *Ц*[ентр
            адаптации людей с инвалидностью «Мастер ОК](ссылка)*»*»), или
            двоеточие перед речью («Ирина Осипова, руководитель ООРДИ
            [«Созвездие»](ссылка)*:*»). Строка тогда кончается не ссылкой, и
            авторство не опознавалось — подпись уезжала в текст цитаты.
          */
          const head = t
            .replace(
              new RegExp(
                `\\s*[*_]{0,2}${LINK_RE.source}[*_]{0,2}\\s*[»"“”:;,.]?\\s*[*_]{0,2}\\s*$`,
              ),
              "",
            )
            .trim();
          /*
            Ссылка может обнимать ВСЮ строку авторства («**[Денис Роза,
            основатель… «Перспектива»](ссылка)**») — тогда от строки после
            снятия хвостовой ссылки не остаётся ничего, и имя надо брать из
            текста самой ссылки.
          */
          const bare = stripEmph(stripLink(head || t));
          /*
            То же самое, но БЕЗ отрезанной хвостовой ссылки: в ней обычно и
            названа организация («…специалист по социальной работе [центра
            адаптации людей с инвалидностью Мастер ОК](ссылка)»). Для
            распознавания строки авторства она мешает (длина, точки), а для
            самой подписи нужна — из неё берём должность вместе с местом работы.
          */
          const full = stripMarks(stripLink(t));
          return {
            it,
            text: t,
            bare,
            full,
            isLinkOnly:
              it.b.kind === "paragraph" &&
              LINK_RE.test(t) &&
              !stripEmph(t.replace(LINK_RE, "")),
            /*
              Строка авторства «Имя, должность в Компании»: либо ЗАГОЛОВОК
              (парсер часто повышает такие строки в h3), либо абзац целиком
              курсивом/жирным. Ключ — запятая между именем и должностью.

              Плюс два ограничителя, без которых целый абзац речи, набранный
              курсивом, принимался за автора и рвал цитату надвое: строка
              авторства КОРОТКАЯ и не содержит конца предложения внутри.
            */
            looksAuthor:
              bare.includes(",") &&
              bare.length <= 140 &&
              !/[.!?]\s+\p{Lu}/u.test(bare) &&
              (it.b.kind === "heading" ||
                (it.b.kind === "paragraph" &&
                  (/^[*_]{1,2}.+[*_]{1,2}$/.test(head) ||
                    /*
                      «Татьяна Самбурова, руководитель отдела…, **[Мастер
                      ОК](ссылка)**» — строка авторства без общего курсива, зато
                      с организацией-ссылкой в хвосте. Раньше такая строка
                      уезжала в тело, и две цитаты слипались в одну.
                    */
                    (LINK_RE.test(t) && head !== t)))),
          };
        });

        const authorIdxs = parsed
          .map((p, i) => (p.looksAuthor ? i : -1))
          .filter((i) => i >= 0);
        // Ни одной строки авторства — вся группа как одна безымянная цитата.
        const starts = authorIdxs.length ? authorIdxs : [0];

        const out: Node[] = [];
        starts.forEach((ai, k) => {
          const end = starts[k + 1] ?? items.length;
          const hasAuthor = authorIdxs.includes(ai);
          let author: string | undefined;
          let role: string | undefined;
          if (hasAuthor) {
            const [name, ...restRole] = parsed[ai].full.split(",");
            author = name.trim() || undefined;
            // Хвостовое двоеточие («…руководитель ООРДИ «Созвездие»:») в
            // источнике вводит речь. В подписи оно ни к чему.
            role = restRole.join(",").replace(/[:;,]+\s*$/u, "").trim() || undefined;
          }
          /*
            АВТОРСТВО, СКЛЕЕННОЕ С РЕЧЬЮ В ОДИН АБЗАЦ. В источнике встречается
            «**Имя Фамилия,** **должность в Компании*** **дальше сама речь…*» —
            перевод строки потерялся ещё в исходном документе. Отдельной строки
            авторства тут нет, поэтому цитата уезжала вовсе без имени.

            Режем по разметке, а не по смыслу: имя и должность — два первых
            жирных куска, речь — всё, что после них. Не совпало — ничего не
            трогаем, останется пометка «дополнить авторство».
          */
          const glued = hasAuthor
            ? null
            : /^\s*\*\*([^*]{3,80}?),\s*\*\*\s*\*\*([^*]{3,200}?)\*{2,3}\s*([\s\S]+)$/u.exec(
                parsed[ai].text,
              );
          if (glued) {
            author = stripMarks(glued[1]);
            role = stripMarks(glued[2]);
          }

          /*
            Организация: ссылка в самой строке авторства или блок-ссылка в
            сегменте. Берём только НАЗВАНИЕ: адрес организации в выгрузке не
            нужен (решение дизайнера) — логотип разработчик скачивает файлом
            с прототипа, а не ходит по ссылке.
          */
          let orgName: string | undefined;
          let orgIdx = -1;
          const inline = hasAuthor ? parsed[ai].text.match(LINK_RE) : null;
          if (inline) orgName = inline[1].trim();
          else
            for (let j = ai; j < end; j++)
              if (orgIdx < 0 && parsed[j].isLinkOnly && (!hasAuthor || j !== ai)) {
                orgName = parsed[j].text.match(LINK_RE)![1].trim();
                orgIdx = j;
              }
          /*
            Организация чаще всего названа прямо в строке авторства и взята в
            кавычки: «…руководитель устойчивого развития торговой сети
            „Пятёрочка“». Ссылки при этом нет — раньше такая цитата уезжала без
            организации вовсе. Кавычки и есть признак имени собственного, гадать
            по остальному тексту не нужно.
          */
          const quoted = hasAuthor
            ? /[«„"]([^»“"]{2,60})[»“"]/u.exec(stripEmph(parsed[ai].bare))?.[1]
            : undefined;
          /*
            Кавычки — запасной признак, а не главный: если организация уже
            названа ССЫЛКОЙ, она и есть организация. Иначе в строке «Алла
            Сотникова, куратор проекта «Трудоустройство», [фонд борьбы с
            инсультом ОРБИ](…)» организацией становилось название проекта, а
            настоящий фонд пропадал — и страж потерь справедливо ругался.
          */
          if (quoted && !inline) orgName = quoted.trim();
          /*
            Ссылка может стоять на ВСЕЙ строке авторства («Денис Роза,
            основатель… в РООИ «Перспектива»»). Тогда название организации — то,
            что в кавычках, а не вся строка: иначе логотип ищется по фразе
            с именем и должностью и, конечно, не находится.
          */
          if (orgName && orgName.includes(",")) {
            const inQuotes = /[«„"]([^»“"]{2,60})[»“"]/u.exec(orgName)?.[1];
            if (inQuotes) orgName = inQuotes.trim();
          }

          /*
            Аффилиация одним полем logo: «yandex» — круглый знак Яндекса,
            иначе имя файла логотипа организации. Отдельного флага yandex нет
            (замечание разработчика: одно понятие — одно поле).
          */
          const yandex =
            Boolean(mods.yandex) || mentionsYandex([author ?? "", role ?? ""]);
          const org = yandex ? "Яндекс" : (orgName ?? "");
          const logo = yandex ? "yandex" : orgName ? findSlug(orgName, logoIndex) : undefined;
          const photo = author ? findPhotoSlug(author, avatarIndex) : undefined;

          /*
            ОРГАНИЗАЦИЯ ВСЕГДА ВИДНА В ДОЛЖНОСТИ (решение дизайнера). По одному
            логотипу читатель фонд не опознает, поэтому строка должности обязана
            называть место работы словами: «руководитель проектов, Фонд борьбы
            с лейкемией». Чаще всего организация уже стоит в самой строке
            авторства — тогда ничего не дописываем, проверяем по буквам.
            У цитаты без автора подписью работает само название организации
            (см. Quote), второй раз его писать не нужно.
          */
          const roleText =
            author && org && !flatten(role ?? "").includes(flatten(org))
              ? role
                ? `${role}, ${org}`
                : org
              : role;

          // Речь: абзацы сегмента, кроме строки авторства и блока-ссылки.
          // Список внутри речи раскрываем в пункты-строки «• …».
          const speech: string[] = [];
          parsed.slice(ai, end).forEach((p, j) => {
            if ((hasAuthor && j === 0) || ai + j === orgIdx) return;
            if (p.it.b.kind === "list")
              p.it.b.items.forEach((li) => speech.push("• " + stripQuotes(liText(p.it, li))));
            else {
              // Склеенный абзац: авторство уже забрали, в речь идёт остаток.
              const raw = glued && j === 0 ? glued[3] : p.text;
              const s = stripQuotes(stripMarks(raw));
              if (s) speech.push(s);
            }
          });

          /*
            Цитата обязана быть полной: имя, должность, организация, логотип и
            фото. Чего не хватает — пишем прямо в превью, чтобы дизайнер видел
            дыру, а не искал её глазами в выгрузке.
          */
          const missing = [
            !author && "имя",
            !role && "должность",
            !org && "организация",
            org && !logo && `логотип «${org}» не найден в каталоге`,
            author && !photo && "фото автора",
          ].filter(Boolean) as string[];

          out.push({
            component: "Quote",
            size: mods.size === "S" ? "S" : "L",
            author,
            role: roleText,
            org,
            logo,
            photo,
            paragraphs: speech,
          });
          if (missing.length)
            out.push({ component: "note", text: `Дополнить авторство: ${missing.join(", ")}` });
        });
        return out;
      }

      case "Text":
        return items.map((it): Node =>
          // size=Phrase остаётся от старой разметки, когда фраза была вариантом
          // Text. Теперь это отдельный компонент Phrase — так и собираем.
          mods.size === "Phrase"
            ? { component: "Phrase", size: "L", text: md(it, fix) }
            : {
                component: "Text",
                size: (["XL", "L", "M", "S"] as const).includes(mods.size as "L")
                  ? (mods.size as TextSize)
                  : "L",
                text: md(it, fix),
              },
        );

      case "Phrase": {
        const size = mods.size === "M" ? "M" : "L";
        // «Это одна фраза» в комментарии — слить все выделенные блоки в ОДИН
        // компонент врезки (абзацы внутри разделяем пустой строкой).
        if (wantsOnePhrase(dir)) {
          const text = items.map((it) => md(it, fix)).filter(Boolean).join("\n\n");
          return [{ component: "Phrase", size, text }];
        }
        return items.map((it) => ({ component: "Phrase" as const, size, text: md(it, fix) }));
      }

      case "Heading":
        return items.map((it) => ({
          component: "Heading" as const,
          level: (["H2", "H3", "H4", "H5"] as const).includes(mods.level as "H2")
            ? (mods.level as HeadingLevel)
            : "H2",
          /*
            Заголовком часто помечают ОДНОПУНКТОВЫЙ список: источник оформил
            подзаголовок маркером. У списка своего text нет, md() отдаёт пустую
            строку — заголовок получался пустым и тихо пропадал. Берём текст
            пунктов.
          */
          text: headingText(
            it.b.kind === "list"
              ? it.b.items.map((li) => applyFix(liText(it, li), fix)).join(" ")
              : md(it, fix),
            fix,
          ),
          // Заголовок мог быть сделан из абзаца — тогда якоря в источнике нет,
          // его посчитает проход по документу.
          anchor: it.b.kind === "heading" ? it.b.anchor : undefined,
        }));

      case "List": {
        const marker =
          mods.marker === "Number" ? "Number" : mods.marker === "Icon" ? "Icon" : "Dot";
        const icon = marker === "Icon" ? listItemIcon(dir) : undefined;
        const item = (text: string): Node => ({
          component: "List Item",
          size: "L",
          type: marker,
          ...(icon ? { icon } : {}),
          text,
        });
        /*
          ПУНКТ ИЗ ДВУХ СТРОК. Источник разложил пункт на заголовок-ссылку и
          абзац-описание — по просьбе «ссылка, потом после переноса строки
          текст» они снова один пункт: заголовок открывает пункт, следующие
          абзацы дописываются к нему с новой строки.
        */
        const kids: Node[] = [];
        if (wantsLinePairs(dir)) {
          const lines: string[][] = [];
          for (const it of items) {
            const text = it.b.kind === "list" ? "" : md(it, fix);
            if (it.b.kind === "heading" || !lines.length) lines.push([]);
            if (it.b.kind === "list")
              it.b.items.forEach((li) => lines[lines.length - 1].push(liText(it, li)));
            else if (text.trim()) lines[lines.length - 1].push(text);
          }
          kids.push(...lines.filter((l) => l.length).map((l) => item(l.join("\n"))));
        } else {
          for (const it of items) {
            if (it.b.kind === "list") it.b.items.forEach((li) => kids.push(item(liText(it, li))));
            else kids.push(item(md(it, fix)));
          }
        }
        const want = listCount(dir);
        return [
          { component: "Stack", ordered: marker === "Number", children: kids },
          // Просили N пунктов, а вышло другое — молчать нельзя (см. аккордеоны).
          ...(want && kids.length !== want
            ? [
                {
                  component: "note" as const,
                  text: `просили ${want} пунктов, получилось ${kids.length} — проверьте`,
                },
              ]
            : []),
        ];
      }

      /*
        КВИЗ. Источник пишет самопроверку всегда одинаково: вопрос (заголовок
        или абзац целиком жирным) → список вариантов → абзац-ярлык «Ответ» →
        разбор. Верные варианты помечены ЖИРНЫМ прямо в источнике, поэтому
        правильность мы ЧИТАЕМ, а не угадываем по тексту разбора.

        Жирность у верного варианта снимаем: иначе ответ виден до проверки.
      */
      case "Quiz": {
        const isAnswerLabel = (t: string) => /^[*_\s]*ответ[*_\s:.]*$/iu.test(t.trim());
        /*
          ФОРМАТ «СИТУАЦИЯ» (М4). В источнике каждый квиз выглядит так:
            заголовок «Ситуация»            → служебный ярлык, в результат не идёт;
            один-три абзаца                 → сам сценарий;
            жирный абзац с «?»              → вопрос;
            жирный ярлык («Работодателя»)   → вариант ответа,
              следующий абзац                 → разбор ИМЕННО этого варианта;
            жирная «Обратная связь»         → общий разбор до конца квиза.

          Верный вариант в источнике НИКАК не помечен — его видно только из
          общего разбора («это зона ответственности работодателя»). Поэтому он
          берётся из комментария директивы строкой «Верные: НКО, Работодателя…»
          — по одному имени на квиз, по порядку. Так решение видно дизайнеру и
          правится им же, а не спрятано в коде.
        */
        /*
          Ярлык кейса. Номер («Ситуация 2») в счёт не идёт: это тот же
          служебный ярлык, просто второй по счёту в главе.
        */
        const isSituationLabel = (t: string) =>
          /^[*_\s]*ситуац\p{L}*\s*\d*[*_\s:.]*$/iu.test(t.trim());
        const isQuizLabel = (t: string) =>
          isSituationLabel(t) || isQuestionLabel(t);
        /** Абзац, НАЧИНАЮЩИЙСЯ с жирного ярлыка: «**Вакансия:** Специалист…». */
        const WHOLE_BOLD_START = /^\s*\*\*[^*]+\*\*/;
        const isFeedbackLabel = (t: string) =>
          /^[*_\s]*(обратная\s+связь|ос)[*_\s:.]*$/iu.test(t.trim());
        /** «Верные: НКО, Работодателя» — по одному верному варианту на квиз. */
        const correctNames = (): string[] => {
          const m = /верн\p{L}*\s*[:—-]\s*([^\n]+)/iu.exec(dir.comment || "");
          return m ? m[1].split(/\s*[,;]\s*/).map((s) => s.trim()).filter(Boolean) : [];
        };
        /*
          Имя верного варианта можно писать коротко: «по слуху» вместо «Люди с
          инвалидностью по слуху». Поэтому сверяем и целиком (с запасом на
          опечатку), и на вхождение — дизайнеру не придётся копировать длинные
          формулировки из источника.
        */
        const isWanted = (option: string, want: string) =>
          roughlySame(option, want) ||
          normName(option).includes(normName(want));
        const WHOLE_BOLD = /^\s*\*\*([\s\S]+)\*\*\s*$/;
        const unbold = (t: string) => WHOLE_BOLD.exec(t.trim())?.[1] ?? t;
        const stripBold = (t: string) => t.replace(/\*\*/g, "").trim();
        const isQuestionBlock = (it: Item) =>
          it.b.kind === "heading" || WHOLE_BOLD.test(md(it, fix).trim());

        /*
          ФОРМАТ С РАЗБОРОМ НА КАЖДЫЙ ВАРИАНТ (М3). В источнике:
            нумерованный пункт     → вопрос-сценарий;
            маркированный пункт     → вариант ответа (жирный — снимаем);
            абзац «ОС: …» следом    → разбор ИМЕННО этого варианта.
          Верный вариант — тот, чей разбор начинается с «Верно» (не «Неверно»).
          Каждый нумерованный пункт открывает новый квиз.
        */
        const OS_RE = /^\s*(?:\*\*)?\s*ОС\s*[:.]/iu;
        const stripOS = (t: string) =>
          stripBold(t.replace(/^\s*(?:\*\*)?\s*ОС\s*[:.]\s*(?:\*\*)?\s*/iu, ""));
        const isOS = (it: Item) => it.b.kind !== "list" && OS_RE.test(md(it, fix).trim());
        const hasPerOption = items.some(isOS);

        /*
          ФОРМАТ «ТЕМА → ВАРИАНТЫ → ОБРАТНАЯ СВЯЗЬ» (М3). В источнике:
            заголовок «Зрение»            → тема, она же вопрос квиза;
            список                        → варианты, ЖИРНЫЕ — верные;
            заголовок «Обратная связь»    → служебный ярлык, в результат не идёт;
            абзацы за ним                 → разбор.

          Здесь верные варианты помечены в самом источнике жирным, поэтому
          строка «Верные: …» в комментарии не нужна. Жирность с текста
          снимается — она была пометкой для нас, а не выделением для читателя.
        */
        /*
          ФОРМАТ «РАЗБОР КАЖДОГО ВАРИАНТА» (М6.2). В источнике:

            заголовок «Вопрос 1»                    → начало квиза;
            абзац под ним                            → сам вопрос;
            список                                   → варианты ответа;
            заголовок «Обратная связь к варианту 2»  → разбор ИМЕННО этого
            и абзацы за ним                            варианта.

          Верный вариант виден из разбора: он начинается со слова «Верно».
          Гадать не нужно, и строка «Верные: …» тут не обязательна — но если
          она есть, слово дизайнера сильнее.
        */
        const OPT_FEEDBACK =
          /^[*_\s]*обратн\p{L}*\s+связ\p{L}*\s+к\s+вариант\p{L}*\s*(\d+)/iu;
        const optFeedbackNo = (it: Item) =>
          it.b.kind === "heading"
            ? Number(OPT_FEEDBACK.exec(md(it, fix))?.[1] ?? 0)
            : 0;

        if (items.some((it) => optFeedbackNo(it) > 0)) {
          type Opt = NonNullable<Extract<Node, { component: "Quiz" }>["items"]>[number];
          type Q = { title: string; qParts: string[]; options: Opt[] };
          const quizzes: Q[] = [];
          let cur: Q | null = null;
          let optIdx = -1;

          for (const it of items) {
            const raw = md(it, fix).trim();
            if (!raw && it.b.kind !== "list") continue;

            const no = optFeedbackNo(it);
            if (no > 0) {
              optIdx = no - 1;
              continue;
            }
            if (it.b.kind === "heading") {
              // Ярлык («Вопрос 1») названием квиза не становится — см. isQuizLabel.
              const head = headingText(raw, fix);
              cur = {
                title: isQuizLabel(head) ? "" : head,
                qParts: [],
                options: [],
              };
              quizzes.push(cur);
              optIdx = -1;
              continue;
            }
            if (!cur) continue;
            if (it.b.kind === "list") {
              cur.options.push(
                ...it.b.items.map((li) => ({
                  text: stripBold(applyFix(liText(it, li), fix).trim()),
                })),
              );
              continue;
            }
            if (optIdx >= 0 && cur.options[optIdx]) {
              const o = cur.options[optIdx];
              o.feedback = o.feedback ? `${o.feedback}\n\n${stripBold(raw)}` : stripBold(raw);
            } else cur.qParts.push(stripBold(raw));
          }

          const names = correctNames();
          const out: Node[] = quizzes
            .filter((q) => q.options.length)
            .map((q, i) => {
              const want = names[i];
              const byNum = want && /^\d+$/.test(want) ? Number(want) : 0;
              const options = q.options.map((o, k) => {
                const right = want
                  ? byNum
                    ? k === byNum - 1
                    : isWanted(o.text, want)
                  : /^\s*верно\b|^\s*верно[.,!]/iu.test(o.feedback ?? "");
                return right ? { ...o, correct: true } : o;
              });
              return {
                component: "Quiz" as const,
                ...(q.title ? { title: q.title } : {}),
                question: q.qParts.filter(Boolean).join("\n\n"),
                mode: (options.filter((o) => o.correct).length > 1
                  ? "multiple"
                  : "single") as "single" | "multiple",
                items: options,
              };
            });
          const wantQuiz = quizCount(dir);
          return wantQuiz && out.length !== wantQuiz
            ? [
                ...out,
                {
                  component: "note",
                  text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
                },
              ]
            : out;
        }

        /*
          ФОРМАТ «КРУЖКИ» (М5.2, М5.3). Самый распространённый вид самопроверки
          в источнике — 106 вариантов в двух модулях:

            заголовок «Ситуация 1. …»          → название квиза (title);
            абзацы под ним                      → сценарий, он же вопрос;
            «**Ваши действия:**»                → служебный ярлык, в результат
                                                  не идёт (что делать — и так
                                                  ясно из вариантов);
            «◯ Написать сотруднику: …»          → вариант ответа, кружок снимаем;
            «**Обратная связь**»                → дальше общий разбор.

          Отличие от формата «Ситуация» (М4): там вариант помечался ЖИРНЫМ и у
          каждого был свой разбор. Здесь вариант помечен кружком, а разбор один
          на квиз — поэтому это отдельная ветка, а не расширение старой.

          Верный вариант в источнике не помечен: он читается только из разбора.
          Берётся из комментария строкой «Верные: …» — по одному на квиз, по
          порядку. Номером («Верные: 2, 4, 1») короче: варианты здесь — длинные
          реплики, копировать их в комментарий неудобно.
        */
        const CIRCLE = /^\s*[◯○●]\s*/u;
        const isCircleOption = (it: Item) =>
          it.b.kind !== "list" && CIRCLE.test(md(it, fix).trim());
        const isActionsLabel = (t: string) =>
          /^[*_\s]*(ваши\s+действия|варианты\s+действий)[*_\s:.]*$/iu.test(t.trim());

        if (items.some(isCircleOption)) {
          type Opt = NonNullable<Extract<Node, { component: "Quiz" }>["items"]>[number];
          type Q = { title: string; qParts: string[]; options: Opt[]; expl: string[] };
          const quizzes: Q[] = [];
          let cur: Q | null = null;
          let mode: "question" | "explanation" = "question";

          for (const it of items) {
            const raw = md(it, fix).trim();
            if (!raw) continue;

            if (it.b.kind === "heading") {
              // Заголовок «Обратная связь» тоже бывает — это не новый квиз.
              if (isFeedbackLabel(raw)) {
                mode = "explanation";
                continue;
              }
              cur = { title: headingText(raw, fix), qParts: [], options: [], expl: [] };
              quizzes.push(cur);
              mode = "question";
              continue;
            }
            // Кружки могут начаться и без заголовка — тогда квиз открывает первый вариант.
            if (!cur) {
              cur = { title: "", qParts: [], options: [], expl: [] };
              quizzes.push(cur);
              mode = "question";
            }
            if (isFeedbackLabel(raw)) {
              mode = "explanation";
              continue;
            }
            if (isCircleOption(it)) {
              // Разбор кончился, пошли варианты нового квиза — значит квиз новый.
              if (mode === "explanation") {
                cur = { title: "", qParts: [], options: [], expl: [] };
                quizzes.push(cur);
                mode = "question";
              }
              cur.options.push({ text: stripBold(raw.replace(CIRCLE, "")) });
              continue;
            }
            if (mode === "explanation") cur.expl.push(stripBold(raw));
            else if (!isActionsLabel(raw)) cur.qParts.push(stripBold(raw));
          }

          const names = correctNames();
          const out: Node[] = quizzes
            .filter((q) => q.options.length)
            .map((q, i) => {
              const want = names[i];
              // «Верные: 2» — номер варианта; иначе имя (целиком или куском).
              const byNum = want && /^\d+$/.test(want) ? Number(want) : 0;
              const options = q.options.map((o, k) =>
                (byNum ? k === byNum - 1 : want && isWanted(o.text, want))
                  ? { ...o, correct: true }
                  : o,
              );
              /*
                «Убираем слово „Ситуация"» — служебный ярлык убирается и из
                НАЗВАНИЯ квиза, а не только из тела: в источнике «Ситуация 1.
                Сотрудник не выходит на работу» ярлык нужен был, чтобы отделить
                кейс от прозы, а в собранном квизе он только шумит.
              */
              const drop = leadWordToDrop(dir);
              const title = drop && q.title ? stripLeadWord(q.title, drop) : q.title;
              return {
                component: "Quiz" as const,
                ...(title ? { title } : {}),
                question: q.qParts.filter(Boolean).join("\n\n"),
                mode: (options.filter((o) => o.correct).length > 1
                  ? "multiple"
                  : "single") as "single" | "multiple",
                items: options,
                ...(q.expl.length ? { explanation: q.expl.join("\n\n") } : {}),
              };
            });
          const missed = out.filter((_, i) => !names[i]).length;
          const wantQuiz = quizCount(dir);
          const notes: Node[] = [];
          if (wantQuiz && out.length !== wantQuiz)
            notes.push({
              component: "note",
              text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
            });
          if (missed)
            notes.push({
              component: "note",
              text: `не указан верный вариант у ${missed} квиз(ов) — допишите в комментарий «Верные: …»`,
            });
          return [...out, ...notes];
        }

        const isFeedbackHeading = (it: Item) =>
          it.b.kind === "heading" && isFeedbackLabel(md(it, fix));
        /** «Общая обратная связь» — разбор не одного квиза, а нескольких сразу. */
        const isSharedFeedbackLabel = (t: string) =>
          /^[*_\s]*общ\p{L}*\s+обратная\s+связь[*_\s:.]*$/iu.test(t.trim());
        const isSharedFeedbackHeading = (it: Item) =>
          it.b.kind === "heading" && isSharedFeedbackLabel(md(it, fix));
        /*
          «Разбор по вариантам: 1 → низкий, 2 → средний, 3-4 → высокий».

          Слева номера вариантов ответа, справа — слово, по которому узнаётся
          нужный кусок общего разбора («Если вы выбрали НИЗКИЙ диапазон»).
          Решение принимает дизайнер: в источнике нигде не сказано, какой ответ
          считать низким, а какой высоким.
        */
        const sharedMap = (): { nums: number[]; name: string }[] => {
          // Между «вариантам» и двоеточием дизайнер может уточнить, о каких
          // квизах речь («…в квизах 2–5:»), поэтому до двоеточия пускаем текст.
          const line = /разбор\s+по\s+вариантам[^:\n]*:\s*([^\n]+)/iu.exec(
            dir.comment || "",
          );
          if (!line) return [];
          return line[1]
            .split(/\s*[,;]\s*/)
            .map((pair) => {
              const m = /^([\d\s,и-]+?)\s*(?:→|->|—|-|:)\s*(.+)$/u.exec(pair.trim());
              if (!m) return null;
              const nums = (m[1].match(/\d+/g) ?? []).map(Number);
              // «3-4» — это диапазон вариантов, а не два номера через дефис.
              const range = /^\s*(\d+)\s*[-–—]\s*(\d+)\s*$/.exec(m[1]);
              const all = range
                ? Array.from(
                    { length: Number(range[2]) - Number(range[1]) + 1 },
                    (_, k) => Number(range[1]) + k,
                  )
                : nums;
              return all.length ? { nums: all, name: m[2].trim() } : null;
            })
            .filter((x): x is { nums: number[]; name: string } => Boolean(x));
        };
        if (items.some(isFeedbackHeading)) {
          type Opt = NonNullable<Extract<Node, { component: "Quiz" }>["items"]>[number];
          type Q = { question: string; qParts: string[]; options: Opt[]; expl: string[] };
          const quizzes: Q[] = [];
          let cur: Q | null = null;
          let mode: "question" | "explanation" = "question";
          /*
            ОБЩИЙ РАЗБОР НА НЕСКОЛЬКО КВИЗОВ (М6.1, самопроверка про масштаб).

            В источнике четыре вопроса — это ветки одного: отвечают только на
            ту, что совпала с ответом в первом вопросе. Своего разбора у веток
            нет, вместо этого в конце стоит «Общая обратная связь», а под ней
            три варианта: «Если вы выбрали низкий диапазон», «средний»,
            «высокий».

            Собираем их отдельно от квизов, а потом раскладываем разбором НА
            КАЖДЫЙ ВАРИАНТ ответа: читатель выбирает и сразу видит нужный ему
            кусок, а не ищет свой абзац глазами. Какому варианту какой разбор —
            говорит комментарий директивы (см. sharedMap ниже).
          */
          const shared: { name: string; parts: string[] }[] = [];
          let sharedCur: { name: string; parts: string[] } | null = null;
          let inShared = false;

          for (const it of items) {
            if (it.b.kind === "heading") {
              if (isSharedFeedbackHeading(it)) {
                inShared = true;
                sharedCur = null;
                continue;
              }
              if (inShared) {
                sharedCur = { name: headingText(md(it, fix), fix), parts: [] };
                shared.push(sharedCur);
                continue;
              }
              if (isFeedbackHeading(it)) {
                mode = "explanation";
                continue;
              }
              /*
                Ярлык «Ситуация» открывает новый квиз, но вопросом не
                становится: в карточке он вставал первой строкой над самим
                кейсом и ничего читателю не сообщал (решение дизайнера). Тот же
                ярлык уже убирается в соседних ветках сборки квиза.
              */
              const head = headingText(md(it, fix), fix);
              cur = {
                question: isQuizLabel(head) ? "" : head,
                qParts: [],
                options: [],
                expl: [],
              };
              quizzes.push(cur);
              mode = "question";
              continue;
            }
            if (inShared) {
              if (sharedCur) sharedCur.parts.push(stripBold(md(it, fix).trim()));
              continue;
            }
            if (!cur) continue;
            if (it.b.kind === "list") {
              /*
                Список ПОСЛЕ «Обратной связи» — часть разбора, а не варианты
                ответа. В М6.1 разбор первого вопроса перечисляет, из чего
                складывается нагрузка на команду («сопровождению участников;
                подбору вакансий; …»), и эти строки уезжали в ответы: читатель
                видел восемь вариантов вместо четырёх. Списком и оставляем —
                разбор рисуется той же разметкой, что и обычный текст.
              */
              const lines = it.b.items.map((li) =>
                applyFix(liText(it, li), fix).trim(),
              );
              if (mode === "explanation") {
                cur.expl.push(lines.map((l) => `- ${stripBold(l)}`).join("\n"));
                continue;
              }
              cur.options.push(
                ...lines.map((raw) => {
                  const correct = WHOLE_BOLD.test(raw);
                  return { text: stripBold(raw), ...(correct ? { correct: true } : {}) };
                }),
              );
              continue;
            }
            const raw = md(it, fix).trim();
            if (!raw) continue;
            if (mode === "explanation") cur.expl.push(stripBold(raw));
            else cur.qParts.push(stripBold(raw));
          }

          /*
            Верные варианты здесь помечены ЖИРНЫМ в самом источнике. Но тот же
            формат встречается и без пометок (М6.1: «Ситуация» → список →
            «Обратная связь»), и тогда решение принимает человек — строкой
            «Верные: …» в комментарии, номером или именем варианта.
          */
          const names = correctNames();
          /*
            Общий разбор → разбор на каждый вариант. Раскладываем только тем
            квизам, у которых своего разбора нет: у первого вопроса он свой, и
            подменять его нечем.
          */
          const map = shared.length ? sharedMap() : [];
          const sharedFor = (optionNo: number): string | undefined => {
            const rule = map.find((r) => r.nums.includes(optionNo));
            if (!rule) return undefined;
            const part = shared.find((s) =>
              normName(s.name).includes(normName(rule.name)),
            );
            return part?.parts.filter(Boolean).join("\n\n") || undefined;
          };
          const out: Node[] = quizzes
            .filter((q) => q.options.length)
            .map((q, i) => {
              const want = names[i];
              const byNum = want && /^\d+$/.test(want) ? Number(want) : 0;
              const marked = q.options.some((o) => o.correct)
                ? q.options
                : q.options.map((o, k) =>
                    (byNum ? k === byNum - 1 : want && isWanted(o.text, want))
                      ? { ...o, correct: true }
                      : o,
                  );
              const options = q.expl.length
                ? marked
                : marked.map((o, k) => {
                    const fb = o.feedback ?? sharedFor(k + 1);
                    return fb ? { ...o, feedback: fb } : o;
                  });
              return {
                component: "Quiz" as const,
                question: [q.question, ...q.qParts].filter(Boolean).join("\n\n"),
                mode: (options.filter((o) => o.correct).length > 1
                  ? "multiple"
                  : "single") as "single" | "multiple",
                items: options,
                ...(q.expl.length ? { explanation: q.expl.join("\n\n") } : {}),
              };
            });
          const wantQuiz = quizCount(dir);
          return wantQuiz && out.length !== wantQuiz
            ? [
                ...out,
                {
                  component: "note",
                  text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
                },
              ]
            : out;
        }

        // Формат «Ситуация» — весь квиз абзацами, без списков.
        if (items.some((it) => isSituationLabel(md(it, fix)))) {
          type Opt = NonNullable<Extract<Node, { component: "Quiz" }>["items"]>[number];
          type Q = { qParts: string[]; options: Opt[]; expl: string[] };
          const quizzes: Q[] = [];
          let cur: Q | null = null;
          let mode: "question" | "options" | "explanation" = "question";
          let lastOpt: Opt | null = null;

          for (const it of items) {
            const raw = md(it, fix).trim();
            if (!raw) continue;
            const bare = stripBold(raw);

            if (isSituationLabel(raw)) {
              // Новый квиз. Сам ярлык «Ситуация» дизайнер просил убрать.
              cur = { qParts: [], options: [], expl: [] };
              quizzes.push(cur);
              mode = "question";
              lastOpt = null;
              continue;
            }
            if (!cur) continue;

            if (isFeedbackLabel(raw)) {
              mode = "explanation";
              lastOpt = null;
              continue;
            }
            // Жирный абзац без вопросительного знака — ярлык варианта ответа.
            const isLabel = WHOLE_BOLD.test(raw) && !/\?\s*$/.test(bare);
            if (isLabel && mode !== "explanation") {
              mode = "options";
              lastOpt = { text: bare };
              cur.options.push(lastOpt);
              continue;
            }
            if (mode === "explanation") cur.expl.push(bare);
            else if (mode === "options" && lastOpt) {
              // Абзац под ярлыком — разбор этого варианта.
              lastOpt.feedback = lastOpt.feedback ? `${lastOpt.feedback}\n\n${bare}` : bare;
            } else cur.qParts.push(bare);
          }

          const names = correctNames();
          const out: Node[] = quizzes.map((q, i) => {
            const want = names[i];
            const options = q.options.map((o) =>
              want && isWanted(o.text, want) ? { ...o, correct: true } : o,
            );
            return {
              component: "Quiz",
              // Сценарий и вопрос — одним блоком: так просил дизайнер.
              question: q.qParts.filter(Boolean).join("\n\n"),
              mode: options.filter((o) => o.correct).length > 1 ? "multiple" : "single",
              items: options,
              ...(q.expl.length ? { explanation: q.expl.join("\n\n") } : {}),
            };
          });
          const missed = quizzes.filter((_, i) => !names[i]).length;
          const wantQuiz = quizCount(dir);
          const notes: Node[] = [];
          if (wantQuiz && out.length !== wantQuiz)
            notes.push({
              component: "note",
              text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
            });
          if (missed)
            notes.push({
              component: "note",
              text: `не указан верный вариант у ${missed} квиз(ов) — допишите в комментарий «Верные: …»`,
            });
          return [...out, ...notes];
        }

        /*
          ФОРМАТ «ВАКАНСИЯ» (М5). Квиз собран из абзацев и двух списков:
            «**Вакансия:** …» и «**Функции:**» + список  → вопрос-описание;
            абзац с «?»                                   → сам вопрос;
            следующий список                              → варианты ответа;
            «ОС: …» и абзацы за ним                       → общий разбор.

          Отличие от формата М3 (там тоже есть «ОС») — нумерованных списков нет:
          в М3 нумерованный пункт открывал вопрос, а разбор был у КАЖДОГО
          варианта. Здесь разбор один на квиз, а варианты лежат одним списком.

          Верный вариант, как и в М4, не помечен в источнике — берётся из
          комментария строкой «Верные: …».
        */
        const hasOrderedList = items.some((it) => it.b.kind === "list" && it.b.ordered);
        if (hasPerOption && !hasOrderedList) {
          type Opt = NonNullable<Extract<Node, { component: "Quiz" }>["items"]>[number];
          type Q = { qParts: string[]; options: Opt[]; expl: string[]; asked: boolean };
          const quizzes: Q[] = [];
          const fresh = (): Q => {
            const q: Q = { qParts: [], options: [], expl: [], asked: false };
            quizzes.push(q);
            return q;
          };
          let cur = fresh();
          let mode: "question" | "explanation" = "question";

          for (const it of items) {
            if (it.b.kind === "list") {
              const lines = it.b.items.map((li) => applyFix(liText(it, li), fix));
              // Список ПОСЛЕ вопроса — это варианты ответа, до вопроса — часть описания.
              if (cur.asked && !cur.options.length)
                cur.options = lines.map((text) => ({ text: stripBold(text) }));
              else cur.qParts.push(lines.map((l) => `• ${stripBold(l)}`).join("\n"));
              continue;
            }
            const raw = md(it, fix).trim();
            if (!raw) continue;
            if (isOS(it)) {
              mode = "explanation";
              cur.expl.push(stripOS(md(it, fix)));
              continue;
            }
            if (mode === "explanation") {
              // Новый квиз начинается, когда прошлый уже собран.
              if (cur.options.length && WHOLE_BOLD_START.test(raw)) {
                cur = fresh();
                mode = "question";
                cur.qParts.push(stripBold(raw));
              } else cur.expl.push(stripBold(raw));
              continue;
            }
            cur.qParts.push(stripBold(raw));
            if (/\?\s*$/.test(raw)) cur.asked = true;
          }

          const names = correctNames();
          const out: Node[] = quizzes
            .filter((q) => q.options.length)
            .map((q, i) => {
              const want = names[i];
              const options = q.options.map((o) =>
                want && isWanted(o.text, want) ? { ...o, correct: true } : o,
              );
              return {
                component: "Quiz",
                question: q.qParts.filter(Boolean).join("\n\n"),
                mode: options.filter((o) => o.correct).length > 1 ? "multiple" : "single",
                items: options,
                ...(q.expl.length ? { explanation: q.expl.join("\n\n") } : {}),
              };
            });
          const wantQuiz = quizCount(dir);
          const notes: Node[] = [];
          if (wantQuiz && out.length !== wantQuiz)
            notes.push({
              component: "note",
              text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
            });
          const noAnswer = out.filter((q) =>
            (q as Extract<Node, { component: "Quiz" }>).items.every((o) => !o.correct),
          ).length;
          if (noAnswer)
            notes.push({
              component: "note",
              text: `не указан верный вариант у ${noAnswer} квиз(ов) — допишите в комментарий «Верные: …»`,
            });
          return [...out, ...notes];
        }

        if (hasPerOption) {
          type Q = { qParts: string[]; options: NonNullable<Extract<Node, { component: "Quiz" }>["items"]> };
          const quizzes: Q[] = [];
          let cur: Q | null = null;
          const flush = () => {
            if (cur && cur.options.length) quizzes.push(cur);
          };
          for (let i = 0; i < items.length; i++) {
            const it = items[i];
            if (it.b.kind === "list" && it.b.ordered) {
              // Нумерованный пункт — новый вопрос.
              flush();
              cur = { qParts: it.b.items.map((li) => stripBold(liText(it, li))), options: [] };
            } else if (it.b.kind === "list") {
              // Маркированный пункт — вариант; следом может идти его «ОС».
              const text = stripBold(it.b.items.map((li) => liText(it, li)).join(" "));
              const next = items[i + 1];
              const fb = next && isOS(next) ? stripOS(md(next, fix)) : "";
              if (fb) i++; // «ОС» съели
              // Верный вариант — разбор начинается с «Верно» (не «Неверно»).
              // \b в JS не знает кириллицу, поэтому проверяем границу вручную:
              // «Верно» + знак препинания/конец, но не «Верное».
              const correct = /^\s*верно(?:[^\p{L}]|$)/iu.test(fb);
              (cur ??= { qParts: [], options: [] }).options.push({
                text,
                ...(correct ? { correct: true } : {}),
                ...(fb ? { feedback: fb } : {}),
              });
            } else if (isOS(it)) {
              // «ОС» без своего варианта — пропускаем (не мусорим в вопрос).
            } else if (cur && cur.options.length === 0) {
              // Абзац до вариантов — часть вопроса.
              const t = md(it, fix).trim();
              if (t) cur.qParts.push(stripBold(t));
            }
          }
          flush();
          const out: Node[] = quizzes.map((q) => ({
            component: "Quiz",
            question: q.qParts.filter(Boolean).join("\n\n"),
            mode: q.options.filter((o) => o.correct).length > 1 ? "multiple" : "single",
            items: q.options,
          }));
          const wantQuiz = quizCount(dir);
          return wantQuiz && out.length !== wantQuiz
            ? [...out, { component: "note", text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте` }]
            : out;
        }

        const answers = items
          .map((it, i) => (it.b.kind !== "list" && isAnswerLabel(md(it)) ? i : -1))
          .filter((i) => i >= 0);

        /* Границы каждого квиза: список вариантов и начало вопроса перед ним. */
        const bounds = answers.map((a) => {
          let opts = a - 1;
          while (opts >= 0 && items[opts].b.kind !== "list") opts--;
          let start = opts - 1;
          while (start >= 0 && isQuestionBlock(items[start])) start--;
          return { answer: a, opts, start: start + 1 };
        });

        const flat = (from: number, to: number): string[] => {
          const out: string[] = [];
          for (let i = from; i < to && i < items.length; i++) {
            const it = items[i];
            if (it.b.kind === "list")
              out.push(it.b.items.map((li) => `• ${liText(it, li)}`).join("\n"));
            else if (md(it, fix).trim()) out.push(md(it, fix).trim());
          }
          return out;
        };

        const out: Node[] = [];
        bounds.forEach((b, i) => {
          if (b.opts < 0 || b.start > b.opts - 1) return;
          const heads = items
            .slice(b.start, b.opts)
            .map((it) =>
              it.b.kind === "heading"
                ? headingText(md(it, fix), fix)
                : unbold(md(it, fix)).trim(),
            )
            .filter(Boolean);
          const optionsBlock = items[b.opts].b;
          const options =
            optionsBlock.kind === "list"
              ? optionsBlock.items.map((li) => {
                  const raw = liText(items[b.opts], li);
                  const correct = WHOLE_BOLD.test(raw.trim());
                  return { text: unbold(raw).trim(), ...(correct ? { correct } : {}) };
                })
              : [];
          const end = bounds[i + 1]?.start ?? items.length;
          const explanation = flat(b.answer + 1, end).join("\n\n");
          out.push({
            component: "Quiz",
            /*
              Все блоки-заголовки квиза идут В ВОПРОС, даже если их несколько
              (сценарий-кейс + сам вопрос). Отдельное поле description не
              заводим: у остальных квизов его нет, единообразнее держать весь
              текст вопросом. Перенос между блоками значащий — сохраняем «\n\n».
            */
            question: heads.join("\n\n"),
            // Режим выбора не задаётся руками — он и есть число верных вариантов.
            mode: options.filter((o) => o.correct).length > 1 ? "multiple" : "single",
            items: options,
            ...(explanation ? { explanation } : {}),
          });
        });

        const wantQuiz = quizCount(dir);
        return wantQuiz && out.length !== wantQuiz
          ? [
              ...out,
              {
                component: "note",
                text: `просили ${wantQuiz} квизов, получилось ${out.length} — проверьте`,
              },
            ]
          : out;
      }

      case "Prompt": {
        const head = items[0] ? md(items[0]).replace(/\*\*/g, "") : "Заготовка";
        const text = items.slice(1).map((it) => md(it)).join("\n\n");
        return [
          {
            component: "Prompt",
            title: head,
            subtitle: "Проверьте текст перед использованием — вслепую применять нельзя.",
            text: text || head,
          },
        ];
      }

      case "Video": {
        /*
          Видео задаётся ссылкой. Источник часто пишет её дважды — автоссылкой
          внутри markdown-ссылки: «<[https://…](https://…)>». Поэтому из адреса
          надо исключить и скобки, и угловые: без этого в href уезжала половина
          разметки вместе со вторым адресом.
        */
        const url = items
          .map((it) => md(it))
          .join(" ")
          .match(/(?:\]\()?(https?:\/\/[^)\s\][<>]+)/)?.[1];
        return [{ component: "Video", ...(url ? { href: url } : {}) }];
      }

      default:
        return [
          { component: "note", text: `${dir.targetLabel}: сборки пока нет` },
          ...items.flatMap((it) => plainNodes(it, fix)),
        ];
    }
  };

  const allGroups = groupsOfDoc(sections, directiveAt);
  const summary = allGroups.find(isPageSummary);

  const children: (SectionNode | Node)[] = [];
  /*
    ВСТУПЛЕНИЕ СТРАНИЦЫ — в своём Section Container (проверено по Figma,
    узел 7054:4797): в его слоте лежат лид Text XL и Page Summary.

    Раньше Page Summary клали в корень документа, мимо секций. Дизайнер изменил
    макет — и правило вслед за ним: у вступления такая же секция-обёртка, как у
    любого раздела, иначе отступ сверху берётся не оттуда.
  */
  if (summary)
    children.push({
      component: "Section Container",
      children: mergeSiblings(guarded(summary)),
    });

  /*
    Секция, чей собственный заголовок h2 ушёл ВНУТРЬ директивы (стал вопросом
    аккордеона или заголовком карточки), перестаёт быть секцией: заголовка у неё
    больше нет. Отдельный Section Container дал бы пустую отбивку и разорвал бы
    то, что дизайнер собирал одним блоком. Содержимое продолжает предыдущую
    секцию — ту, чей заголовок уцелел.

    Цель «Заголовок» не считается поглощением: там заголовок остаётся собой.
  */
  const absorbed = (si: number): boolean => {
    const first = sections[si]?.blocks[0];
    if (!first || first.kind !== "heading") return false;
    const d = directiveAt?.(si, 0);
    return isActive(d) && Boolean(d?.target) && d?.target !== "Heading";
  };

  const hostOf = (si: number): number => {
    let s = si;
    while (s > 0 && absorbed(s)) s -= 1;
    return s;
  };

  // Группа принадлежит секции, где началась: директива не рвётся границей h2.
  const bySection = new Map<number, PlacedGroup[]>();
  for (const g of allGroups) {
    if (g === summary) continue;
    const host = hostOf(g.si);
    const list = bySection.get(host);
    if (list) list.push(g);
    else bySection.set(host, [g]);
  }

  sections.forEach((sec, i) => {
    const kids: Node[] = [];
    for (const g of bySection.get(i) ?? []) {
      const nodes = guarded(g);
      if (needsCard(g))
        kids.push({
          component: "Block",
          orientation: cardOrientation(g),
          join: wantsSameContainer(g.dir) || undefined,
          children: nodes,
        });
      else kids.push(...nodes);
    }
    /*
      Секция без содержимого не рисуется: её заголовок ушёл внутрь директивы,
      начавшейся выше (стал вопросом аккордеона). Пустой Section Container дал
      бы лишнюю отбивку на пустом месте.
    */
    if (!kids.length) return;
    children.push({
      component: "Section Container",
      anchor: sec.anchor,
      children: mergeSiblings(kids),
    });
  });

  // Правила системы применяем в самом конце, одинаково для всех источников.
  return normalizeDoc({ module: moduleId, children });
}

/*
  НОРМАЛИЗАЦИЯ ДЕРЕВА — правила системы, которые не зависят от директив.

  Карточка внутри аккордеона: у аккордеона свой тонированный фон, и цветная
  карточка на нём спорит с ним же. Поэтому внутри аккордеона карточка всегда
  БЕЛАЯ, а лежит в Stack — том самом стеке с равным шагом.

  Отдельным проходом, а не в месте сборки: правило одно, а собирают дерево два
  источника (раскладка модулей и рукописный эталон). Держать его в одном месте —
  единственный способ не разъехаться.
*/
function bodyInsideAccordion(children: Node[]): Node[] {
  const out: Node[] = [];
  let stack: Node[] = [];
  const flush = () => {
    if (!stack.length) return;
    out.push({ component: "Stack", ordered: false, children: stack });
    stack = [];
  };
  for (const c of children) {
    if (c.component === "General Card") {
      // Подряд идущие карточки — в ОДИН стек, а не по контейнеру на каждую.
      stack.push({ ...c, bgColor: "white", children: normalizeNodes(c.children) });
      continue;
    }
    // Цитата внутри аккордеона — то же правило: живёт в стеке, не россыпью.
    // И размер тут S: спокойный вариант без подложки, чтобы не спорить с фоном.
    if (c.component === "Quote") {
      stack.push({ ...c, size: "S" });
      continue;
    }
    flush();
    out.push(normalizeNode(c));
  }
  flush();
  return out;
}

/*
  ОДИН ПУНКТ, И ТОТ ЖИРНЫЙ, — это не список, а подпись к абзацу под ним.

  В источнике так оформлены типичные вопросы работодателя («• Расскажите о
  себе», следом абзац с разбором) и похожие ярлыки. Перечисления там нет:
  пункт ровно один, а маркер достался ему от оформления в документе. На
  странице он читается как обрывок списка, которого нет.

  Убираем маркер, а жирную строку оставляем обычным текстом того же размера.
*/
const BOLD_LINE = /^\s*\*\*([^*]+)\*\*\s*$/;

function boldLabelOfList(n: Node): Node | null {
  if (n.component !== "Stack" || n.ordered || n.children.length !== 1) return null;
  const item = n.children[0];
  if (item.component !== "List Item" || !BOLD_LINE.test(item.text)) return null;
  return { component: "Text", size: item.size, text: item.text, at: item.at };
}

function normalizeNode(n: Node): Node {
  if (n.component === "Accordion")
    return { ...n, children: bodyInsideAccordion(n.children) };

  const label = boldLabelOfList(n);
  if (label) return label;
  /*
    Размер цитаты определяется МЕСТОМ, а не желанием: S — спокойный вариант без
    подложки, он существует ради аккордеона, где кремовая подложка спорила бы с
    тонированным фоном. В самом тексте страницы цитата всегда L: там она акцент,
    её нужно заметить.

    Сюда доходят только цитаты ВНЕ аккордеона: его тело разбирает
    bodyInsideAccordion и до этой ветки не доводит.
  */
  if (n.component === "Quote") return n.size === "L" ? n : { ...n, size: "L" };
  if ("children" in n && Array.isArray(n.children))
    return { ...n, children: normalizeNodes(n.children) } as Node;
  return n;
}

const normalizeNodes = (nodes: Node[]): Node[] => nodes.map(normalizeNode);

/*
  ЯКОРЯ ЗАГОЛОВКОВ И ПОДПИСИ ТАБЛИЦ — одним проходом по документу.

  Почему не в normalizeNode: обоим правилам нужен контекст, которого у
  отдельного узла нет. Якорь обязан быть уникальным НА ВСЮ СТРАНИЦУ (по нему
  разработчик вешает id и скроллит оглавление), а подпись таблицы берётся у
  ближайшего заголовка сверху.

  Заголовок, открывающий секцию, получает якорь САМОЙ секции: это одно и то же
  место, и два разных id на одну точку только запутали бы.
*/
const RU_LAT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/** Тот же транслит, что у парсера источника, — якоря совпадают с оглавлением. */
function anchorSlug(text: string, used: Set<string>): string {
  let out = "";
  for (const ch of text.toLowerCase()) {
    if (RU_LAT[ch] !== undefined) out += RU_LAT[ch];
    else if (/[a-z0-9]/.test(ch)) out += ch;
    else if (/[\s\-–—_]/.test(ch)) out += "-";
  }
  out = out.replace(/-+/g, "-").replace(/^-|-$/g, "").slice(0, 48) || "sec";
  let s = out;
  let i = 2;
  while (used.has(s)) s = `${out}-${i++}`;
  used.add(s);
  return s;
}

function annotate(doc: Doc): Doc {
  const used = new Set<string>();
  // Ближайший заголовок сверху — из него растёт подпись таблицы.
  let lastHeading = "";

  const captionFor = (t: { header: string[] }) => {
    const cols = t.header.map((h) => stripEmph(h).trim()).filter(Boolean).join(", ");
    const head = lastHeading.trim();
    return (
      [head && `${head}.`, cols && `Столбцы: ${cols}.`].filter(Boolean).join(" ") ||
      "Таблица"
    );
  };

  /** share — якорь секции, он достаётся её первому заголовку. */
  const walk = (nodes: Node[], share?: string): Node[] => {
    let toShare = share;
    return nodes.map((n) => {
      if (n.component === "Heading") {
        const anchor = toShare ?? anchorSlug(n.anchor || n.text, used);
        toShare = undefined;
        lastHeading = n.text;
        return { ...n, anchor };
      }
      if (n.component === "Accordion") {
        lastHeading = n.question;
        return { ...n, children: walk(n.children) };
      }
      if (n.component === "General Card" && n.title) lastHeading = n.title;
      // Подпись — первым полем: её читают глазами раньше, чем строки таблицы.
      if (n.component === "Table")
        return n.caption
          ? n
          : { component: n.component, caption: captionFor(n), header: n.header, rows: n.rows };
      if ("children" in n && Array.isArray(n.children))
        return { ...n, children: walk(n.children) } as Node;
      return n;
    });
  };

  return {
    ...doc,
    children: doc.children.map((n) => {
      if ((n as SectionNode).component !== "Section Container") return walk([n as Node])[0];
      const sec = n as SectionNode;
      const anchor = sec.anchor ? anchorSlug(sec.anchor, used) : undefined;
      return { ...sec, anchor, children: walk(sec.children, anchor) };
    }),
  };
}

/** Применить правила системы ко всему документу. */
export function normalizeDoc(doc: Doc): Doc {
  return annotate({
    ...doc,
    children: doc.children.map((n) =>
      (n as SectionNode).component === "Section Container"
        ? { ...(n as SectionNode), children: normalizeNodes((n as SectionNode).children) }
        : normalizeNode(n as Node),
    ),
  });
}

/*
  РАЗМЕТКА В ВЫГРУЗКЕ — ТЕГИ, А НЕ MARKDOWN.

  Внутри инструмента текст хранится в markdown (`**жирный**`, `[текст](ссылка)`):
  так он остаётся читаемым и правится в редакторе. Но разработчик собирает
  страницы в конструкторе, и звёздочки ему не нужны — нужна явная разметка.
  Поэтому markdown переводится в теги ровно на границе выгрузки, а превью
  продолжает рендерить исходный markdown.

  Экранирование обязательно: в источнике есть и «&», и URL в угловых скобках
  («<https://…>»). Без него такой адрес в JSON выглядел бы как тег. Экранируем
  ДО вставки своих тегов, иначе экранировались бы и они.
*/
const escapeText = (t: string) =>
  t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/*
  Последняя альтернатива — тултип {{термин|описание}} или
  {{термин|Заголовок|описание}}. В выгрузке он становится тегом с тремя полями:
  видимый текст внутри, заголовок и описание — атрибутами.
*/
const INLINE_MD =
  /\[([^\]]+)\]\(([^)\s]+)\)|\*\*([^*]+)\*\*|\*([^*]+)\*|_([^_]+)_|\{\{([^{}|]+)\|([^{}|]+)(?:\|([^{}|]+))?\}\}/g;

/** В атрибут тега кавычка попасть не должна — экранируем её отдельно. */
const escapeAttr = (t: string) => escapeText(t).replace(/"/g, "&quot;");

/*
  ТЕКСТ БЛОКАМИ — абзацы и перечисления внутри одного поля.

  Вопрос квиза и разбор приходят из источника несколькими абзацами, а внутри
  бывают перечисления. Раньше всё это лежало одной строкой: абзацы разделял
  голый перенос, а пункты помечались символом «•» прямо в тексте. На странице
  пункты слипались в одну строку, а разработчик получил бы абзац вместо списка.

  Разбор один и для показа, и для выгрузки — иначе сайт и JSON разъедутся.
*/
export type TextBlock = { kind: "p" | "ul"; lines: string[] };

export function textBlocks(text: string): TextBlock[] {
  const out: TextBlock[] = [];
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith("•")) {
      const item = line.replace(/^•\s*/, "");
      const last = out[out.length - 1];
      // Идущие подряд пункты — один список, а не список на каждый пункт.
      if (last?.kind === "ul") last.lines.push(item);
      else out.push({ kind: "ul", lines: [item] });
      continue;
    }
    out.push({ kind: "p", lines: [line] });
  }
  return out;
}

/*
  То же поле в выгрузку: один абзац без пунктов уезжает как раньше, обычной
  строкой с тегами. Всё, что сложнее, — тегами блоков: <p> и <ul><li>. Поле и
  так несёт разметку (<b>, <a>), поэтому список тегами ей не чужой.
*/
export function mdBlocksToTags(text: string): string {
  const blocks = textBlocks(text);
  if (blocks.length <= 1 && blocks[0]?.kind !== "ul") return mdToTags(text);
  return blocks
    .map((b) =>
      b.kind === "ul"
        ? `<ul>${b.lines.map((l) => `<li>${mdToTags(l)}</li>`).join("")}</ul>`
        : `<p>${mdToTags(b.lines[0])}</p>`,
    )
    .join("");
}

export function mdToTags(text: string): string {
  // Метки раскурсовки — только для показа замен на сайте (<mark> с подсказкой).
  // В данные разработчику уходит ЧИСТЫЙ новый текст: убираем метки и оригинал,
  // оставляя замену (группа 1). Иначе в JSON текли бы невидимые символы U+E000
  // и задвоенный текст «замена+оригинал».
  text = text.replace(markRe(), "$1");
  let out = "";
  let last = 0;
  let m: RegExpExecArray | null;
  // Свой экземпляр: рекурсия (ссылка внутри жирного) не должна сбивать lastIndex.
  const re = new RegExp(INLINE_MD.source, "g");
  while ((m = re.exec(text))) {
    out += escapeText(text.slice(last, m.index));
    if (m[1] !== undefined) {
      const href = safeHref(m[2]);
      /*
        Внешняя ссылка помечается rel="external": по ней разработчик берёт
        компонент External Link со стрелкой, по остальным — обычную ссылку.
        Правило то же, что в превью: с протоколом — наружу, от корня — внутрь.
      */
      const rel = href && isExternalHref(href) ? ' rel="external"' : "";
      // Небезопасный протокол — ссылку не делаем, текст сохраняем.
      out += href
        ? `<a href="${escapeText(href)}"${rel}>${mdToTags(m[1])}</a>`
        : mdToTags(m[1]);
    } else if (m[3] !== undefined) {
      out += `<b>${mdToTags(m[3])}</b>`;
    } else if (m[6] !== undefined) {
      const title = m[8] !== undefined ? m[7] : undefined;
      const description = m[8] ?? m[7];
      out +=
        `<tooltip${title ? ` title="${escapeAttr(title)}"` : ""}` +
        ` description="${escapeAttr(description)}">${escapeText(m[6])}</tooltip>`;
    } else {
      out += `<i>${mdToTags(m[4] ?? m[5])}</i>`;
    }
    last = re.lastIndex;
  }
  return out + escapeText(text.slice(last));
}

