/*
  Инструкции из комментария, которые исполняются механически.

  ВНИМАНИЕ: хвост русского слова — это \p{L} с флагом u, а НЕ \w. \w в JS это
  [A-Za-z0-9_], кириллицу он не покрывает, и «убра\w*\s+жирн» молча не
  совпадал с «Убрать жирный».
*/
/*
  Удаление блока: директива без цели, чей комментарий велит убрать. Кроме
  «удалить» принимаем «убрать / убираем / убери / уберём», но НЕ когда дальше
  идёт «жирный / курсив» — это команда снять оформление (wantsUnbold ниже),
  а не выкинуть блок.
*/
const wantsDelete = (d?: Directive) => {
  if (!d) return false;
  const c = (d.comment || "").trim();
  /*
    Комментарий из ОДНОГО слова «удалить» — команда без оговорок, и компонент
    ей не мешает: дизайнер бывает сначала выбирает цель, а потом решает, что
    блок вообще не нужен. Во всех остальных случаях удаление требует, чтобы
    цель НЕ была выбрана, иначе «удалить заголовок Пояснение» (точечная чистка
    ярлыка внутри карточки) выкинуло бы всю карточку.
  */
  if (/^\s*удал\p{L}*\s*$/iu.test(c)) return true;
  if (d.target) return false;
  /*
    убра — убрать/убрал; убир — убираем/убирать; убер — убери/уберём.

    ВАЖНО: «убрать» без уточнения — это «выкинуть блок», но «убрать ссылку»,
    «убрать жирный», «убрать капс», «убрать нумерацию» — это чистки ВНУТРИ
    блока. Правило удаления идёт первым, поэтому такие уточнения надо
    исключать явно, иначе блок исчезает целиком: так пропал заголовок
    «Абилимпикс», которому просили лишь снять ссылку.
  */
  return (
    // «удал» без «и»: живой комментарий пришёл как «удаляем».
    /^\s*(удал|убра|убир|убер)/iu.test(c) &&
    !/(жирн|болд|bold|курсив|италик|italic|ссылк|линк|капс|нумерац|нумирац|номер|двоеточ|кавыч)/iu.test(
      c,
    )
  );
};
const wantsUnbold = (d?: Directive) =>
  !!d && /(убра|убир|убер|сня|без)\p{L}*\s+(жирн|болд|bold)/iu.test(d.comment || "");
/*
  Курсив просили снимать теми же словами, что и жирный («убрать курсив»,
  «убрать италик»), но шаблон ловил только «жирн» — комментарий молча не
  срабатывал. Держим оба написания: и «курсив», и «италик».
*/
const wantsUnitalic = (d?: Directive) =>
  !!d && /(убра|убир|убер|сня|без)\p{L}*\s+(курсив|италик|italic)/iu.test(d.comment || "");
/*
  «Убрать нумерацию в заголовках» — источник нумерует подряд («1. Особенности…»,
  «Пример 1. Трудоустройство…»), а в аккордеоне и карточке номер лишний.
  Касается ТОЛЬКО заголовков и вопросов, не тела текста.
*/
const wantsUnnumber = (d?: Directive) =>
  !!d && /(убра|убир|убер|сня|без)\p{L}*\s+(нумерац|нумирац|номер)/iu.test(d.comment || "");

/*
  «Пронумеровать заголовки» — обратная просьба. Источник перечисляет направления
  словами («Первое — …», «Второе направление — …»), и в вёрстке этот зачин
  выбрасывается: в ряду карточек порядок и так виден. Но иногда номер нужен явно,
  и тогда его ставит раскладка — по месту карточки в ряду, а не по тексту.

  Проверяем, что это не «убрать нумерацию»: слово «номер» есть в обеих просьбах,
  а смысл у них противоположный.
*/
const wantsNumber = (d?: Directive) =>
  !!d &&
  !wantsUnnumber(d) &&
  /(пронумер\p{L}*|нумерац\p{L}*|с\s+номер\p{L}*)/iu.test(instructionOf(d.comment || ""));

const SERVICE_WORD =
  /^(заголов\p{L}*|загловк\p{L}*|подпис\p{L}*|надпис\p{L}*|слов\p{L}*|строк\p{L}*|текст\p{L}*|блок\p{L}*|эти|все|всё)$/iu;

/*
  «Удалить заголовок Пояснение» — точечное удаление служебной подписи внутри
  директивы С целью. Правило намеренно строгое вдвойне: слова берём из
  комментария, а выбрасываем только блок, ВЕСЬ текст которого равен одному из
  них. Содержательный абзац пропасть не может.
*/
function labelsToDrop(d?: Directive): string[] {
  if (!d?.target) return [];
  const out: string[] = [];
  const re = /(?:удали|убра)\p{L}*\s+([^.;!?\n]+)/giu;
  let m: RegExpExecArray | null;
  while ((m = re.exec(d.comment || ""))) {
    for (const w of m[1].split(/[\s,]+/)) {
      const bare = w.replace(/[«»"'*_:]/g, "").trim();
      if (bare.length >= 3 && !SERVICE_WORD.test(bare)) out.push(bare.toLowerCase());
    }
  }
  return out;
}

/*
  Комментарий без фраз-удалений. Нужен, чтобы «удалить заголовок Пояснение» не
  прочиталось как «задать заголовок Пояснение»: это ровно противоположные
  намерения, а слово «заголовок» в них одно и то же.
*/
const withoutRemovals = (c: string) =>
  c
    /*
      Инструкции дизайнер часто пишет в одну строку без знаков препинания:
      «Убрать болд сделать заг Важно». Без границы фраза-удаление съедала и
      вторую инструкцию, и заголовок терялся. Ставим границу перед глаголом
      следующей инструкции.
    */
    .replace(/\s+(?=(?:сдела|добав|постав|нужн)\p{L}*)/giu, ". ")
    .replace(/(?:удали|убра|убер|сня)\p{L}*[^.;!?\n]*/giu, " ");

/*
  Просьба разбить набор на несколько карточек/аккордеонов («сделать три
  карточки», «сделать 6 аккордионов»). Деление пока не автоматизировано —
  флаг нужен, чтобы НЕ навесить один заголовок на слипшуюся карточку:
  «с заголовками 1-2-3 группа» — это три разных заголовка, а не один.
*/
const RU_NUM: Record<string, number> = {
  два: 2, две: 2, три: 3, четыре: 4, пять: 5, шесть: 6, семь: 7, восемь: 8,
};

/** Сколько карточек/аккордеонов просили сделать. undefined — не просили. */
const splitCount = (d?: Directive): number | undefined => {
  const m = /(\d+|дв[ае]|три|четыре|пять|шесть|семь|восемь)\s+(?:карточ|аккорд|аккард)/iu.exec(
    d?.comment || "",
  );
  if (!m) return undefined;
  const raw = m[1].toLowerCase();
  const n = /^\d+$/.test(raw) ? Number(raw) : RU_NUM[raw];
  return n && n >= 2 && n <= 20 ? n : undefined;
};

const wantsSplit = (d?: Directive) => splitCount(d) !== undefined;

/*
  СРАВНЕНИЕ ИМЁН ИЗ КОММЕНТАРИЯ С ТЕКСТОМ ИСТОЧНИКА — мягкое.

  Дизайнер называет заголовок по памяти и почти всегда с опечаткой
  («Альтерннативное квотировангие» вместо «Альтернативное квотирование»).
  Точное сравнение здесь означало бы молчаливый отказ — тот самый случай,
  который этот файл ловит проходами. Поэтому допускаем расхождение до пятой
  части длины: свои опечатки покрывает, чужой заголовок не притягивает.
*/
const normName = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();

/** Расстояние Левенштейна — сколько правок отделяет одну строку от другой. */
const editDistance = (a: string, b: string): number => {
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++)
      cur[j] = Math.min(
        prev[j] + 1,
        cur[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),
      );
    prev = cur;
  }
  return prev[b.length];
};

const roughlySame = (a: string, b: string): boolean => {
  const x = normName(a);
  const y = normName(b);
  if (!x || !y) return false;
  if (x === y) return true;
  const limit = Math.max(1, Math.floor(Math.max(x.length, y.length) * 0.2));
  return editDistance(x, y) <= limit;
};

/*
  «Ссылка, и потом после переноса строки текст» — в источнике пункт списка
  разложен на ДВА блока: заголовок-ссылка и абзац-описание. В списке это один
  пункт из двух строк, а не два пункта.
*/
const wantsLinePairs = (d?: Directive) =>
  /перенос\p{L}*\s+строк|с\s+новой\s+строк|новой\s+строчк/iu.test(d?.comment || "");

/*
  «Вместо галочки иконка ссылки» — у пункта списка с иконкой галочка стоит по
  умолчанию, а для перечня документов по смыслу нужна ссылка. Слово из
  комментария переводим в имя иконки; незнакомое слово оставляет галочку.
*/
const ICON_BY_WORD: [RegExp, string][] = [
  [/ссылк|линк|link/iu, "Link"],
  [/документ|файл|бумаг/iu, "FileText"],
  [/закон|прав|юрид/iu, "Scale"],
];

const listItemIcon = (d?: Directive): string | undefined => {
  const m = /иконк\p{L}*\s+([\p{L}]+)/iu.exec(d?.comment || "");
  if (!m) return undefined;
  return ICON_BY_WORD.find(([re]) => re.test(m[1]))?.[1];
};

