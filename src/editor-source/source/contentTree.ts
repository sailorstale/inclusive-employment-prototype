/** Контейнеры, чьи дети — пункты списка. Page Summary — такой же случай. */
const LIST_HOSTS = new Set(["Stack", "Page Summary"]);
const hoistListFields = (container: Record<string, unknown>): Record<string, unknown> => {
  const out = { ...container };
  delete out.ordered;
  let kids: Record<string, unknown>[] = (out.children as Record<string, unknown>[]) ?? [];
  if (!kids.length) return out;
  /*
    Смотрим только на ПУНКТЫ: у Page Summary рядом с ними лежит ещё и вводный
    текст, и по нему подъём отступал — пункты оставались с маркером.
  */
  const isItem = (k: Record<string, unknown>) => k.component === "List Item";
  const items = kids.filter(isItem);
  if (!items.length) return out;
  for (const key of ["marker", "size", "icon"]) {
    const first: unknown = items[0][key];
    if (first === undefined) continue;
    // Иконка — единственное поле, где различие пунктов осмысленно.
    if (key === "icon" && !items.every((k) => k[key] === first)) continue;
    out[key] = first;
    kids = kids.map((k) => {
      if (!isItem(k)) return k;
      const copy = { ...k };
      delete copy[key];
      return copy;
    });
  }
  /*
    children — последним полем: иначе поднятый marker оказывается ПОСЛЕ
    длинного списка пунктов, и читать выгрузку глазами неудобно.
  */
  delete out.children;
  out.children = kids;
  return out;
};

/*
  АДРЕСА УЗЛОВ ВЫГРУЗКИ. Выгрузка теряет служебные пометки инструмента («note»),
  поэтому номера узлов в ней не совпадают с номерами в дереве: всё, что стоит
  после пометки, съезжает на позицию вверх. Колонке JSON нужны номера ИСХОДНОГО
  дерева — иначе клик по компоненту на странице подсвечивал бы соседний узел.
  Дерево адресов повторяет форму выгрузки узел в узел.
*/
export type ExportPath = { path: string; children: ExportPath[] };

const cleanForExport = (
  n: Node | SectionNode,
  path: string,
  sink?: ExportPath[],
): unknown | null => {
    if ((n as Node).component === "note") return null;
    const component = (n as Node).component;
    const isSection = (n as SectionNode).component === "Section Container";
    const rename = RENAME_KEYS[component] ?? {};
    const out: Record<string, unknown> = {};
    // Адреса выживших детей — в том же порядке, что и они сами.
    const kidPaths: ExportPath[] = [];
    for (const [rawKey, v] of Object.entries(n)) {
      const k = rename[rawKey] ?? rawKey;
      // Служебные пометки инструмента: склейка конвертов и адрес блоков
      // источника. В дереве они нужны, разработчику — нет.
      if (k === "join" || k === "at") continue;
      /*
        Якорь едет ТОЛЬКО у заголовков: разработчик делает из него id элемента.
        У секции он повторял якорь её первого H2 (одно и то же место), и id
        получались неуникальными — просьба разработчика 3 августа 2026.
      */
      if (k === "anchor" && isSection) continue;
      if (v === undefined || v === null || v === false) continue;
      if (Array.isArray(v) && v.length === 0) continue;
      if (typeof v === "string" && !v.trim()) continue;
      if (k === "children") {
        const kids = (v as Node[])
          .map((c, j) => cleanForExport(c, `${path}.${j}`, kidPaths))
          .filter(Boolean);
        if (kids.length) out.children = kids;
        continue;
      }
      // Перечисления — строчными; текст и шкалы (L, H2) не трогаем.
      if (LOWER_VALUE_KEYS.has(k) && typeof v === "string") {
        out[k] = v.toLowerCase();
        continue;
      }
      /*
        Иконка едет каноническим именем Lucide — строчными через дефис
        («file-text»), как на lucide.dev: разработчик заводит их у себя по
        ключу. Внутри дерева имя PascalCase, потому что это имя импорта.
      */
      if (k === "icon" && typeof v === "string") {
        out[k] = v.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();
        continue;
      }
      // Текст уезжает разработчику с тегами; служебные поля — как есть.
      if (TEXT_KEYS.has(k) && typeof v === "string") {
        /*
          Вопрос и разбор квиза — не одна фраза, а несколько абзацев, внутри
          которых бывают перечисления. Их размечаем блоками (<p>, <ul>), иначе
          пункты уехали бы разработчику символами «•» посреди текста.
        */
        out[k] = component === "Quiz" && BLOCK_TEXT_KEYS.has(k)
          ? mdBlocksToTags(v)
          : mdToTags(v);
        continue;
      }
      if (TEXT_ARRAY_KEYS.has(k) && Array.isArray(v)) {
        out[k] = (v as string[]).map(mdToTags);
        continue;
      }
      if (k === "rows" && Array.isArray(v)) {
        /*
          Ячейка с перечислением едет узлом — её чистим тем же обходом, что и
          всё остальное. Адрес ей не заводим: таблица выбирается на странице
          целиком, отдельных ячеек в выборе нет.
        */
        out[k] = (v as TableCellValue[][]).map((row, ri) =>
          row.map((c, ci) =>
            typeof c === "string" ? mdToTags(c) : cleanForExport(c, `${path}.${ri}.${ci}`),
          ),
        );
        continue;
      }
      // Варианты квиза — объекты {text, correct}: текст переводим в теги,
      // флаг верности оставляем как есть.
      if (k === "items" && Array.isArray(v)) {
        out[k] = (v as { text: string; correct?: boolean }[]).map((o) => ({
          ...o,
          text: mdToTags(o.text),
        }));
        continue;
      }
      out[k] = v;
    }
    sink?.push({ path, children: kidPaths });
    return LIST_HOSTS.has(component) ? hoistListFields(out) : out;
};

/*
  Выгрузка для разработчика: то же дерево, но без служебных пометок инструмента
  и без пустых полей. В JSON едет только контент — так решено, чтобы структура
  была чёткой и без мусора.
*/
export function toExport<T extends Node | SectionNode>(nodes: T[]): unknown[] {
  return nodes.map((n, i) => cleanForExport(n, String(i))).filter(Boolean);
}

/** Та же выгрузка плюс дерево адресов исходных узлов — для колонки JSON. */
export function toExportWithPaths<T extends Node | SectionNode>(
  nodes: T[],
): { nodes: unknown[]; paths: ExportPath[] } {
  const paths: ExportPath[] = [];
  return {
    nodes: nodes.map((n, i) => cleanForExport(n, String(i), paths)).filter(Boolean),
    paths,
  };
}

export function docToExport(doc: Doc) {
  return { module: doc.module, children: toExport(doc.children) };
}

/*
  РАССТАНОВКА ДИРЕКТИВ ПО ПОЗИЦИЯМ.

  Почему не по тексту: id блока считается от его текста и якоря раздела, а
  повторяющиеся строки («**Миф**», «**Пояснение**») стоят в каждом из девяти
  мифов ОДНОГО раздела — id у них совпадает. Если отдавать такой блок «первой
  попавшейся» директиве, группа рвётся: заголовок остаётся в одной группе,
  хвост мифа — в другой, и аккордеон собирается пустым, с одним вопросом.

  Поэтому директиву прикладываем к документу целиком: ищем непрерывный участок,
  где подряд идущие id совпадают с её списком блоков. Уникальные соседи
  однозначно пришпиливают участок к нужному месту.

  Два прохода: сначала директивы с ЕДИНСТВЕННЫМ возможным местом, потом
  остальные — жадно, в первое свободное. Так директива из одного повторяющегося
  блока (шесть «**Почему это важно**») не отбирает место у той, которой деваться
  некуда.
*/
export function placeDirectives(
  sections: Section[],
  pathname: string,
  moduleId: string,
  directives: Directive[],
): (si: number, bi: number) => Directive | undefined {
  const flat: { key: string; id: string }[] = [];
  sections.forEach((sec, si) =>
    sec.blocks.forEach((b, bi) =>
      flat.push({ key: `${si}:${bi}`, id: blockRefId(b, pathname, sec.anchor) }),
    ),
  );

  const mine = directives.filter((d) => d.module === moduleId && d.blocks.length);
  const taken = new Set<number>();
  const map = new Map<string, Directive>();

  const candidates = (ids: string[]) => {
    const out: number[] = [];
    for (let p = 0; p + ids.length <= flat.length; p++) {
      let ok = true;
      for (let k = 0; k < ids.length; k++)
        if (flat[p + k].id !== ids[k]) {
          ok = false;
          break;
        }
      if (ok) out.push(p);
    }
    return out;
  };

  const place = (d: Directive, p: number) => {
    for (let k = 0; k < d.blocks.length; k++) {
      taken.add(p + k);
      map.set(flat[p + k].key, d);
    }
  };

  const pending: { d: Directive; at: number[] }[] = [];
  for (const d of mine) {
    const at = candidates(d.blocks.map((b) => b.id));
    if (at.length === 1) place(d, at[0]);
    else if (at.length > 1) pending.push({ d, at });
  }
  for (const { d, at } of pending) {
    const free = at.find((p) => d.blocks.every((_, k) => !taken.has(p + k)));
    if (free !== undefined) place(d, free);
  }

  return (si, bi) => map.get(`${si}:${bi}`);
}
