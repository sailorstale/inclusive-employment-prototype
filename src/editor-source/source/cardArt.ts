/*
  КАРТИНКА И ИКОНКА КАРТОЧКИ ПО ЕЁ НАЗВАНИЮ.

  Две разные вещи, и путать их не надо.

  ИЛЛЮСТРАЦИЯ-СТИКЕР (image) — у карточек-ярлыков, которые повторяются по всему
  сайту. «Важно» встречается восемь раз, «Пример» — восемь. Это не тема, а РОЛЬ
  блока, и рисунок опознаётся раньше, чем прочитано слово: человек листает
  длинную страницу и по картинке понимает, что перед ним предупреждение или
  разбор случая. Рисунок обязан быть одинаковым у всех карточек одной роли,
  иначе читатель начнёт искать в нём смысл, которого нет.

  ИКОНКА (icon) — у наборов, где карточки идут рядом и правда про разное. Пять
  разделов ИПРА различаются по сути: условия, оборудование, виды труда,
  ограничения, график. Иконка помогает выхватить нужную глазами.

  Берём только иконки Lucide: другого набора в проекте нет (решение дизайнера
  5 августа 2026). Имена — как в public/figma/icons/.

  ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Карточки «Ментальная инвалидность» и «Физическая
  инвалидность» (двенадцать штук) и пять правил уважительного общения дизайнер
  решил оставить без иконок: подходящих рисунков в наборе нет, а приблизительная
  иконка сбивает с толку сильнее, чем её отсутствие.
*/

/** Название без хвостовой пунктуации и лишних пробелов. */
const bare = (t: string) => t.replace(/[*_]/g, "").replace(/[.:;!]+$/, "").trim();

/* Ярлык-роль → сюжет из набора Small Image. */
const IMAGE: Record<string, string> = {
  важно: "Важная информация",
  пример: "Пример",
};

/* Название карточки → имя иконки Lucide. Пять разделов ИПРА. */
const ICON: Record<string, string> = {
  "условия труда": "ShieldCheck",
  "оборудование рабочего места": "MonitorSmartphone",
  "доступные виды труда": "Accessibility",
  "ограничения по видам работ": "Ban",
  "особенности графика": "Clock",
};

/** Картинка и иконка, положенные карточке с таким названием. */
export function cardArt(title?: string): { icon?: string; image?: string } {
  if (!title) return {};
  const key = bare(title).toLowerCase();
  const image = IMAGE[key];
  const icon = ICON[key];
  return { ...(image ? { image } : {}), ...(icon ? { icon } : {}) };
}
