/*
  АДРЕС ЗАПИСИ ЗАМЕЧАНИЯ К СПРАВОЧНИКУ.

  Устроен как «адрес блока ## метка»: к одному месту документа замечаний может
  быть сколько угодно, поэтому одной привязки к блоку мало.

  Разделитель «##», а не «::», как у замечаний к страницам: адрес блока сам
  состоит из кусков через «::» (см. tools/bible/build.mjs), и по двоеточиям
  запись обратно не разобрать.
*/

const SEP = "##";

export const bibleCommentId = (blockId: string, uid: string) =>
  `${blockId}${SEP}${uid}`;

/** Адрес блока, к которому оставлено замечание. */
export const blockOf = (commentId: string) => commentId.split(SEP)[0] ?? "";

/** Метка записи: время в 36-й системе плюс случайный хвост. */
export const newUid = () =>
  `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`;
