/*
  АДРЕС ЗАПИСИ ЗАМЕЧАНИЯ К СПРАВОЧНИКУ.

  Устроен как «адреса блоков через плюс ## метка»: одно замечание нередко
  относится к нескольким кускам подряд — правилу и примеру под ним, строке
  таблицы и абзацу рядом. Так же устроены и замечания к страницам сайта
  (site/commentIds.ts), только там впереди ещё стоит адрес страницы.

  Метка в конце нужна потому, что к одному месту замечаний может быть сколько
  угодно: у второго замечания к тому же блоку адрес обязан отличаться.

  Разделитель «##», а не «::», как на сайте: адрес блока сам состоит из кусков
  через «::» (см. tools/bible/build.mjs), и по двоеточиям запись обратно не
  разобрать.
*/

const SEP = "##";
const JOIN = "+";

export const bibleCommentId = (blocks: string[], uid: string) =>
  `${blocks.join(JOIN)}${SEP}${uid}`;

/** Адреса блоков, к которым оставлено замечание. */
export const blocksOf = (commentId: string): string[] => {
  const head = commentId.split(SEP)[0] ?? "";
  return head ? head.split(JOIN).filter(Boolean) : [];
};

/** Метка записи: время в 36-й системе плюс случайный хвост. */
export const newUid = () =>
  `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`;
