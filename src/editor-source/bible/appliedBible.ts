/*
  ЖУРНАЛ РАЗБОРА ЗАМЕЧАНИЙ К СПРАВОЧНИКУ — что мы сделали по каждому замечанию
  разработчика.

  Устроено так же, как разбор замечаний клиента к страницам сайта
  (site/appliedComments.ts), и по той же причине. Само замечание лежит в данных
  на сервере: там его оставил разработчик, и эти данные мы не трогаем. А ответ
  на замечание — это правка в справочнике или в самой выгрузке, и записывать её
  надо рядом с ней, тем же коммитом.

  Отсюда правило: ЗАПИСЬ ПОЯВЛЯЕТСЯ ВМЕСТЕ С ПРАВКОЙ. Метка «учтено» в панели
  зажигается ровно тогда, когда правка выходит на боевой стенд. Раньше она
  соврала бы разработчику, что справочник уже изменился, а он открыл бы старый
  текст.

  ЧТО ИМЕННО МЕНЯЕТСЯ ПО ЗАМЕЧАНИЮ. Справочник описывает формат, по которому
  собирается выгрузка, поэтому замечание почти всегда затрагивает две вещи
  сразу: текст справочника и код, который этот формат создаёт. Поле `where`
  говорит, что именно тронули, чтобы разработчик понимал, изменилось ли только
  описание или уже и сам JSON.

  Тексты пишем ДЛЯ ЧЕЛОВЕКА: разработчик читает их в панели рядом со своим
  замечанием и должен понять, что произошло, не заглядывая в код.
*/

/** Что тронули по замечанию. */
export type AppliedWhere =
  /** Поправили только описание в справочнике, формат прежний. */
  | "текст"
  /** Изменился сам формат: правка в коде выгрузки, JSON поедет другой. */
  | "формат"
  /** И описание, и формат. */
  | "текст и формат";

export type AppliedBible = {
  /** id замечания в панели: «адреса блоков##метка». */
  id: string;
  /** Что сделали — одной фразой. */
  what: string;
  where: AppliedWhere;
  /** Как было в справочнике до правки. */
  before: string;
  /** Как стало. Пусто — кусок из справочника убран совсем. */
  after?: string;
  /** Когда внесли. Дата в формате ГГГГ-ММ-ДД. */
  date: string;
  /*
    ВТОРОЙ РАУНД. Разработчик прочитал наш разбор, не согласился и написал
    реплику в ветку под замечанием — значит, правим ещё раз, и на правку
    заводится ВТОРАЯ запись здесь, рядом с первой. Здесь пишем, сколько реплик
    она отвечает: у второй записи это 1, у третьей 2. Первая запись поле не
    заполняет. По нему панель понимает, ответили мы уже или разработчик ждёт.
  */
  answers?: number;
};

/*
  ЗАПИСЬ ЗАВОДИТСЯ НА КАЖДОЕ ЗАМЕЧАНИЕ, КОТОРОЕ МЫ ВНЕСЛИ. Внесли правку и не
  завели запись — замечание останется в панели «в работе», хотя оно давно
  сделано, и разработчик придёт спрашивать второй раз.

  Порядок работы, когда приходит просьба «внедри замечания»:

  1. Открыть панель на странице /bible и прочитать замечание целиком, вместе с
     веткой ответов.
  2. Внести правку — в справочник (src/docs/json-bible.md) и, если замечание про
     сам формат, в код выгрузки.
  3. Пересобрать справочник: npm run bible.
  4. Завести здесь запись тем же коммитом.

  Пока замечаний не разобрано, список пуст — и это честное состояние, а не
  забытый файл.
*/
const LOG: AppliedBible[] = [];

/** Все записи разбора по замечанию, по порядку появления. */
export function appliedFor(id: string): AppliedBible[] {
  return LOG.filter((r) => r.id === id);
}

/** Сколько реплик разработчика мы уже отработали правкой. */
export function answeredCount(id: string): number {
  return appliedFor(id).reduce((max, r) => Math.max(max, r.answers ?? 0), 0);
}
