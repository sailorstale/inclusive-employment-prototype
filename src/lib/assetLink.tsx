import * as React from "react";

/*
  КАРТИНКУ МОЖНО СКАЧАТЬ КЛИКОМ.

  Сайт собирают в конструкторе Яндекса, и все картинки — логотипы фондов,
  аватары авторов, портреты экспертов — разработчик заводит туда руками.
  Искать их по папкам репозитория неудобно, а просить у нас каждый файл
  отдельно — тем более. Поэтому любая такая картинка в прототипе сама себе
  ссылка на скачивание: клик — файл у разработчика.

  Атрибут download просит браузер сохранить файл, а не открыть его. Работает
  для своих же файлов (те, что лежат рядом с сайтом), а это ровно наш случай.

  Имя файла берём из адреса: «/figma/logos/orbifond.png» сохранится как
  «orbifond.png», а не как «загрузка.png».
*/

export function AssetLink({
  src,
  title,
  className,
  children,
}: {
  /** Адрес файла — он же адрес скачивания. */
  src: string;
  /** Подсказка при наведении; к ней дописываем «— скачать». */
  title?: string;
  className?: string;
  children: React.ReactNode;
}) {
  const name = src.split("/").pop() || "";
  return (
    <a
      href={src}
      download={name}
      title={[title, "скачать"].filter(Boolean).join(" — ")}
      /*
        Клик по картинке не должен вести себя как клик по блоку страницы: в
        инструменте сверки это выделило бы блок и открыло форму комментария.
      */
      onClick={(e) => e.stopPropagation()}
      className={className}
    >
      {children}
    </a>
  );
}
