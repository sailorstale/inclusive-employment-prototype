/*
  Слаг сюжета для выгрузки — имя файла без расширения.

  Незнакомое название возвращается как есть: молча подставить пустую строку
  значило бы стереть картинку у карточки, а увидеть это можно было бы только
  глазами в готовом файле. Русская строка посреди латинских слагов бросается в
  глаза сразу, и на неё же ругается проверка выгрузки (см. exportChecks).
*/
export function smallImageSlug(name: string): string {
  const file = SMALL_IMAGE_FILE[name as SmallImageName];
  return file ? file.replace(/\.[a-z0-9]+$/i, "") : name;
}

/** Все слаги набора — для проверки выгрузки. */
export const SMALL_IMAGE_SLUGS: string[] = Object.values(SMALL_IMAGE_FILE).map((f) =>
  f.replace(/\.[a-z0-9]+$/i, ""),
);
