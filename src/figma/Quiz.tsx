import * as React from "react";
import { cn } from "@/lib/utils";
import { Button } from "./Button";
import { QuizItems, type QuizItemState } from "./QuizItems";

/*
  Figma: component «Quiz» (6519:2040), Platform=Desktop (6519:1997).

  Блок самопроверки: заголовок темы, поясняющий текст, вопрос, варианты ответа
  с чекбоксами, кнопка «Проверить» и разбор результата. Ставится в слот
  Block (в шаблоне Quiz всегда внутри него), в другие компоненты
  не вкладывается. Внутрь принимает только Quiz Items и Button.

  Тексты внутри — НЕ инстансы Heading/Text: в Figma это собственные слои Quiz
  со стилями Desktop/H3, Body L, Body L Bold. Поэтому здесь ds-*-классы напрямую —
  иначе к зазору 16 приклеился бы ещё и верхний отступ Heading/Text.

  Наши расхождения с Figma, честно:
  1) В Figma у Quiz нет свойства «проверено / не проверено», а на макете видны
     сразу и нетронутые варианты, и заполненный разбор. Мы решили: до нажатия
     «Проверить» разбор скрыт. Вопрос дизайнеру открыт.
  2) Кнопки «Проверить» до выбора (disabled) и «Пройти заново» (Ghost) в Figma нет —
     наше добавление, иначе макет некликабельный. Сюда же «Сбросить»: после
     проверки та же кнопка возвращает квиз в исходное состояние. Это служебное
     действие для проверки квизов, в формат выгрузки оно не входит.
  3) (снято) Бейдж в блоке разбора когда-то добавили мы — убран по решению
     дизайнера. Теперь как в Figma: бейдж живёт только внутри строки ответа,
     а Feedback Container — обычный фрейм со счётом и разбором.
  4) Заголовок (title) сделали опциональным: в шаблоне он дословно повторяет вопрос,
     похоже на заглушку. Вопрос дизайнеру: заголовок и вопрос — разные тексты?

  Интерактив на локальном состоянии — это макет, на сервер ничего не уходит.
*/

export type QuizOption = {
  text: string;
  /** Верный ли вариант. Чекбоксы = множественный выбор, верных может быть несколько. */
  correct?: boolean;
  /** Разбор ИМЕННО этого варианта («почему верно / неверно»). Показывается после
   *  проверки под выбранными вариантами. Если задан хоть у одного — блок разбора
   *  собирается по вариантам, а не из общего explanation. */
  feedback?: string;
};

/*
  Вопрос, вводный абзац и разбор принимают не только строку, но и готовую
  разметку: в источнике это несколько абзацев, внутри которых бывают
  перечисления, и раскладка передаёт их настоящими абзацами и списком.
  Простая строка тоже работает — так их задают страницы-витрины.
*/
type Props = {
  /** Заголовок темы, H3. */
  title?: string;
  /** Вводный абзац, Body L. По смыслу опционален. */
  description?: React.ReactNode;
  /** Сам вопрос, Body L Bold. */
  question: React.ReactNode;
  items: QuizOption[];
  /*
    Сколько ответов можно выбрать. «single» — один: квадратов-чекбоксов нет,
    выбор делается кликом по строке, и новый выбор снимает прежний. «multiple» —
    несколько, с чекбоксами.

    Раскладка считает это по числу верных вариантов и кладёт в узел квиза, но
    до 5 августа 2026 сюда не передавала: любой квиз без разбора по вариантам
    вёл себя как множественный выбор, и в вопросе с одним ответом можно было
    отметить хоть все четыре строки. Не задано — оставляем прежнее поведение,
    чтобы страницы-витрины, которые зовут Quiz напрямую, не поехали.
  */
  mode?: "single" | "multiple";
  /** Текст разбора, Body M — показывается после проверки. */
  explanation?: React.ReactNode;
  className?: string;
};

export function Quiz({
  title,
  description,
  question,
  items,
  explanation,
  mode,
  className,
}: Props) {
  const questionId = React.useId();
  const [selected, setSelected] = React.useState<boolean[]>(() =>
    items.map(() => false),
  );
  const [checked, setChecked] = React.useState(false);

  /*
    Один ответ или несколько — считается по числу верных вариантов (см. mode).
    Не задано — как раньше, по наличию разбора на каждый вариант: страницы-
    витрины зовут Quiz напрямую и режим не передают.
  */
  const single = mode ? mode === "single" : items.some((i) => i.feedback);
  /*
    КНОПКА «ПРОВЕРИТЬ» ЕСТЬ ТОЛЬКО ТАМ, ГДЕ ВЕРНЫХ ВАРИАНТОВ НЕСКОЛЬКО (решение
    дизайнера 17 августа 2026). Смысл кнопки — сказать «я закончил выбирать»:
    пока вариантов можно отметить несколько, без неё непонятно, когда показывать
    разбор. При одном верном ответе выбор и есть окончание, и лишнее нажатие
    только отделяет вопрос от ответа.

    Отдельного поля у этого режима больше нет. До 17 августа 2026 в выгрузке
    ехал instant, но он называл лишь четыре квиза из шестнадцати, работавших без
    кнопки: остальные двенадцать прототип угадывал по наличию разбора у
    вариантов, и файл про них молчал.
  */
  const instant = single;
  // Есть ли что проверять: без верных вариантов это самопроверка (см. isJudged).
  const judged = isJudged(items);

  const toggle = (index: number, value: boolean) => {
    // Один ответ: выбираем только эту строку, прежний выбор снимаем.
    // Несколько — обычное переключение, иммутабельно.
    setSelected((prev) =>
      single
        ? prev.map((_, i) => i === index)
        : prev.map((v, i) => (i === index ? value : v)),
    );
  };

  const hasSelection = selected.some(Boolean);
  // Разбор виден: в мгновенном режиме — как только выбрали, иначе — по «Проверить».
  const revealed = instant ? hasSelection : checked;

  /*
    СБРОС — НАША СЛУЖЕБНАЯ КНОПКА, НЕ ЧАСТЬ ФОРМАТА (просьба Мити 16 августа
    2026). После «Проверить» квиз замирал навсегда: чтобы посмотреть, что он
    ответит на другой набор вариантов, приходилось перезагружать страницу. Это
    мешало проверять квизы, а их на сайте много.

    Поэтому та же кнопка после проверки становится «Сбросить» и возвращает квиз
    в исходное состояние. В ВЫГРУЗКУ ЭТО НЕ ПОПАДАЕТ: выгрузка описывает вопрос,
    варианты и разбор, а кнопок в ней нет вообще (см. json-bible.md, раздел про
    Quiz). Состояние живёт только здесь, в памяти страницы.
  */
  const reset = () => {
    setSelected(items.map(() => false));
    setChecked(false);
  };

  return (
    <div
      data-component="Quiz"
      className={cn(
        // Серая карточка: поля 24, скругление 24, зазор между частями 16.
        "flex w-full flex-col gap-[var(--space-m)]",
        "bg-[color:var(--card-bg-gray)] p-[var(--space-l)] rounded-[var(--radius-l)]",
        className,
      )}
    >
      {title ? (
        <h3 className="ds-h3 text-[color:var(--text-primary)]">{title}</h3>
      ) : null}
      {description ? (
        <div className="ds-body-l text-[color:var(--text-primary)]">
          {description}
        </div>
      ) : null}

      {/*
        Вопрос бывает из нескольких абзацев (сценарий-кейс + сам вопрос), и
        внутри бывает перечисление. Раскладка передаёт их готовой разметкой,
        поэтому обёртка — блок, а не абзац: абзац в абзаце недопустим.
        whitespace-pre-line оставлен для простой строки, которую передают
        страницы-витрины.
      */}
      {/* Вопроса может не быть: у квиза-темы («Зрение») он весь в заголовке.
          Пустой блок оставлял бы лишний зазор над вариантами. */}
      {question ? (
        <div
          id={questionId}
          className="ds-body-l-bold whitespace-pre-line text-[color:var(--text-primary)]"
        >
          {question}
        </div>
      ) : null}

      {/* Options Container: стопка вариантов с зазором 4 — плотно, как единый список. */}
      <div
        role="group"
        aria-labelledby={questionId}
        className="flex w-full flex-col gap-[var(--space-2xs)]"
      >
        {items.map((item, index) => (
          <QuizItems
            // Список статичен и не переупорядочивается — индекс как ключ безопасен
            // и не ломается, если два варианта совпали текстом.
            key={index}
            state={revealed ? itemState(item, judged) : "Default"}
            checked={selected[index]}
            // В мгновенном режиме варианты остаются кликабельными — можно
            // попробовать другой ответ. В обычном — после «Проверить» замирают.
            disabled={instant ? false : checked}
            /*
              Один ответ → кружок-радио, несколько → квадрат-чекбокс. Просьба
              Мити 16 августа 2026. Раньше в квизе с одним ответом отметки не
              было вовсе, и до первого клика читатель не понимал, что строки
              вообще выбираются. Форма отметки заодно говорит правило: квадрат
              — «отметьте всё подходящее», кружок — «выберите один».
            */
            radio={single}
            name={single ? questionId : undefined}
            onCheckedChange={(value) => toggle(index, value)}
          >
            {item.text}
          </QuizItems>
        ))}
      </div>

      {/* Кнопка «Проверить» — только в обычном режиме. После проверки она же
          работает сбросом (см. reset выше). «Пройти заново» убрана совсем:
          смысла в ней нет. */}
      {!instant ? (
        <div className="flex items-center gap-[var(--space-xs)]">
          <Button
            /* Сброс — служебное действие, поэтому кнопка тише основной. Не
               Secondary: её фон в точности совпадает с фоном карточки квиза, и
               кнопка пропадает. Outline держит контур и остаётся видимой. */
            type={checked ? "Outline" : "Primary"}
            size="M"
            disabled={!hasSelection}
            onClick={checked ? reset : () => setChecked(true)}
          >
            {checked ? "Сбросить" : "Проверить"}
          </Button>
        </div>
      ) : hasSelection ? (
        /* Мгновенный квиз кнопки «Проверить» не имеет, но сбросить его тоже
           нужно: иначе вернуться к нетронутым вариантам можно только
           перезагрузкой страницы. Появляется после первого выбора. */
        <div className="flex items-center gap-[var(--space-xs)]">
          <Button type="Outline" size="M" onClick={reset}>
            Сбросить
          </Button>
        </div>
      ) : null}

      {revealed ? (
        <Feedback
          items={items}
          selected={selected}
          explanation={explanation}
          /*
            ВЕРДИКТ ПОКАЗЫВАЕМ ВСЕГДА, где есть что судить (решение дизайнера
            17 августа 2026). Раньше строка зависела от двух вещей сразу: от
            режима квиза и от списка страниц, который мы вели руками. Получалось,
            что одно и то же слово в одном месте есть, в другом нет, и по файлу
            понять это было нельзя.

            Теперь условие одно: у квиза есть верные варианты. Само слово
            считается по выбору читателя — см. verdict ниже, — и отдельного поля
            в выгрузке ему не нужно.
          */
          showScore={judged}
        />
      ) : null}
    </div>
  );
}

/*
  Как красим строку после проверки (в Figma это не задано — наше решение):
  верный → Correct (зелёный), неверный → Incorrect (красный). Отметил читатель
  строку или нет, на цвет не влияет.

  ВЕРНЫЙ ВАРИАНТ ЗЕЛЁНЫЙ, ОТМЕТИЛИ ЕГО ИЛИ НЕТ — замечание Мити от 12 августа
  2026 по квизу на «Как устроен наём»: «надо чтобы у правильных ответов был не
  жёлтый, а зелёный цвет».

  Раньше пропущенный верный вариант красился жёлтым (состояние Partly). Смысл
  был в оттенке «тут тоже надо было», но читателю он ничего не объяснял: подпись
  на плашке и так уже говорила «Верно», а два разных цвета у двух верных строк
  подряд читались как разная степень правоты. Теперь цвет отвечает на один
  вопрос — верен вариант или нет.

  НЕВЕРНЫЙ ВАРИАНТ ТОЖЕ КРАСИТСЯ ВСЕГДА — замечание Мити от 16 августа 2026:
  «не все ответы подсвечиваются как верные и неверные». Пропущенная неверная
  строка оставалась белой и без плашки, и разбор выходил половинчатым: про
  верные варианты читатель узнавал всё, а про часть неверных — ничего. Правило
  теперь одно на обе стороны: после проверки у каждой строки написано, верна
  она или нет.

  Состояние Partly у компонента осталось: оно есть в наборе Figma и показано на
  витрине /figma. Просто раскладка его больше не выдаёт.
*/
function itemState(item: QuizOption, judged: boolean): QuizItemState {
  // Самопроверка без верного ответа: красить нечего, ошибки тут не бывает.
  if (!judged) return "Default";
  return item.correct ? "Correct" : "Incorrect";
}

/*
  САМОПРОВЕРКА БЕЗ ВЕРНОГО ОТВЕТА. В квизе может не быть ни одного верного
  варианта — например, «сколько потенциальных участников программы вы видите
  сейчас?». Человек описывает свою ситуацию, а не угадывает, и вердикт ему не
  положен: раньше такой квиз на любой ответ отвечал «Неверно» и красил строку
  красным. Узнаём такие квизы по отсутствию верных вариантов и просто
  показываем разбор.
*/
const isJudged = (items: QuizOption[]) => items.some((i) => i.correct);

/*
  Feedback Container: белая карточка, поля 24, скругление 16, зазор 8.
  В Figma это обычный фрейм внутри Quiz, а не отдельный компонент —
  поэтому data-component здесь не ставим, шильдика в Figma для него нет.
*/
function Feedback({
  items,
  selected,
  explanation,
  showScore,
}: {
  items: QuizOption[];
  selected: boolean[];
  explanation?: React.ReactNode;
  /** Показывать строку-вердикт («Верно» / «Частично верно» / «Неверно»). */
  showScore: boolean;
}) {
  const totalCorrect = items.filter((i) => i.correct).length;
  const hits = items.filter((i, n) => i.correct && selected[n]).length;
  const misses = items.filter((i, n) => !i.correct && selected[n]).length;
  /*
    Вердикт словом, без счёта. Цифры («Верно 1 из 2») читателя не учат: он и
    так видит по цвету строк, где ошибся, а «1 из 0» на квизе без единого
    верного варианта выглядело просто сломанным. Решение дизайнера.

    ПРАВИЛО СЧЁТА — оно же договорённость с разработчиком (17 августа 2026).
    Отметил все верные и ни одного неверного — «Верно». Не отметил ни одного
    верного — «Неверно». Всё остальное — «Частично верно»: и смесь верного с
    неверным, и случай, когда верных в квизе несколько, а выбран только один.

    Слово вычисляется здесь, а в выгрузку не едет: разработчику для того же
    подсчёта хватает пометок correct у вариантов и того, что выбрал читатель.
  */
  const verdict =
    hits === totalCorrect && misses === 0
      ? "Верно"
      : hits === 0
        ? "Неверно"
        : "Частично верно";
  /*
    РАЗБОР ПОКАЗЫВАЕМ ЦЕЛИКОМ — и по выбранному варианту, и общий.

    Раньше эти две части считались взаимоисключающими: есть разбор у вариантов —
    общий не показывался вовсе. Для формата «ОС на каждый ответ» это верно, там
    общего разбора и нет. А в ситуационных квизах Модуля 4 есть оба, и общий
    пропадал молча.

    Клиент это заметил и описал точно: «тут потеряна обратная связь вообще, а
    вместо неё — пояснение к одному из вариантов». В источнике под каждой
    ситуацией стоит и пояснение к варианту, и абзац «Обратная связь», который
    объясняет, чья это зона ответственности и почему. Именно он и был главным.

    Теперь показываем обе части подряд: сначала разбор варианта, потом общий.

    И ещё одно, из того же замечания: «второе пояснение тоже потеряно». Когда у
    квиза есть общий разбор, пояснения вариантов ОПИСЫВАЮТ стороны («HR
    связывается с Мариной…», «Куратор заранее обсуждает…»), а не судят ответ —
    судит как раз общий разбор. Читателю нужны оба описания, поэтому показываем
    их все, а не только выбранное.

    Там, где общего разбора нет, всё остаётся как было: пояснение варианта там
    и есть вердикт («Верно, потому что…»), и показывать чужое рано.
  */
  const chosen = items
    .map((it, n) => ({ it, n }))
    .filter(({ it, n }) => (explanation ? Boolean(it.feedback) : selected[n] && it.feedback));

  return (
    <div
      className={cn(
        "flex w-full flex-col gap-[var(--space-xs)]",
        "bg-[color:var(--card-bg-white)] p-[var(--space-l)] rounded-[var(--radius-m)]",
      )}
      aria-live="polite"
    >
      {showScore ? (
        <p className="ds-h5 text-[color:var(--text-primary)]">{verdict}</p>
      ) : null}
      {chosen.map(({ it, n }) => (
        <p key={n} className="ds-body-m text-[color:var(--text-primary)]">
          {it.feedback}
        </p>
      ))}
      {explanation ? (
        /* Блок, а не абзац: разбор приходит готовой разметкой из абзацев
           и списка (см. вопрос выше). */
        <div className="ds-body-m text-[color:var(--text-primary)]">
          {explanation}
        </div>
      ) : null}
    </div>
  );
}
